// Scaffolds a complete, working tool with its test file and both catalog
// registrations.
//
// The generated tool is not a stub: it opens, renders, consumes runtime
// snapshots, translates, survives a language change, and comes with a test
// file that passes. Starting from something that already works means the first
// thing a contributor does is change behaviour, not fight the plumbing.
//
// Usage:
//   node scripts/new-tool.mjs --id my-tool --label "My Tool"
//   node scripts/new-tool.mjs --id my-tool --label "My Tool" --dry-run

import { lstat, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function argument(name, fallback = null) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? fallback : process.argv[index + 1];
}

function toCamel(id) {
  return id.replace(/-([a-z])/g, (_unused, letter) => letter.toUpperCase());
}

function toPascal(id) {
  const camel = toCamel(id);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

async function exists(path) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
    return false;
  }
}

async function isRegularFile(path) {
  try {
    const info = await lstat(path);
    return info.isFile() && !info.isSymbolicLink();
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

function oneLineComment(value) {
  return String(value).replace(/[\r\n\u2028\u2029]+/g, " ");
}

function toolSource(id, label) {
  const pascal = toPascal(id);
  const camel = toCamel(id);
  const labelLiteral = JSON.stringify(String(label));
  return `// ${oneLineComment(label)}
//
// Generated by scripts/new-tool.mjs. Read docs/tool-api.md alongside it.
//
// The pure part is exported as Mars${pascal}Core so it can be tested without a
// DOM; the tool itself only renders what that core computes. Keeping the two
// apart is what makes a tool testable in Node.
((rootScope) => {
  const root = rootScope || (typeof window !== "undefined" ? window : globalThis);

  // --- pure core, no DOM ----------------------------------------------------

  // Replace this with whatever your tool actually computes from a snapshot.
  function summarize(snapshot) {
    if (!snapshot || snapshot.assembled !== true) {
      return { assembled: false, instructions: 0, steps: 0, pcHex: "" };
    }
    return {
      assembled: true,
      instructions: Array.isArray(snapshot.textRows) ? snapshot.textRows.length : 0,
      steps: Number(snapshot.steps) || 0,
      pcHex: String(snapshot.pcHex || "")
    };
  }

  const coreApi = Object.freeze({ summarize });
  root.Mars${pascal}Core = coreApi;

  // --- browser tool ---------------------------------------------------------

  const host = root.MarsWebTools;
  if (!host || typeof host.register !== "function" || typeof document === "undefined") return;

  const STYLE_ID = "mars-web-tool-${id}-style";
  if (!document.getElementById(STYLE_ID)) {
    const style = document.createElement("style");
    style.id = STYLE_ID;
    // Colours come from the theme tokens; a literal colour fails the release
    // checks. Mobile rules are scoped to .desktop-stacked.
    style.textContent = \`
      .${id}-tool { height:100%; min-height:0; box-sizing:border-box; padding:8px; display:flex; flex-direction:column; gap:8px; color:var(--text); font:12px "Segoe UI",Tahoma,sans-serif; }
      .${id}-toolbar { display:flex; align-items:center; gap:6px; flex-wrap:wrap; }
      .${id}-status { margin:0; min-height:18px; color:var(--text-muted); }
      .${id}-body { flex:1; min-height:60px; overflow:auto; border:1px solid var(--line); background:var(--surface); padding:8px; }
      .${id}-metric { border:1px solid var(--line); background:var(--surface-raised); padding:6px 8px; }
      .${id}-metric strong { display:block; font-size:16px; color:var(--accent-strong); font-family:Consolas,monospace; }
      .desktop-stacked .${id}-toolbar { flex-wrap:nowrap; overflow-x:auto; }
      .desktop-stacked .${id}-toolbar > * { flex:0 0 auto; }
    \`;
    document.head.appendChild(style);
  }

  function t(message, params = {}) {
    const i18n = typeof window !== "undefined" ? window.WebMarsI18n : globalThis.WebMarsI18n;
    if (i18n && typeof i18n.t === "function") return i18n.t(message, params);
    return String(message).replace(/\\{([a-zA-Z0-9_]+)\\}/g, (_unused, key) => String(params[key] ?? ""));
  }

  function subscribeLanguageChange(listener) {
    const i18n = typeof window !== "undefined" ? window.WebMarsI18n : globalThis.WebMarsI18n;
    if (!i18n || typeof i18n.subscribe !== "function" || typeof listener !== "function") return () => {};
    return i18n.subscribe(listener);
  }

  host.register({
    id: "${id}",
    label: ${labelLiteral},
    create(ctx) {
      // createToolWindowShell escapes its title before placing it in HTML; the
      // generated source still uses a proper JS literal so quotes and control
      // characters in the label cannot break this file.
      const shell = ctx.createToolWindowShell("${id}", ${labelLiteral}, 520, 380, \`
        <div class="${id}-tool">
          <div class="${id}-toolbar">
            <button class="tool-btn" data-${camel}="refresh" type="button">Refresh</button>
            <button class="tool-btn" data-${camel}="close" type="button">Close</button>
          </div>
          <p class="${id}-status" data-${camel}="status"></p>
          <div class="${id}-metric">Instructions<strong data-${camel}="instructions">0</strong></div>
          <div class="${id}-body" data-${camel}="body"></div>
        </div>
      \`);

      const rootElement = shell.root;
      const statusNode = rootElement.querySelector("[data-${camel}='status']");
      const bodyNode = rootElement.querySelector("[data-${camel}='body']");
      const instructionsNode = rootElement.querySelector("[data-${camel}='instructions']");

      // State lives in the closure: create() runs once, so it survives every
      // close and reopen of the window.
      let latestSnapshot = null;

      function render() {
        const summary = coreApi.summarize(latestSnapshot);
        instructionsNode.textContent = String(summary.instructions);
        statusNode.textContent = summary.assembled
          ? t("Step {steps}, PC {pc}.", { steps: summary.steps, pc: summary.pcHex })
          : t("Assemble a program to see it here.");
        bodyNode.textContent = summary.assembled
          ? t("{count} instructions assembled.", { count: summary.instructions })
          : "";
      }

      rootElement.querySelector("[data-${camel}='refresh']").addEventListener("click", render);
      rootElement.querySelector("[data-${camel}='close']").addEventListener("click", shell.close);

      subscribeLanguageChange(() => {
        shell.refreshTranslations?.();
        render();
      });
      render();

      return {
        root: rootElement,
        // No connect control, so the tool always wants updates. Returning false
        // would deliver one snapshot at creation and nothing afterwards.
        isConnected: () => true,
        open() {
          shell.open();
          render();
        },
        close: shell.close,
        onSnapshot(snapshot, delivery = {}) {
          latestSnapshot = snapshot;
          // Render once per batch, not once per snapshot.
          if (delivery.batched === true && delivery.isLast !== true) return;
          render();
        }
      };
    }
  });
})(typeof window !== "undefined" ? window : globalThis);
`;
}

function testSource(id, label) {
  const pascal = toPascal(id);
  return `// Tests for the ${oneLineComment(label)} tool.
//
// The core is exercised directly, with no DOM; the browser half is checked by
// asserting the contracts docs/tool-api.md states, the same way
// tests/tool-api-contract.test.mjs does for the worked example.

import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import vm from "node:vm";
import { resolve } from "node:path";
import { projectRoot } from "./helpers/engines.mjs";

const toolPath = resolve(projectRoot, "tools/${id}.js");
const source = await readFile(toolPath, "utf8");

function loadCore() {
  const context = vm.createContext({});
  // The filename lets V8 coverage attribute this to the real file.
  vm.runInContext(source, context, { filename: "tools/${id}.js" });
  assert.ok(context.Mars${pascal}Core, "the tool must expose a DOM-free core");
  return context.Mars${pascal}Core;
}

test("the core summarises an assembled snapshot", () => {
  const core = loadCore();
  const summary = core.summarize({
    assembled: true,
    steps: 12,
    pcHex: "0x00400010",
    textRows: [{}, {}, {}]
  });

  assert.equal(summary.assembled, true);
  assert.equal(summary.instructions, 3);
  assert.equal(summary.steps, 12);
  assert.equal(summary.pcHex, "0x00400010");
});

test("the core tolerates an absent or unassembled snapshot", () => {
  const core = loadCore();
  [null, undefined, {}, { assembled: false }].forEach((snapshot) => {
    const summary = core.summarize(snapshot);
    assert.equal(summary.assembled, false);
    assert.equal(summary.instructions, 0);
  });
});

test("the tool follows the documented API contracts", () => {
  // A tool with no connect control must stay subscribed to runtime updates.
  assert.match(source, /isConnected: \\(\\) => true/);
  // Styles injected once, through theme tokens, with a mobile scope.
  assert.match(source, /document\\.getElementById\\(STYLE_ID\\)/);
  assert.match(source, /var\\(--surface\\)/);
  assert.match(source, /\\.desktop-stacked \\.${id}-toolbar/);
  assert.doesNotMatch(source, /#[0-9a-fA-F]{6}/, "no literal colours");
  // Language changes re-render.
  assert.match(source, /subscribeLanguageChange\\(/);
  // Batched delivery renders once.
  assert.match(source, /delivery\\.batched === true && delivery\\.isLast !== true/);
});

test("the tool is registered in both catalogs", async () => {
  const manifest = JSON.parse((await readFile(resolve(projectRoot, "tools/tools.json"), "utf8")).replace(/^\\ufeff/, ""));
  const manager = await readFile(resolve(projectRoot, "assets/js/app-modules/12-ui-tool-manager.js"), "utf8");

  assert.ok(manifest.tools.some((tool) => tool.id === "${id}"), "missing from tools/tools.json");
  assert.ok(manager.includes('id: "${id}"'), "missing from the fallback catalog");
});
`;
}


async function writeScaffoldTransaction(operations) {
  const attempted = [];
  let active = null;
  try {
    for (const operation of operations) {
      active = operation;
      attempted.push(operation);
      if (operation.create) {
        await writeFile(operation.path, operation.next, { encoding: "utf8", flag: "wx" });
      } else {
        await writeFile(operation.path, operation.next, "utf8");
      }
      operation.applied = true;
      active = null;
    }
  } catch (error) {
    const rollbackErrors = [];
    for (const operation of attempted.reverse()) {
      try {
        if (operation.create) {
          // EEXIST means another process won the race after validation; its file
          // is not ours to remove. Any other failed create may have left a
          // partial file behind and is safe to clean up because it was absent
          // when the transaction started.
          if (operation.applied || operation !== active || error?.code !== "EEXIST") {
            await rm(operation.path, { force: true });
          }
        } else {
          await writeFile(operation.path, operation.original, "utf8");
        }
      } catch (rollbackError) {
        rollbackErrors.push(rollbackError);
      }
    }
    if (rollbackErrors.length) {
      throw new AggregateError(
        [error, ...rollbackErrors],
        `Scaffold creation failed and ${rollbackErrors.length} rollback operation(s) also failed.`
      );
    }
    throw error;
  }
}

async function main() {
  const id = argument("id");
  const label = argument("label");
  const dryRun = process.argv.includes("--dry-run");

  if (!id || !label) {
    process.stderr.write('Usage: node scripts/new-tool.mjs --id my-tool --label "My Tool"\n');
    process.exitCode = 1;
    return;
  }
  if (!/^[a-z][a-z0-9-]*$/.test(id)) {
    process.stderr.write(`Invalid id '${id}': use lowercase letters, digits and hyphens.\n`);
    process.exitCode = 1;
    return;
  }

  const toolPath = resolve(projectRoot, `tools/${id}.js`);
  const testPath = resolve(projectRoot, `tests/tool-${id}.test.mjs`);
  const collisions = [];
  if (await exists(toolPath)) collisions.push(`tools/${id}.js`);
  if (await exists(testPath)) collisions.push(`tests/tool-${id}.test.mjs`);
  if (collisions.length) {
    process.stderr.write(`${collisions.join(" and ")} already exist${collisions.length === 1 ? "s" : ""}; refusing to overwrite existing work.\n`);
    process.exitCode = 1;
    return;
  }

  const manifestPath = resolve(projectRoot, "tools/tools.json");
  const managerPath = resolve(projectRoot, "assets/js/app-modules/12-ui-tool-manager.js");
  const invalidCatalogTargets = [];
  if (!(await isRegularFile(manifestPath))) invalidCatalogTargets.push("tools/tools.json");
  if (!(await isRegularFile(managerPath))) invalidCatalogTargets.push("assets/js/app-modules/12-ui-tool-manager.js");
  if (invalidCatalogTargets.length) {
    process.stderr.write(`${invalidCatalogTargets.join(" and ")} must be regular, non-symlink files before scaffolding.\n`);
    process.exitCode = 1;
    return;
  }
  const manifestText = await readFile(manifestPath, "utf8");
  const managerText = await readFile(managerPath, "utf8");
  let manifest;
  try {
    manifest = JSON.parse(manifestText.replace(/^\uFEFF/, ""));
  } catch (error) {
    process.stderr.write(`tools/tools.json is invalid JSON: ${error.message}\n`);
    process.exitCode = 1;
    return;
  }
  if (!Array.isArray(manifest.tools)) {
    process.stderr.write("tools/tools.json has no tools array.\n");
    process.exitCode = 1;
    return;
  }
  const scriptPath = `./tools/${id}.js`;
  if (manifest.tools.some((tool) => tool?.id === id || tool?.script === scriptPath)) {
    process.stderr.write(`tools/tools.json already registers '${id}' or '${scriptPath}'; refusing to duplicate it.\n`);
    process.exitCode = 1;
    return;
  }
  if (managerText.includes(`id: "${id}"`) || managerText.includes(`script: "${scriptPath}"`)) {
    process.stderr.write(`The fallback catalog already registers '${id}' or '${scriptPath}'; refusing to duplicate it.\n`);
    process.exitCode = 1;
    return;
  }

  // Match the manifest's existing layout rather than reserialising it, so the
  // diff stays to the added entry.
  const anchor = manifestText.match(/\n(\s+)\{\n\s+"label":/);
  const indent = anchor ? anchor[1] : "                  ";
  const labelLiteral = JSON.stringify(String(label));
  const entry = `${indent}{\n${indent}    "label":  ${labelLiteral},\n${indent}    "script":  "${scriptPath}",\n${indent}    "id":  "${id}"\n${indent}},\n`;
  const firstEntry = manifestText.indexOf(`${indent}{`);
  if (firstEntry === -1) {
    process.stderr.write("Could not find the tools array entries in tools/tools.json.\n");
    process.exitCode = 1;
    return;
  }
  const newManifest = manifestText.slice(0, firstEntry) + entry + manifestText.slice(firstEntry);

  const managerAnchor = /(\n\s+\{ id: "[a-z-]+", label: ".*", script: "\.\/tools\/[a-z-]+\.js" \},)/.exec(managerText);
  if (!managerAnchor) {
    process.stderr.write("Could not find the fallback catalog in the tool manager.\n");
    process.exitCode = 1;
    return;
  }
  const managerLine = `\n    { id: "${id}", label: ${labelLiteral}, script: "${scriptPath}" },`;
  const newManager = managerText.replace(managerAnchor[1], `${managerLine}${managerAnchor[1]}`);

  if (dryRun) {
    process.stdout.write(`Would create tools/${id}.js and tests/tool-${id}.test.mjs, and register "${label}" in both catalogs.\n`);
    return;
  }

  await writeScaffoldTransaction([
    { path: toolPath, next: toolSource(id, label), create: true },
    { path: testPath, next: testSource(id, label), create: true },
    { path: manifestPath, next: newManifest, original: manifestText, create: false },
    { path: managerPath, next: newManager, original: managerText, create: false }
  ]);

  process.stdout.write(`Created tools/${id}.js\n`);
  process.stdout.write(`Created tests/tool-${id}.test.mjs\n`);
  process.stdout.write("Registered in tools/tools.json and the fallback catalog.\n\n");
  process.stdout.write("Next:\n");
  process.stdout.write(`  1. Add the new strings to assets/js/i18n/en.js, then es.js and pt.js by hand.\n`);
  process.stdout.write(`  2. Add tests/tool-${id}.test.mjs to the "test" script in package.json.\n`);
  process.stdout.write(`  3. node --test tests/tool-${id}.test.mjs\n`);
  process.stdout.write(`  4. npm start, then open Tools -> ${label}.\n`);
  process.stdout.write("\nRead docs/tool-api.md before changing the generated contracts.\n");
}

await main();
