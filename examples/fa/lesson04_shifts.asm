# 04 - شیفت و توان دو
#
# یک جابجایی به چپ در 3 در 8 ضرب می شود که نتیجه مناسب باشد. بیت هایی که از لبه جابه جا شده اند
# دور ریخته می شوند.
#
# در سمت راست، `srl` با صفر پر می‌شود و `sra` بیت علامت را کپی می‌کند. برای 16- که 2 جابجا شده
# است، به ترتیب انتظار 1073741820 و -4 را داشته باشید.
#
# -15 را با `sra` امتحان کنید. نتیجه -4 است زیرا شیفت به سمت پایین می رود. راندهای تقسیم به سمت
# صفر را امضا کردند.

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #سه شیفت سمت چپ در 2^3 ضرب می شود در حالی که تنها 32 بیت نتیجه را حفظ می کند.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #$t3 و $t4 را در هگزادسیمال مقایسه کنید تا بیت‌های ورودی مختلف را ببینید.
        sra  $t3, $t2, 2        #علامت حفظ شده: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #صفرهای جابجا شده به: مثبت بزرگ
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
