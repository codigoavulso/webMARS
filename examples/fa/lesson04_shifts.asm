# ==========================================================
#درس 04 - جابجایی یا ضرب با سیم
#
#THE PROBLEM
#یک ضرب کننده عمومی یکی از گران ترین بلوک ها است
#یک مسیر داده ضرب در 8 نباید آنقدر هزینه داشته باشد.
#
#WHAT THE HARDWARE DOES
#یک شیفت اصلاً حسابی نیست: همان بیت های خوانده شده است
#از سیم های مختلف جابجایی به چپ توسط n در 2^n ضرب می شود
#و فقط هزینه مسیریابی دارد.
#
#THE SOLUTION
#قدرت های دو تبدیل به شیفت می شوند. به دو شیفت سمت راست توجه کنید: srl
#صفرها را در بالا وارد می کند، sra بیت علامت را کپی می کند، بنابراین فقط
#sra یک عدد منفی را به درستی تقسیم می کند.
#
#WATCH FOR
#-16 >> 2 با sra -4 می دهد اما با srl یک مثبت بزرگ است. را
#بیت ها به طور یکسان حرکت کردند. فقط آنچه در بالا وارد شده است متفاوت است.
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #سه شیفت سمت چپ در 2^3 ضرب می شود در حالی که تنها 32 بیت نتیجه را حفظ می کند.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #$t3 و $t4 را در هگزادسیمال مقایسه کنید تا بیت‌های ورودی مختلف را ببینید.
        sra  $t3, $t2, 2        #علامت حفظ شده: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #صفرهای جابجا شده به: مثبت بزرگ
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
