# 07 - کلمات در حافظه
#
# آدرس های حافظه بایت شمارش می کنند. هر کلمه چهار بایت را اشغال می کند، بنابراین `lw` و `sw` در
# اینجا از آفست 0، 4 و 8 استفاده می کنند.
#
# یک آدرس کلمه باید مضرب چهار باشد. استفاده از افست 1 به جای 4 باعث استثنای تراز در این برنامه
# می شود.
#
# بعد از فروشگاه‌ها، به `cell` در بخش داده نگاه کنید. سه کلمه مجاور باید شامل 111، 222 و 333
# باشد.

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #آدرس پایه

        #هر افست زیر نسبت به $t0 است و به صورت کلمه تراز می ماند.
        li   $t1, 111
        sw   $t1, 0($t0)        #اولین کلمه
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بایت = کلمه بعدی
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بایت

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw همان مقادیر 32 بیتی را که قبلا توسط sw نوشته شده بود بازسازی می کند.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
