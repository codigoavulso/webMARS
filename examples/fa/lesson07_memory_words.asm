# ==========================================================
#درس 07 - کلمات در حافظه، و چرا آدرس ها چهار تا می شوند
#
#THE PROBLEM
#حافظه هر بار یک بایت آدرس دهی می شود، اما یک ثبات نگه می دارد
#چهار بایت یک آدرس در واقع چه چیزی را انتخاب می کند؟
#
#WHAT THE HARDWARE DOES
#lw و sw چهار بایت در یک دسترسی حرکت می کنند، بنابراین متوالی
#کلمات با چهار آدرس فاصله دارند. دو بیت پایین از
#آدرس باید صفر باشد: این تراز چیزی است که به آن اجازه می دهد
#سخت افزار یک کلمه کامل را در یک چرخه واکشی می کند.
#
#THE SOLUTION
#حساب آدرس در بایت انجام می شود، بنابراین فهرست به کلمات
#همیشه با چهار مقیاس بندی می شود.
#
#WATCH FOR
#اسمبل کنید، سپس بخش داده را در 0x10010000 باز کنید. را
#سه مقدار در ستون های مجاور یک ردیف ظاهر می شود.
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #آدرس پایه

        #هر افست زیر نسبت به $t0 است و به صورت کلمه تراز می ماند.
        li   $t1, 111
        sw   $t1, 0($t0)        #اولین کلمه
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بایت = کلمه بعدی
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بایت

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw همان مقادیر 32 بیتی را که قبلا توسط sw نوشته شده بود بازسازی می کند.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
