#درس 06 - شمارنده، در نرم افزار و سخت افزار
#
#THE PROBLEM
#شمارنده سخت افزاری یک رجیستر، یک افزایش دهنده و یک است
#مقایسه کننده همان دستگاه به چه شکل نوشته شده است
#به عنوان دستورالعمل؟
#
#WHAT THE HARDWARE DOES
#دقیقاً آن سه بخش، یکی در هر دستورالعمل: ثبت نام
#شمارش را نگه می دارد، addi افزایش دهنده است، slt با یک شاخه
#مقایسه کننده ای است که در مورد دور دیگری تصمیم می گیرد.
#
#THE SOLUTION
#حلقه مفهوم جدیدی نیست. این منطق ترتیبی نوشته شده است
#بیرون، با کامپیوتر به عنوان ساعت.
#
#WATCH FOR
#$t0 ثبت تعداد و $t1 حد است. گام بردارید
#یک دور کامل و نام گذاری کنید که کدام خط کدام قسمت است.
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #ثبت شمارش
        li   $t1, 11            #حد

loop:
        #ثابت حلقه: $t0 مقدار بعدی برای چاپ است و در زیر $t1 باقی می‌ماند.
        slt  $t2, $t0, $t1      #مقایسه کننده
        beq  $t2, $zero, endl   #وقتی تعداد به حد مجاز رسید از آن خارج شوید

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #به روز رسانی شمارنده قبل از پرش، پیشرفت به سمت خاتمه را تضمین می کند.
        addi $t0, $t0, 1        #جمع کننده
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
