# 06 - حلقه به عنوان شمارنده
#
# `$t0` عدد بعدی برای چاپ است. `$t1` حد بالایی انحصاری است، بنابراین محدودیت 11 عدد 1 تا 10 را
# چاپ می کند.
#
# مقایسه قبل از هر تکرار انجام می شود. افزایش به سمت حد پیشرفت می کند و پرش چک را تکرار می کند.
#
# حد را به 1 تغییر دهید و اجرا کنید. شاخه خروج قبل از اولین چاپ گرفته می شود.

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #ثبت شمارش
        li   $t1, 11            #حد

loop:
        # در آزمون حلقه، $t0 نامزد بعدی است. فقط در صورتی چاپ کنید که زیر $t1 باشد.
        slt  $t2, $t0, $t1      #مقایسه کننده
        beq  $t2, $zero, endl   #وقتی تعداد به حد مجاز رسید از آن خارج شوید

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #به روز رسانی شمارنده قبل از پرش، پیشرفت به سمت خاتمه را تضمین می کند.
        addi $t0, $t0, 1        #جمع کننده
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
