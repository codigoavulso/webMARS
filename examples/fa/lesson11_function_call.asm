# 11 - فراخوانی یک تابع
#
# با انشعاب تاخیری اجرا کنید. `jal` به تابع می‌پرد و آدرس دستور بعدی را در `$ra` قرار می‌دهد.
#
# کنوانسیون فراخوان از 17 و 42 در `$a0` و `$a1` عبور می‌کند. تابع مقدار بزرگتر را در `$v0` برمی
# گرداند.
#
# وارد تماس شوید، `$ra` را با آدرس بعد از `jal` مقایسه کنید، سپس `jr $ra` را دنبال کنید و به
# تماس گیرنده برگردید.

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #استدلال اول
        li   $a1, 42            #استدلال دوم
        jal  maxof

        move $a0, $v0           #نتیجه در $v0 بازگشت
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof یک تابع برگ است، بنابراین می تواند بدون ذخیره $ra در پشته برگردد.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
