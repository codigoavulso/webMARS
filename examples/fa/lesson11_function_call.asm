#THE PROBLEM
#پریدن به یک روال آسان است. بازگشت نیست، زیرا
#همین روال ممکن است از بسیاری از جاها و از
#آدرس بازگشت هر بار متفاوت است.
#
#WHAT THE HARDWARE DOES
#jal دو کار را در یک دستورالعمل انجام می دهد: آن را ذخیره می کند
#آدرس دستورالعمل زیر در $ra، سپس می‌پرد. جونیور
#به هر چیزی که یک رجیستر دارد می پرد، بنابراین jr $ra برمی گردد.
#
#THE SOLUTION
#همه چیز دیگر توافق است، نه مدار: استدلال در
#$a0..$a3، نتایج در $v0. قرارداد و کد را بشکنید
#هنوز مونتاژ می شود - به سادگی کار متقابل را متوقف می کند.
#
#WATCH FOR
#روی jal بروید و $ra را بخوانید. با آدرس مقایسه کنید
#از خط بعد از تماس در بخش متن.
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #استدلال اول
        li   $a1, 42            #استدلال دوم
        #jal هم جریان کنترل و هم $ra را در یک عملیات معماری تغییر می دهد.
        jal  maxof              #$ra = آدرس خط بعدی

        move $a0, $v0           #نتیجه در $v0 بازگشت
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof یک تابع برگ است، بنابراین می تواند بدون ذخیره $ra در پشته برگردد.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
