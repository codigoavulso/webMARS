# 15 - چرا قدم زدن باعث تغییر سرعت می شود
#
# هر دو حلقه از یک آرایه استفاده می کنند. اول تمام 256 کلمه را می خواند. دومی هر شانزدهمین کلمه
# را می خواند و تنها 16 بار بارگذاری می کند.
#
# با بلوک های کش 16 کلمه ای، خواندن های متوالی می توانند هر بلوک واکشی شده را دوباره استفاده
# کنند. حلقه دوم در هر بار به یک بلوک جدید پیشروی می کند.
#
# شبیه‌ساز را به MIPS وصل کنید، گزینهٔ «فعال شد» را علامت بزنید و اندازهٔ بلوک را روی ۱۶ کلمه بگذارید.
# برای بررسی حلقه اول از شبیه ساز حافظه پنهان داده با نقطه شکست در `far` استفاده کنید. قبل از
# اجرای حلقه دوم، آمار حافظه پنهان را در آنجا بازنشانی کنید و نرخ ضربه را مقایسه کنید.

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# پاس متوالی: همه 256 کلمه.
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #نمایه های متوالی قبل از حرکت، از کلمات هر بلوک کش استفاده مجدد می کنند.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# پاس راه راه: هر شانزده کلمه یک بار.
        li   $t1, 0
        li   $t3, 0
far:
        # آدرس بعدی 64 بایت فاصله دارد: هر کدام شانزده کلمه در چهار بایت.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
