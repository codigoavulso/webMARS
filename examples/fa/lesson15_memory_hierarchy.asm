#درس 15 - چرا گام برداشتن سرعت را تغییر می دهد
#
#THE PROBLEM
#دو حلقه زیر یک آرایه را می خوانند و همان کار را انجام می دهند
#تعداد بارها در یک ماشین واقعی، سرعت آن بسیار کندتر است. را
#تعداد دستورالعمل نمی تواند آن را توضیح دهد.
#
#WHAT THE HARDWARE DOES
#حافظه تنها کلمات را تحویل نمی دهد. یک خانم یک کل را می آورد
#بلاک، شرط می بندم که کلمات همسایه به زودی مورد نیاز خواهد بود.
#یک قدم آن شرط را جمع می کند. یک قدم شانزده می پردازد
#برای یک بلوک و یک کلمه از آن را می خواند.
#
#THE SOLUTION
#هیچ چیزی در کد تغییر نمی کند. محلی بودن یک ویژگی از است
#الگوی دسترسی، و این الگو است که باید ثابت شود.
#
#WATCH FOR
#Tools > Data Cache Simulator را باز کنید، Connect to MIPS را فشار دهید،
#سپس اجرا کنید نرخ ضربه دو حلقه را مقایسه کنید. هر دو مبلغ
#0 چاپ کنید زیرا آرایه صفر شده است - عدد آن نیست
#در اینجا، نرخ ضربه است.
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- هر کلمه از هر بلوک ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #نمایه های متوالی قبل از حرکت، از کلمات هر بلوک کش استفاده مجدد می کنند.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- یک کلمه در هر بلوک به فاصله شانزده کلمه ----
        li   $t1, 0
        li   $t3, 0
far:
        #افزودن 16 پرش 64 بایت در هر تکرار: معمولاً یک بلوک کش کامل.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
