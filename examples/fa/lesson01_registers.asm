#THE PROBLEM
#ALU دو پورت ورودی دارد و هر دو به
#فایل ثبت نام عددی که در منبع نوشته شده در a نیست
#ثبت نام کنید، بنابراین نمی تواند مستقیماً به آن پورت ها برسد.
#
#WHAT THE HARDWARE DOES
#یک لحظه در داخل خود کلمه دستورالعمل حرکت می کند.
#addi یک فیلد 16 بیتی را حمل می کند. لی یک راحتی است
#اسمبلر به یک یا دو دستورالعمل واقعی گسترش می یابد.
#
#THE SOLUTION
#ابتدا ثابت را در یک ثبات قرار دهید، سپس اجازه دهید ALU
#دو رجیستر را بخوانید و سومی را بنویسید.
#
#WATCH FOR
#در هر خط یک بار قدم بردارید و $t0، $t1 و $t2 را در
#پنل ثبت می کند. فقط خط سوم ALU را لمس می کند.
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscals از $v0 به عنوان انتخابگر سرویس و $a0 به عنوان اولین آرگومان استفاده می‌کنند.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li یک شبه دستورالعمل است. اسمبل نشان می دهد که کدام دستورالعمل واقعی می شود.
        li   $t0, 12            #فوری -> ثبت نام
        li   $t1, 30            #فوری -> ثبت نام
        add  $t2, $t0, $t1      #ALU دو رجیستر را می خواند

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
