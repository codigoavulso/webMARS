# 01 - ثبت نام می کند و بلافاصله
#
# فوری در دستورالعمل کدگذاری شده است. جمع آوری کنید و بررسی کنید که هر `li` کدام دستورالعمل اصلی
# می شود.
#
# از میان دو بار و اضافه گذر کنید. در ثبت نام، `$t0 = 12`، `$t1 = 30` و `$t2 = 42` را دنبال
# کنید.
#
# سعی کنید 30 را با `0x12345678` جایگزین کنید و دوباره مونتاژ کنید. ثابت بزرگتر به بیش از یک
# دستور اساسی نیاز دارد.

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscals از $v0 به عنوان انتخابگر سرویس و $a0 به عنوان اولین آرگومان استفاده می‌کنند.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li یک شبه دستورالعمل است. اسمبل نشان می دهد که کدام دستورالعمل واقعی می شود.
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # مجموع در یک ثبت نام دیگر نوشته می شود.

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
