# 12 - بازگشت و فریم
#
# یک تماس بازگشتی `$ra` را بازنویسی می کند و از `$a0` برای آرگومان خود استفاده می کند. قبل از
# برقراری تماس، هر دو مقدار را ذخیره کنید.
#
# برای هر مقدار از 5 تا 1 وارد `fact` شوید. هر تماس هشت بایت ذخیره می کند، از جمله تماسی که 1 را
# برمی گرداند.
#
# برای تماشای مسیر برگشت، نقطه شکست را روی `mul` تنظیم کنید. هر فراخوانی آرگومان خود را دوباره
# بارگذاری می کند، ضرب می کند و فریم خود را آزاد می کند.

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #هر فراخوانی دارای یک فریم هشت بایتی متمایز است.
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #آدرس برگشت این تماس
        sw   $a0, 4($sp)        #این تماس n است

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #کیس پایه: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #دوباره n ما
        mul  $v0, $v0, $a0

factend:
        # قبل از آزاد کردن قاب این تماس، آدرس بازگشتی ذخیره شده را بازیابی کنید.
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
