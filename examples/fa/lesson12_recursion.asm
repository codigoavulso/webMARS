# ==========================================================
#درس 12 - بازگشت به یک فریم در هر تماس نیاز دارد
#
#THE PROBLEM
#یک فراخوان بازگشتی $ra را بازنویسی می‌کند و آرگومان ثبت می‌شود.
#پس تماس بیرونی راه بازگشتی ندارد و هیچ ایده ای ندارد
#خود n بود.
#
#WHAT THE HARDWARE DOES
#یک $ra را فراهم می کند، نه پشته ای از آنها. هیچ چیز ذخیره نمی شود
#به طور خودکار؛ اگر کد آن را ذخیره نکرد، از بین رفته است.
#
#THE SOLUTION
#هر فعال‌سازی یک فریم روی پشته باز می‌کند، آنچه را که در آن وجود دارد نگه می‌دارد
#پس از تماس همچنان نیاز خواهد داشت و در راه آن را بازیابی می کند
#بیرون عمق پشته، عمق بازگشتی است.
#
#WATCH FOR
#یک نقطه انفصال در مول تعیین کنید و مشاهده کنید $sp 8 در هر نزول می کند
#سطح پنج کپی ذخیره شده از n چیزی است که باعث می شود
#ضرب در راه بازگشت امکان پذیر است.
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #هر فراخوانی دارای یک فریم هشت بایتی متمایز است.
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #آدرس برگشت این تماس
        sw   $a0, 4($sp)        #این تماس n است

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #کیس پایه: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #دوباره n ما
        mul  $v0, $v0, $a0

factend:
        #وضعیت تماس گیرنده را بازیابی کنید و دقیقاً فریم اختصاص داده شده در هنگام ورود را دور بریزید.
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
