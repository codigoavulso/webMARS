# 14 - اعداد واقعی در 32 بیت
#
# یک شناور تک دقیق دارای یک بیت علامت، هشت بیت توان و ۲۳ بیت کسری است.
#
# `lwc1` الگوی بیت را در یک ثبات ممیز شناور کپی می کند. سپس `add.s` 3.5 و 1.25 را اضافه می کند
# تا 4.75 تولید شود.
#
# کدگذاری های 4.75 و 0.1 را در ابزار نمایش نقطه شناور مقایسه کنید. 4.75 دقیق است. 0.1 نیاز به
# گرد کردن دارد.

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #در فایل ثبت FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #جمع کننده FPU

        #Syscall 2 آرگومان شناور خود را به طور خاص در $f12 انتظار دارد.
        mov.s $f12, $f4
        li   $v0, 2             #چاپ شناور
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
