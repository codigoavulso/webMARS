# ==========================================================
#درس 14 - اعداد واقعی در 32 بیت
#
#THE PROBLEM
#3.5 جایی در یک ثبات عدد صحیح ندارد. کجا می کند
#بخش کسری می رود، و چگونه یک عدد بسیار بزرگ ذخیره می شود
#در همان 32 بیت به عنوان یک بسیار کوچک؟
#
#WHAT THE HARDWARE DOES
#IEEE-754 کلمه را به سه قسمت تقسیم می‌کند: یک بیت علامت،
#هشت بیت توان و بیست و سه بیت کسری. را
#توان نقطه باینری را اسلاید می کند، به همین دلیل است که فرمت آن است
#نقطه شناور نامیده می شود.
#
#THE SOLUTION
#یک فایل ثبت جداگانه ($f0..$f31) و یک جمع کننده جداگانه
#این مقادیر را مدیریت کنید، به همین دلیل است که یادگاری ها متفاوت هستند:
#lwc1 برای بارگیری، add.s برای افزودن، syscall 2 برای چاپ.
#
#WATCH FOR
#Tools > Floating Point Representation را باز کنید و 3.5 را وارد کنید.
#سه فیلد را تماشا کنید، سپس بررسی کنید که 4.75 دقیق است -
#بر خلاف 0.1 که کسر باینری محدودی ندارد.
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #آدرس های عدد صحیح هنوز داده ها را پیدا می کنند. lwc1 بیت های خود را به COP1 منتقل می کند.
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #در فایل ثبت FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #جمع کننده FPU

        #Syscall 2 آرگومان شناور خود را به طور خاص در $f12 انتظار دارد.
        mov.s $f12, $f4
        li   $v0, 2             #چاپ شناور
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
