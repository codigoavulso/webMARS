# 02 - مکمل دو
#
# در متمم 32 بیتی دو، معکوس کردن بیت های 5 و اضافه کردن 1، نمایش 5- را ایجاد می کند.
#
# برنامه همان مقدار را به دو صورت محاسبه می کند: `sub` از صفر، سپس `nor` و `addi`.
#
# هر دو مسیر -5 را چاپ می کنند. `0xFFFFFFFB` را در ثبات‌ها بررسی کنید تا ببینید همان بیت‌ها در
# هگزادسیمال چگونه به نظر می‌رسند.

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #تفریق از صفر، معکوس افزودنی را بدون بیت علامت منفی تشکیل می دهد.
        li   $t0, 5
        sub  $t1, $zero, $t0    #جمع کننده کار را انجام می دهد
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #و نه با $zero بیتی است NOT; اضافه کردن یک مکمل دو را کامل می کند.
        nor  $t2, $t0, $zero    #همه بیت ها را معکوس کنید
        addi $t2, $t2, 1        #یکی اضافه کن
        move $a0, $t2           #همان مقدار بالا
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
