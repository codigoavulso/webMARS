#THE PROBLEM
#یک رجیستر 32 سیم است که هر سیم بالا یا پایین است. سیم وجود ندارد
#برای علامت منفی، اعداد منفی باید کار کنند.
#
#WHAT THE HARDWARE DOES
#بیت بالا را به عنوان یک علامت می خواند، اما نه به عنوان یک پرچم جداگانه:
#-n به‌عنوان الگوی بیتی که به n اضافه می‌شود، ذخیره می‌شود
#صفر هر بیت را معکوس کنید و یکی اضافه کنید و آن را خواهید داشت.
#
#THE SOLUTION
#تفریق نیازی به مدار دوم ندارد. a - b می شود
#a + (-b)، بنابراین یک جمع کننده هر دو عملیات را انجام می دهد.
#
#WATCH FOR
#چاپ هر دو نیمه -5. دومی از راه طولانی به آن می رسد،
#با nor و addi، نشان می دهد که sub در داخل چه کاری انجام می دهد.
#مقادیر را روی هگزادسیمال تنظیم کنید تا 0xFFFFFFFB را ببینید.
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #تفریق از صفر، معکوس افزودنی را بدون بیت علامت منفی تشکیل می دهد.
        li   $t0, 5
        sub  $t1, $zero, $t0    #جمع کننده کار را انجام می دهد
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #و نه با $zero بیتی است NOT; اضافه کردن یک مکمل دو را کامل می کند.
        nor  $t2, $t0, $zero    #همه بیت ها را معکوس کنید
        addi $t2, $t2, 1        #یکی اضافه کن
        move $a0, $t2           #همان مقدار بالا
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
