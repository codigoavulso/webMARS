# 08 - ترتیب بایت و بایت
#
# در حافظه کوچک این شبیه ساز، کم اهمیت ترین بایت یک کلمه در پایین ترین آدرس زندگی می کند.
#
# `0x04030201` را به عنوان یک کلمه ذخیره کنید و آفست های 0 تا 3 را به عنوان بایت بخوانید. خروجی
# 1، 2، 3، 4 است.
#
# بایت کم `0xFF` را امتحان کنید. یک بار بدون علامت با `lbu` عدد 255 را به دست می دهد، در حالی که
# یک بار علامت دار با `lb`، -1 را می دهد.

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #بایت 01 کمترین اهمیت را دارد
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #بایت افست
bloop:
        #حلقه از 0، 1، 2 و 3 در داخل کلمه ذخیره شده بازدید می کند.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #آدرس موثر = آدرس پایه + افست بایت فعلی.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #بایت بدون امضا
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
