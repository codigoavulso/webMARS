#THE PROBLEM
#یک کلمه چهار آدرس را اشغال می کند. کدام بایت کمترین عملکرد را دارد
#نام آن آدرس ها؟
#
#WHAT THE HARDWARE DOES
#این انتخاب به ترتیب بایت است و یک تصمیم سیم کشی است
#یک بار برای کل دستگاه MIPS در اینجا کمی اندین است: the
#بایت کم اهمیت در پایین ترین آدرس زندگی می کند.
#
#THE SOLUTION
#یک کلمه را ذخیره کنید، سپس آن را هر بار یک بایت بخوانید و اجازه دهید
#دستور پاسخ سوال برای شما
#
#WATCH FOR
#0x04030201 به عنوان 1 2 3 4 برمی‌گردد. آخرین بایت نوشته شده در
#ابتدا حرف تحت اللفظی خوانده می شود. lbu به جای lb so a استفاده می شود
#بایت بالای 127 با علامت تمدید نشده است.
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #بایت 01 کمترین اهمیت را دارد
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #بایت افست
bloop:
        #حلقه از 0، 1، 2 و 3 در داخل کلمه ذخیره شده بازدید می کند.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #آدرس موثر = آدرس پایه + افست بایت فعلی.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #بایت بدون امضا
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
