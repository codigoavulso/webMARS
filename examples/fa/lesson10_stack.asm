# 10 - پشته
#
# طبق قرارداد، پشته به سمت آدرس های پایین تر رشد می کند. 8 را از `$sp` کم کنید تا برای دو کلمه
# فاصله رزرو کنید.
#
# این برنامه دو رجیستر را با `sw` ذخیره می کند، آنها را پاک می کند، سپس مقادیر آنها را با `lw`
# بازیابی می کند.
#
# قبل از رزرو، در طول دو فروشگاه و پس از انتشار، `$sp` را تماشا کنید. مقدار نهایی آن باید با
# مقدار اولیه آن مطابقت داشته باشد.

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #پشته به سمت پایین رشد می کند، بنابراین تخصیص از $sp کم می شود.
        addi $sp, $sp, -8       #دو کلمه رزرو کن
        sw   $t0, 0($sp)        #فشار دهید
        sw   $t1, 4($sp)

        li   $t0, 0             #رجیسترها را زیر و رو کنید
        li   $t1, 0

        lw   $t0, 0($sp)        #پاپ
        lw   $t1, 4($sp)
        #هر تخصیص باید متعادل باشد تا تماس‌گیرنده $sp اصلی خود را ببیند.
        addi $sp, $sp, 8        #آزاد کردن

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
