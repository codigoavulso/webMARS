#
#THE PROBLEM
#32 ثبت وجود دارد و هر قطعه از آنها به اشتراک گذاشته می شود
#کد وقتی یک ارزش باید از این کار جان سالم به در ببرد، کجا می رود
#آیا از آن رجیسترها استفاده مجدد خواهد شد؟
#
#WHAT THE HARDWARE DOES
#اصلا چیز خاصی نیست $sp یک رجیستر معمولی است که
#اتفاقاً به حافظه اشاره می کند و پشته به سمت رشد می کند
#آدرس های پایین تر صرفاً طبق قرارداد.
#
#THE SOLUTION
#رزرو فضا یک تفریق از $sp است، و آن را آزاد می کند
#علاوه بر این. فشار و پاپ فقط sw و lw هستند.
#
#WATCH FOR
#رجیسترها به عمد بین فروشگاه ها پاک می شوند
#و بارها، بنابراین مقادیر چاپ شده فقط می توانند آمده باشند
#از حافظه برگشت حرکت $sp را تا 8 و به عقب تماشا کنید.
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #پشته به سمت پایین رشد می کند، بنابراین تخصیص از $sp کم می شود.
        addi $sp, $sp, -8       #دو کلمه رزرو کن
        sw   $t0, 0($sp)        #فشار دهید
        sw   $t1, 4($sp)

        li   $t0, 0             #رجیسترها را زیر و رو کنید
        li   $t1, 0

        lw   $t0, 0($sp)        #پاپ
        lw   $t1, 4($sp)
        #هر تخصیص باید متعادل باشد تا تماس‌گیرنده $sp اصلی خود را ببیند.
        addi $sp, $sp, 8        #آزاد کردن

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
