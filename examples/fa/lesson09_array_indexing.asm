# 09 - نمایه سازی یک آرایه
#
# هر عنصر آرایه چهار بایت را اشغال می کند. برای محاسبه افست بایت آن، شاخص را به سمت چپ دو تا
# کنید.
#
# دنباله `sll`، `add`، `lw` را دنبال کنید: شاخص را مقیاس کنید، آدرس پایه را اضافه کنید و عنصر را
# بارگیری کنید.
#
# در شاخص 2، `$t5` برابر 8 است و `$t6` به مقدار 30 اشاره می کند. مجموع این پنج عنصر به 150 می
# رسد.

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #پایه
        li   $t1, 0             #من
        li   $t2, 5             #طول
        li   $t3, 0             #انباشت کننده

sum:
        #ثابت حلقه: $t3 مجموع arr[0] تا arr[i-1] است.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i * 4 بایت
        add  $t6, $t0, $t5      #پایه + شاخص مقیاس شده
        #$t6 اکنون دقیقاً یک عنصر را نام می‌برد. lw مقدار 32 بیتی خود را واکشی می کند.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
