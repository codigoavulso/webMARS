#THE PROBLEM
#یک دستورالعمل بار یک ثبات پایه و یک ثابت ارائه می دهد
#جبران. هیچ چیز دیگری. پس چگونه a[i] در زمانی که i فقط است به دست می آید
#شناخته شده در زمان اجرا، نشسته در یک ثبت نام؟
#
#WHAT THE HARDWARE DOES
#این پایه را به هر چیزی که رجیستر نگه می دارد اضافه می کند. شاخص
#بنابراین باید قبلاً بر حسب بایت باشد، نه در عناصر.
#
#THE SOLUTION
#شاخص را بر اساس اندازه عنصر مقیاس کنید، سپس اضافه کنید. برای چهار بایت
#کلماتی که مقیاس‌پذیری تغییری دو نفره است که هزینه دارد
#هیچ چیز
#
#WATCH FOR
#سه خط sll، add، lw چیزی است که a[i] در آن کامپایل می کند.
#یک تکرار را طی کنید و $t5 و $t6 را بخوانید.
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #پایه
        li   $t1, 0             #من
        li   $t2, 5             #طول
        li   $t3, 0             #انباشت کننده

sum:
        #ثابت حلقه: $t3 مجموع arr[0] تا arr[i-1] است.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i * 4 بایت
        add  $t6, $t0, $t5      #پایه + شاخص مقیاس شده
        #$t6 اکنون دقیقاً یک عنصر را نام می‌برد. lw مقدار 32 بیتی خود را واکشی می کند.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
