# 13 - دستور یک عدد است
#
# ستون Code را در بخش متن جمع آوری و بررسی کنید. هر دستورالعمل اصلی یک کلمه 32 بیتی است که به
# فیلدها تقسیم می شود.
#
# دو دستورالعمل `add` را مقایسه کنید. فیلدهای عملیات مطابقت دارند، در حالی که فیلدهای ثبت،
# عملوندهای مختلف را رمزگذاری می کنند.
#
# در `addi`، 16 بیت پایین، 100 فوری را نگه می دارند که `0x0064` است. آن را به 101 تغییر دهید و
# دوباره مونتاژ کنید تا تغییرات را ببینید.

        .text
        .globl main
main:
        #ستون Code را پس از مونتاژ بررسی کنید: این یادداشت ها به عنوان متن ذخیره نمی شوند.
        add  $t0, $t1, $t2      #نوع R: opcode، rs، rt، rd، تابع
        add  $t3, $t4, $t5      #یک شکل، رجیسترهای مختلف
        addi $t0, $t1, 100      #I-type: ثابت در کلمه است
        sll  $t0, $t1, 4        #مقدار شیفت فیلد خاص خود را دارد
        j    tail               #J-type: یک آدرس، نه یک ثبت نام
tail:
        #لی خود قبل از اجرا گسترش می یابد. پردازنده فقط کلمات رمزگذاری شده را می بیند.
        li   $v0, 10
        syscall
