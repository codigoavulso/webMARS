#THE PROBLEM
#پردازنده کلمات را از حافظه واکشی می کند. کد زندگی می کند
#حافظه نیز بنابراین چه چیزی یک دستورالعمل را از a متمایز می کند
#تکه داده؟
#
#WHAT THE HARDWARE DOES
#هیچ چیز، فراتر از ثبت نام کلمه در آن بارگذاری می شود. را
#کامپیوتر کلماتی را انتخاب می کند که به رمزگشا می روند. lw کلمات را انتخاب می کند
#که به فایل ثبت نام بروید. بیت ها از همین نوع هستند.
#
#THE SOLUTION
#رمزگذاری را مستقیماً بخوانید. جمع کنید و باز کنید
#Main > Execute: ستون Code هر دستورالعمل را به صورت نشان می دهد
#کلمه 32 بیتی که واقعا هست.
#
#WATCH FOR
#این درس هیچ چیز را از روی هدف چاپ نمی کند - خروجی آن است
#خود بخش متن دو افزودنی را با هم مقایسه کنید: همان opcode و
#فیلدهای تابع، اعداد ثبت مختلف. سپس پیدا کنید
#به معنای واقعی کلمه 100 در داخل کلمه addi.
# ==========================================================
        .text
        .globl main
main:
        #ستون Code را پس از مونتاژ بررسی کنید: این یادداشت ها به عنوان متن ذخیره نمی شوند.
        add  $t0, $t1, $t2      #نوع R: opcode، rs، rt، rd، تابع
        add  $t3, $t4, $t5      #یک شکل، رجیسترهای مختلف
        addi $t0, $t1, 100      #I-type: ثابت در کلمه است
        sll  $t0, $t1, 4        #مقدار شیفت فیلد خاص خود را دارد
        j    tail               #J-type: یک آدرس، نه یک ثبت نام
tail:
        #لی خود قبل از اجرا گسترش می یابد. پردازنده فقط کلمات رمزگذاری شده را می بیند.
        li   $v0, 10
        syscall
