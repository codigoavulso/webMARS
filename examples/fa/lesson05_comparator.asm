#THE PROBLEM
#یک تصمیم به یک بیت نیاز دارد، اما مقایسه دو عدد 32 بیتی
#تفریق است. چگونه تفریق به انتخاب تبدیل می شود؟
#
#WHAT THE HARDWARE DOES
#slt همه چیز را کم می کند و دور می اندازد به جز علامت،
#نوشتن 0 یا 1. سپس شاخه آن بیت را به رایانه شخصی تغذیه می کند
#منطق، که یا یک افست اضافه می کند یا به کامپیوتر اجازه می دهد پیشرفت کند.
#
#THE SOLUTION
#در یک رجیستر مقایسه کنید، در آن رجیستر منشعب کنید. کنترل کنید
#جریان حسابی به اضافه یک مالتی پلکسر در رایانه شخصی است.
#
#WATCH FOR
#بعد از slt، $t2 1 را نگه می‌دارد. از beq رد شوید و رایانه شخصی را تماشا کنید
#در نوار وضعیت: به جای 4 تا پیشروی می پرد.
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #الف
        li   $t1, 12            #ب
        #slt مقایسه را به عنوان یک عدد صحیح معمولی و هرگز به عنوان پرچم های مخفی انجام نمی دهد.
        slt  $t2, $t0, $t1      #t2 = 1 اگر a < b
        #فقط زمانی که آن نتیجه بولی صفر باشد به notless شاخه می شود.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
