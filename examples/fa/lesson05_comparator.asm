# 05 - مقایسه کننده و شعبه
#
# `slt` دو عدد صحیح علامت دار را با هم مقایسه می کند و زمانی که اولی کوچکتر است 1 یا در غیر این
# صورت 0 می نویسد.
#
# برای 7 و 12، `$t2` 1 است، بنابراین `beq` به `notless` نمی‌پرد و اجرا به دستور بعدی ادامه
# می‌یابد.
#
# با انشعاب تاخیری، `beq` را پشت سر بگذارید و رایانه شخصی را مشاهده کنید. دو مقدار ورودی را عوض
# کنید و مقصد جدید را مقایسه کنید.

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #الف
        li   $t1, 12            #ب
        #slt مقایسه را به عنوان یک عدد صحیح معمولی و هرگز به عنوان پرچم های مخفی انجام نمی دهد.
        slt  $t2, $t0, $t1      #t2 = 1 اگر a < b
        #فقط زمانی که آن نتیجه بولی صفر باشد به notless شاخه می شود.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
