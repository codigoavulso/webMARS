# ==========================================================
#Урок 03. Логические элементы на 32 бита
#
#THE PROBLEM
#AND, OR и XOR — однобитовые вентили. Регистр содержит 32 бита.
#Что означают ворота такой ширины?
#
#WHAT THE HARDWARE DOES
#На нем лежат 32 копии ворот рядом. Бит 0
#результат зависит только от бита 0 каждого операнда, бит 1 только от
#бит 1 и так далее. Никакого переноса между ними.
#
#THE SOLUTION
#Именно эта независимость заставляет маску работать: выбирайте, какую
#биты, которые следует сохранить с помощью AND, принудительно перевести в единицу с помощью OR, перевернуть с помощью XOR.
#
#WATCH FOR
#0xCC — 11001100, а маска 0x0F — 00001111. AND сохраняет
#младшие четыре бита, ИЛИ устанавливает их, XOR переворачивает их. Только
#низкий клев постоянно меняется.
# ==========================================================
        .data
ma:     .asciiz "AND keeps the low nibble: "
mo:     .asciiz "OR sets the low nibble:   "
mx:     .asciiz "XOR flips the low nibble: "
        .text
        .globl main
main:
        li   $t0, 204           #0xCC
        li   $t1, 15            #Маска 0x0F

        la   $a0, ma
        li   $v0, 4
        syscall
        #AND очищает каждую позицию, где маска содержит ноль.
        and  $t2, $t0, $t1
        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mo
        li   $v0, 4
        syscall
        or   $t3, $t0, $t1
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mx
        li   $v0, 4
        syscall
        #XOR переключает только позиции, выбранные в маске.
        xor  $t4, $t0, $t1
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
