#Привет, мир для запуска ввода-вывода
#Печатает простое сообщение и выходит.
#Это наименьший пример разделения данных и текста и соглашения о системных вызовах.

.data
#.asciiz хранит символы, за которыми следует нулевой знак завершения, требуемый системным вызовом 4.
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #Выберите строку печати (4) в $v0 и передайте адрес строки в $a0.
  li $v0, 4
  la $a0, msg
  syscall

  #Выход (10) полностью останавливает моделируемую программу.
  li $v0, 10
  syscall
