# 02 – дополнение до двух
#
# В 32-битном дополнении до двух инвертирование битов 5 и добавление 1 дает представление -5.
#
# Программа вычисляет одно и то же значение двумя способами: `sub` от нуля, затем `nor` и
# `addi`.
#
# Оба пути печатают -5. Проверьте `0xFFFFFFFB` в регистрах, чтобы увидеть, как те же биты
# выглядят в шестнадцатеричном виде.

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #Вычитание из нуля образует обратную добавку без бита со знаком минус.
        li   $t0, 5
        sub  $t1, $zero, $t0    #сумматор делает работу
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #ни с $zero не является побитовым NOT; добавление одного завершает дополнение до двух.
        nor  $t2, $t0, $zero    #инвертировать все биты
        addi $t2, $t2, 1        #добавить один
        move $a0, $t2           #то же значение, что и выше
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
