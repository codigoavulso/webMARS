# ==========================================================
#Урок 02 - Дополнение до двух
#
#THE PROBLEM
#Регистр состоит из 32 проводов, каждый из которых имеет высокий или низкий уровень. Нет провода
#для знака минус, однако отрицательные числа должны работать.
#
#WHAT THE HARDWARE DOES
#Он читает верхний бит как знак, а не как отдельный флаг:
#-n хранится как битовая комбинация, которая, добавленная к n, переносится в
#ноль. Инвертируйте каждый бит и добавьте один, и все готово.
#
#THE SOLUTION
#Вычитание не требует второго контура. а-б становится
#a + (-b), поэтому один сумматор обслуживает обе операции.
#
#WATCH FOR
#Обе половины печатают -5. Второй добирается до него долгим путем,
#с nor и addi, показывающие, что саб делает внутри.
#Установите шестнадцатеричные значения, чтобы увидеть 0xFFFFFFFB.
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #Вычитание из нуля образует обратную добавку без бита со знаком минус.
        li   $t0, 5
        sub  $t1, $zero, $t0    #сумматор делает работу
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #ни с $zero не является побитовым NOT; добавление одного завершает дополнение до двух.
        nor  $t2, $t0, $zero    #инвертировать все биты
        addi $t2, $t2, 1        #добавить один
        move $a0, $t2           #то же значение, что и выше
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
