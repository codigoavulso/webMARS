# ==========================================================
#Урок 12. Рекурсии нужен кадр на вызов
#
#THE PROBLEM
#Рекурсивный вызов перезаписывает $ra и регистр аргументов.
#Внешний вызов тогда не имеет пути назад и не знает, что это такое.
#собственный был.
#
#WHAT THE HARDWARE DOES
#Он предоставляет один $ra, а не их стек. Ничего не сохраняется
#автоматически; если код не сохраняет его, он пропал.
#
#THE SOLUTION
#Каждая активация открывает кадр в стеке, сохраняя то, что в нем есть.
#все равно понадобится после звонка, и восстановит его по дороге
#вне. Глубина стека — это глубина рекурсии.
#
#WATCH FOR
#Установите точку останова на mul и наблюдайте, как $sp снижается на 8
#уровень. Пять сохраненных копий n — это то, что делает
#возможно умножение на обратном пути.
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int факт(int n) ----
fact:
        #Каждому вызову принадлежит отдельный восьмибайтовый кадр.
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #обратный адрес этого звонка
        sw   $a0, 4($sp)        #номер этого звонка

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #базовый вариант: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #снова наш н
        mul  $v0, $v0, $a0

factend:
        #Восстановите состояние вызываемого абонента и отбросьте ровно тот кадр, который был выделен при входе.
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
