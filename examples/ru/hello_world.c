//Пример C0-S1: вывод строки и обычный возврат из main.
//Компилятор понижает уровень этих помощников до тех же системных вызовов печати MIPS, которые используются сборкой.
int main(void) {
  //Строковые литералы создаются в сегменте данных с конечным нулевым байтом.
  print_string("Hello from C on webMARS!");
  //ASCII 10 — перевод строки; print_char выдает ровно один символ.
  print_char(10);
  //Возврат из main становится чистым выходом из программы.
  return 0;
}
