# 08 — Байты и порядок байтов
#
# В памяти этого симулятора с прямым порядком байтов младший байт слова находится по самому
# младшему адресу.
#
# Сохраните `0x04030201` как слово и прочитайте смещения от 0 до 3 как байты. Выход: 1, 2, 3, 4.
#
# Попробуйте младший байт `0xFF`. Беззнаковая загрузка с `lbu` дает 255, а знаковая загрузка с
# `lb` дает -1.

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #байт 01 является наименее значимым
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #смещение байта
bloop:
        #Цикл посещает смещения 0, 1, 2 и 3 внутри сохраненного слова.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #Эффективный адрес = базовый адрес + текущее смещение байта.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #беззнаковый байт
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
