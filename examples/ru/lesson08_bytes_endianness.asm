# ==========================================================
#Урок 08 – Байты внутри слова и порядок байтов
#
#THE PROBLEM
#Слово занимает четыре адреса. Какой байт имеет наименьший
#названия этих адресов?
#
#WHAT THE HARDWARE DOES
#Этот выбор определяется порядком байтов, и это решение, принятое при подключении.
#один раз на всю машину. MIPS здесь прямой порядок байтов:
#младший байт находится по наименьшему адресу.
#
#THE SOLUTION
#Сохраните одно слово, затем читайте его побайтно и позволяйте
#заказ ответит на вопрос для вас.
#
#WATCH FOR
#0x04030201 возвращается как 1 2 3 4. Байт, записанный последним в
#литерал читается первым. используется lbu, а не lb, поэтому
#Байт выше 127 не расширяется по знаку.
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #байт 01 является наименее значимым
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #смещение байта
bloop:
        #Цикл посещает смещения 0, 1, 2 и 3 внутри сохраненного слова.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #Эффективный адрес = базовый адрес + текущее смещение байта.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #беззнаковый байт
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
