#Урок 05 - Компаратор и ветвь
#
#THE PROBLEM
#Для решения нужен один бит, но сравнение двух 32-битных чисел
#это вычитание. Как вычитание становится выбором?
#
#WHAT THE HARDWARE DOES
#slt вычитает и отбрасывает все, кроме знака,
#записываем 0 или 1. Затем ветвь передает этот бит на ПК.
#логика, которая либо добавляет смещение, либо позволяет ПК двигаться вперед.
#
#THE SOLUTION
#Сравнить с регистром, перейти к этому регистру. Контроль
#поток — это арифметика плюс один мультиплексор на ПК.
#
#WATCH FOR
#После slt $t2 содержит 1. Пройдите мимо beq и посмотрите на компьютер.
#в строке состояния: он прыгает, а не продвигается на четыре.
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #а
        li   $t1, 12            #б
        #slt материализует сравнение как обычное целое число, а не как скрытые флаги.
        slt  $t2, $t0, $t1      #t2 = 1, если a < b
        #Переход к notless только тогда, когда этот логический результат равен нулю.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
