# 05 — Компаратор и ветвь
#
# `slt` сравнивает два целых числа со знаком и записывает 1, если первое меньше, или 0 в
# противном случае.
#
# Для 7 и 12 `$t2` равно 1, поэтому `beq` не переходит на `notless` и выполнение продолжается до
# следующей инструкции.
#
# При отложенном ответвлении пройдите мимо `beq` и наблюдайте за ПК. Поменяйте местами два
# входных значения и сравните новый пункт назначения.

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #а
        li   $t1, 12            #б
        #slt материализует сравнение как обычное целое число, а не как скрытые флаги.
        slt  $t2, $t0, $t1      #t2 = 1, если a < b
        #Переход к notless только тогда, когда этот логический результат равен нулю.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
