# 04 – Сдвиги и степени двойки
#
# Сдвиг влево на 3 умножается на 8, когда результат подходит. Биты, сдвинутые за край,
# отбрасываются.
#
# Справа `srl` заполняется нулями, а `sra` копирует знаковый бит. Если -16 сдвинуто на 2,
# ожидайте 1073741820 и -4 соответственно.
#
# Попробуйте -15 с `sra`. Результат равен -4, поскольку сдвиг округляется в меньшую сторону;
# подписанное деление округляется до нуля.

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #Три сдвига влево умножаются на 2^3, сохраняя при этом только 32 бита результата.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #Сравните $t3 и $t4 в шестнадцатеричном формате, чтобы увидеть различные входящие биты.
        sra  $t3, $t2, 2        #знак сохранен: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #нули сдвинулись: огромный позитив
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
