# ==========================================================
#Урок 04 - Сдвиги или умножение с помощью проводов
#
#THE PROBLEM
#Общий множитель — один из самых дорогих блоков в
#путь данных. Умножение на 8 не должно стоить так много.
#
#WHAT THE HARDWARE DOES
#Сдвиг — это вообще не арифметика: это считывание тех же битов.
#из разных проводов. Сдвиг влево на n умножается на 2^n
#и стоит только маршрутизация.
#
#THE SOLUTION
#Степени двойки становятся сдвигами. Обратите внимание на два смещения вправо: srl
#подает нули вверху, sra копирует знаковый бит, так что только
#сра правильно делит отрицательное число.
#
#WATCH FOR
#-16 >> 2 дает -4 с ср, но огромный плюс с срл.
#биты перемещались одинаково; отличается только то, что введено вверху.
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #Три сдвига влево умножаются на 2^3, сохраняя при этом только 32 бита результата.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #Сравните $t3 и $t4 в шестнадцатеричном формате, чтобы увидеть различные входящие биты.
        sra  $t3, $t2, 2        #знак сохранен: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #нули сдвинулись: огромный позитив
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
