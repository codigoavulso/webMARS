# ==========================================================
#Урок 10 — Стек — это регистр и смещение
#
#THE PROBLEM
#Существует 32 регистра, и они являются общими для каждой части устройства.
#код. Куда девается ценность, если она должна пережить работу,
#будет повторно использовать эти регистры?
#
#WHAT THE HARDWARE DOES
#Ничего особенного. $sp — это обычный регистр, который
#случается, что он указывает на память, и стек растет в сторону
#нижние адреса чисто по соглашению.
#
#THE SOLUTION
#Резервирование места — это вычитание из $sp, освобождение его
#дополнение. Push и pop — это просто sw и lw.
#
#WATCH FOR
#Регистры намеренно очищаются между магазинами
#и нагрузки, поэтому напечатанные значения могли прийти только
#вернуться из памяти. Посмотрите, как $sp перемещается на 8 и обратно.
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #Стек увеличивается вниз, поэтому выделение вычитается из $sp.
        addi $sp, $sp, -8       #оставь два слова
        sw   $t0, 0($sp)        #толкать
        sw   $t1, 4($sp)

        li   $t0, 0             #затирать регистры
        li   $t1, 0

        lw   $t0, 0($sp)        #поп
        lw   $t1, 4($sp)
        #Каждое распределение должно быть сбалансированным, чтобы вызывающая сторона видела исходный $sp.
        addi $sp, $sp, 8        #выпуск

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
