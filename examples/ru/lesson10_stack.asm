# 10 - Стек
#
# По соглашению стек растет в сторону меньших адресов. Вычтите 8 из `$sp`, чтобы освободить
# место для двух слов.
#
# Программа сохраняет два регистра с помощью `sw`, очищает их, затем восстанавливает их значения
# с помощью `lw`.
#
# Смотрите `$sp` перед резервированием, во время двух магазинов и после выпуска. Его
# окончательное значение должно соответствовать его начальному значению.

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #Стек увеличивается вниз, поэтому выделение вычитается из $sp.
        addi $sp, $sp, -8       #оставь два слова
        sw   $t0, 0($sp)        #толкать
        sw   $t1, 4($sp)

        li   $t0, 0             #затирать регистры
        li   $t1, 0

        lw   $t0, 0($sp)        #поп
        lw   $t1, 4($sp)
        #Каждое распределение должно быть сбалансированным, чтобы вызывающая сторона видела исходный $sp.
        addi $sp, $sp, 8        #выпуск

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
