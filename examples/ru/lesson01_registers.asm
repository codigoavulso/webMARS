# ==========================================================
#Урок 01 — Регистры и непосредственные значения
#
#THE PROBLEM
#ALU имеет два входных порта, оба подключены к
#зарегистрировать файл. Числа, записанного в источнике, нет в
#зарегистрируйтесь, чтобы он не мог напрямую обращаться к этим портам.
#
#WHAT THE HARDWARE DOES
#Немедленное перемещение внутри самого командного слова.
#addi содержит 16-битное поле; ли это удобство
#ассемблер расширяется до одной или двух реальных инструкций.
#
#THE SOLUTION
#Сначала поместите константу в регистр, а затем пусть ALU
#прочитать два регистра и записать третий.
#
#WATCH FOR
#Шагайте по одной строке и следуйте $t0, $t1 и $t2 в
#Панель регистров. Только третья строка касается ALU.
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Системные вызовы используют $v0 в качестве селектора службы и $a0 в качестве первого аргумента.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li — псевдоинструкция; Ассемблер показывает, какой настоящей инструкцией она становится.
        li   $t0, 12            #немедленно -> зарегистрироваться
        li   $t1, 30            #немедленно -> зарегистрироваться
        add  $t2, $t0, $t1      #ALU читает два регистра

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
