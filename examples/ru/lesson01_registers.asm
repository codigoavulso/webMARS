# 01 — Регистры и непосредственные действия
#
# Непосредственное действие закодировано в инструкции. Соберите и проверьте, какой базовой
# инструкцией становится каждая `li`.
#
# Пройдите через две нагрузки и сложение. В регистрах следуйте `$t0 = 12`, `$t1 = 30` и
# `$t2 = 42`.
#
# Попробуйте заменить 30 на `0x12345678` и собрать заново. Для большей константы требуется более
# одной базовой инструкции.

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Системные вызовы используют $v0 в качестве селектора службы и $a0 в качестве первого аргумента.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li — псевдоинструкция; Ассемблер показывает, какой настоящей инструкцией она становится.
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # Сумма записывается в другой регистр.

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
