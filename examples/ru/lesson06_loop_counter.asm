# ==========================================================
#Урок 06 - Счетчик, программный и аппаратный
#
#THE PROBLEM
#Аппаратный счетчик — это регистр, инкрементатор и
#компаратор. Как выглядит та же машина написано
#как инструкция?
#
#WHAT THE HARDWARE DOES
#Именно эти три части, по одной на инструкцию: регистр
#удерживает счетчик, addi — инкрементатор, slt с ветвью
#это компаратор, который принимает решение о следующем раунде.
#
#THE SOLUTION
#Петля — это не новая концепция. Это последовательная логика, написанная
#out, с ПК в качестве часов.
#
#WATCH FOR
#$t0 — регистр счетчика, а $t1 — предел. Шаг через
#один полный раунд и назовите, какая линия является какой частью.
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #счетный регистр
        li   $t1, 11            #предел

loop:
        #Инвариант цикла: $t0 — это следующее значение для печати, которое остается ниже $t1.
        slt  $t2, $t0, $t1      #компаратор
        beq  $t2, $zero, endl   #выйти, когда счетчик достигнет предела

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #Обновление счетчика перед прыжком гарантирует продвижение к завершению.
        addi $t0, $t0, 1        #сумматор
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
