# 06 - Цикл как счетчик
#
# `$t0` — следующее число, которое нужно вывести. `$t1` — это исключительный верхний предел,
# поэтому ограничение в 11 печатает от 1 до 10.
#
# Сравнение выполняется перед каждой итерацией. Приращение приближается к пределу, и прыжок
# повторяет проверку.
#
# Измените лимит на 1 и бегите. Выходная ветвь берется до первой печати.

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #счетный регистр
        li   $t1, 11            #предел

loop:
        # При циклическом тесте следующим кандидатом является $t0. Распечатывайте его, только если оно ниже $t1.
        slt  $t2, $t0, $t1      #компаратор
        beq  $t2, $zero, endl   #выйти, когда счетчик достигнет предела

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #Обновление счетчика перед прыжком гарантирует продвижение к завершению.
        addi $t0, $t0, 1        #сумматор
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
