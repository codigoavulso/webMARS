# 14 – Действительные числа в 32 битах
#
# Число с плавающей запятой одинарной точности имеет один бит знака, восемь битов экспоненты и
# 23 бита дроби.
#
# `lwc1` копирует битовую комбинацию в регистр с плавающей запятой. Затем `add.s` добавляет 3,5
# и 1,25, получая 4,75.
#
# Сравните кодировки 4.75 и 0.1 в инструменте Представление с плавающей запятой. 4,75 — это
# точно; 0,1 требует округления.

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #в файл регистра FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #сумматор FPU

        #Системный вызов 2 ожидает аргумент с плавающей запятой именно в $f12.
        mov.s $f12, $f4
        li   $v0, 2             #распечатать плавающее число
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
