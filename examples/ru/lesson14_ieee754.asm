# ==========================================================
#Урок 14 - Действительные числа в 32 битах
#
#THE PROBLEM
#3.5 нет места в целочисленном регистре. Где находится
#дробная часть идет, и как хранится очень большое число
#в тех же 32 битах, что и очень маленький?
#
#WHAT THE HARDWARE DOES
#IEEE-754 разбивает слово на три поля: один знаковый бит,
#восемь битов экспоненты и двадцать три бита дроби.
#экспонента сдвигает двоичную точку, поэтому формат
#называется плавающей запятой.
#
#THE SOLUTION
#Отдельный файл регистра ($f0..$f31) и отдельный сумматор
#обрабатывать эти значения, поэтому мнемоника различается:
#lwc1 для загрузки, add.s для добавления, системный вызов 2 для печати.
#
#WATCH FOR
#Откройте «Инструменты» > «Представление с плавающей запятой» и введите 3.5.
#Посмотрите на три поля, затем проверьте, что 4,75 является точным –
#в отличие от 0,1, у которого нет конечной двоичной дроби.
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #Целочисленные адреса по-прежнему определяют местонахождение данных; lwc1 перемещает свои биты в COP1.
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #в файл регистра FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #сумматор FPU

        #Системный вызов 2 ожидает аргумент с плавающей запятой именно в $f12.
        mov.s $f12, $f4
        li   $v0, 2             #распечатать плавающее число
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
