#
#THE PROBLEM
#Процессор извлекает слова из памяти. Код живет в
#память тоже. Так что же отличает инструкцию от
#часть данных?
#
#WHAT THE HARDWARE DOES
#Ничего, за пределами какого регистра загружается слово.
#ПК выбирает слова, которые поступают в декодер; лв выбирает слова
#которые идут в файл реестра. Биты одинаковые.
#
#THE SOLUTION
#Прочтите кодировку напрямую. Собираем и открываем
#Main > Execute: в столбце «Код» каждая инструкция отображается как
#32-битное слово это действительно так.
#
#WATCH FOR
#В этом уроке специально ничего не печатается. Результатом является
#Сам текстовый сегмент. Сравните два добавления: одинаковый код операции и
#функциональные поля, разные номера регистров. Затем найдите
#буква 100 внутри слова адди.
# ==========================================================
        .text
        .globl main
main:
        #После сборки проверьте столбец «Код»: эти мнемоники не сохраняются в виде текста.
        add  $t0, $t1, $t2      #R-тип: код операции, rs, rt, rd, функция
        add  $t3, $t4, $t5      #та же форма, разные регистры
        addi $t0, $t1, 100      #I-тип: константа есть в слове
        sll  $t0, $t1, 4        #сумма смены имеет собственное поле
        j    tail               #J-тип: адрес, а не регистр
tail:
        #li сам расширяется перед выполнением; процессор видит только закодированные слова.
        li   $v0, 10
        syscall
