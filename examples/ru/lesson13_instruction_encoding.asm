# 13 – Инструкция – это число
#
# Соберите и проверьте столбец «Код» в текстовом сегменте. Каждая базовая инструкция
# представляет собой 32-битное слово, разделенное на поля.
#
# Сравните две инструкции `add`. Поля операций совпадают, а поля регистров кодируют разные
# операнды.
#
# В `addi` младшие 16 бит содержат непосредственные 100, то есть `0x0064`. Измените его на 101 и
# соберите заново, чтобы увидеть изменения.

        .text
        .globl main
main:
        #После сборки проверьте столбец «Код»: эти мнемоники не сохраняются в виде текста.
        add  $t0, $t1, $t2      #R-тип: код операции, rs, rt, rd, функция
        add  $t3, $t4, $t5      #та же форма, разные регистры
        addi $t0, $t1, 100      #I-тип: константа есть в слове
        sll  $t0, $t1, 4        #сумма смены имеет собственное поле
        j    tail               #J-тип: адрес, а не регистр
tail:
        #li сам расширяется перед выполнением; процессор видит только закодированные слова.
        li   $v0, 10
        syscall
