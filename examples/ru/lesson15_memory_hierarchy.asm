# 15 - Почему шаг меняет скорость
#
# Оба цикла используют один и тот же массив. Первый читает все 256 слов; второй читает каждое
# 16-е слово, совершая всего 16 загрузок.
#
# При блоках кэша по 16 слов последовательное чтение может повторно использовать каждый
# выбранный блок. Второй цикл переходит к новому блоку при каждой загрузке.
#
# Подключите симулятор к MIPS, установите флажок «Включено» и задайте размер блока 16 слов.
# Используйте Симулятор кэша данных с точкой останова на `far`, чтобы проверить первый цикл.
# Сбросьте статистику кэша перед запуском второго цикла и сравните показатели попаданий.

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# Последовательный проход: все 256 слов.
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #Последовательные индексы повторно используют слова из каждого блока кэша, прежде чем двигаться дальше.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# Шаговый проход: одна загрузка каждые шестнадцать слов.
        li   $t1, 0
        li   $t3, 0
far:
        # Следующий адрес находится на расстоянии 64 байтов: шестнадцать слов по четыре байта каждое.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
