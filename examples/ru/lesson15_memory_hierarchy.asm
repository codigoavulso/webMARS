# ==========================================================
#Урок 15 - Почему шаг меняет скорость
#
#THE PROBLEM
#Два цикла ниже читают один и тот же массив и выполняют одно и то же.
#количество грузов. На реальной машине все происходит гораздо медленнее.
#количество инструкций не может этого объяснить.
#
#WHAT THE HARDWARE DOES
#Память не выдает отдельных слов. Мисс приносит целое
#блокировать, делая ставку на то, что соседние слова скоро будут востребованы.
#Один шаг забирает эту ставку; шестнадцать шагов платит
#для блока и читает одно его слово.
#
#THE SOLUTION
#В коде ничего не меняется. Локализация является собственностью
#шаблон доступа, и именно этот шаблон необходимо исправить.
#
#WATCH FOR
#Откройте «Инструменты» > «Имитатор кэша данных», нажмите «Подключиться к MIPS».
#тогда беги. Сравните скорость попадания двух циклов. Обе суммы
#выведите 0, потому что массив обнулён — число не является
#точка здесь, процент попаданий.
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- каждое слово каждого блока ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #Последовательные индексы повторно используют слова из каждого блока кэша, прежде чем двигаться дальше.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- одно слово в блоке с интервалом шестнадцать слов ----
        li   $t1, 0
        li   $t3, 0
far:
        #Добавление 16 пропускает 64 байта за итерацию: обычно один целый блок кэша.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
