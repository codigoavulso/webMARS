# ==========================================================
#Урок 07. Слова в памяти и почему адреса скачут на четыре
#
#THE PROBLEM
#Память адресуется по одному байту за раз, но регистр хранит
#четыре байта. Что на самом деле выбирает один адрес?
#
#WHAT THE HARDWARE DOES
#lw и sw перемещают четыре байта за один доступ, поэтому последовательно
#слова располагаются на расстоянии четырех адресов друг от друга. Младшие два бита
#адрес должен быть нулевым: именно это выравнивание позволяет
#аппаратное обеспечение извлекает целое слово за один цикл.
#
#THE SOLUTION
#Адресная арифметика выполняется в байтах, поэтому индекс состоит из слов.
#всегда масштабируется на четыре.
#
#WATCH FOR
#Соберите, затем откройте сегмент данных в 0x10010000.
#три значения появляются в соседних столбцах одной строки.
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #базовый адрес

        #Каждое смещение ниже относится к $t0 и остается выравниваемым по слову.
        li   $t1, 111
        sw   $t1, 0($t0)        #первое слово
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 байта = следующее слово
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 байт

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw восстанавливает те же 32-битные значения, ранее записанные sw.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
