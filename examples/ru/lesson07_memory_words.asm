# 07 - Слова в памяти
#
# Адреса памяти считают байты. Каждое слово занимает четыре байта, поэтому `lw` и `sw`
# используют здесь смещения 0, 4 и 8.
#
# Адрес слова должен быть кратен четырем. Использование смещения 1 вместо 4 приводит к
# исключению выравнивания в этой программе.
#
# После магазинов посмотрите на `cell` в сегменте данных. Три соседних слова должны содержать
# 111, 222 и 333.

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #базовый адрес

        #Каждое смещение ниже относится к $t0 и остается выравниваемым по слову.
        li   $t1, 111
        sw   $t1, 0($t0)        #первое слово
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 байта = следующее слово
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 байт

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw восстанавливает те же 32-битные значения, ранее записанные sw.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
