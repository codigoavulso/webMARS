# ==========================================================
#Урок 09 — Индексирование массива
#
#THE PROBLEM
#Инструкция загрузки предлагает базовый регистр и константу.
#смещение. Ничего больше. Так как же достигается a[i], когда я всего лишь
#известно во время выполнения, находится в реестре?
#
#WHAT THE HARDWARE DOES
#Он добавляет базу ко всему, что хранится в регистре. Индекс
#поэтому уже должно быть в байтах, а не в элементах.
#
#THE SOLUTION
#Масштабируйте индекс по размеру элемента, затем добавьте. Для четырехбайтового
#слова о том, что масштабирование — это сдвиг влево на два, который стоит
#ничего.
#
#WATCH FOR
#Три строки sll, add, lw — это то, во что компилируется a[i].
#Пройдите одну итерацию и прочитайте $t5 и $t6.
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #база
        li   $t1, 0             #я
        li   $t2, 5             #длина
        li   $t3, 0             #аккумулятор

sum:
        #Инвариант цикла: $t3 представляет собой сумму от arr[0] до arr[i-1].
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #я * 4 байта
        add  $t6, $t0, $t5      #базовый + масштабированный индекс
        #$t6 теперь называет ровно один элемент; lw извлекает свое 32-битное значение.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
