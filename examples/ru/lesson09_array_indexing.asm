# 09 — Индексирование массива
#
# Каждый элемент массива занимает четыре байта. Сдвиньте индекс влево на два, чтобы вычислить
# смещение в байтах.
#
# Следуйте последовательности `sll`, `add`, `lw`: масштабируйте индекс, добавьте базовый адрес и
# загрузите элемент.
#
# В индексе 2 `$t5` равно 8, а `$t6` указывает на значение 30. Сумма пяти элементов дает 150.

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #база
        li   $t1, 0             #я
        li   $t2, 5             #длина
        li   $t3, 0             #аккумулятор

sum:
        #Инвариант цикла: $t3 представляет собой сумму от arr[0] до arr[i-1].
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #я * 4 байта
        add  $t6, $t0, $t5      #базовый + масштабированный индекс
        #$t6 теперь называет ровно один элемент; lw извлекает свое 32-битное значение.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
