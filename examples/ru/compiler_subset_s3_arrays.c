//@requires \length(row) == 3;
int row_sum(int row[]) {   //параметр является адресом: строка не копируется
  int total = 0;
  for (int i = 0; i < 3; i++) {
    total += row[i];   //row[i] компилируется в базу + i*4
  }
  return total;
}

int main(void) {
  //Тема о массивах S3: локальные массивы, списки инициализаторов, многомерные фигуры и параметры массивов.
  int matrix[2][3] = { {1, 2, 3}, {4, 5, 6} };   //два ряда по три слова, смежные в памяти
  int total = row_sum(matrix[0]) + row_sum(matrix[1]);   //матрица[0] и матрица[1] — это адреса, расположенные на расстоянии 12 байт друг от друга.

  //Ожидаемый результат: 21
  print_int(total);
  print_char(10);
  return 0;
}
