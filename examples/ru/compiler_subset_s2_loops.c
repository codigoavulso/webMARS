int main(void) {
  //Требуется C0-S2- или выше: для циклов, разрыва/продолжения и ++/--.
  int sum = 0;   //аккумулятор живет в регистре после компиляции

  for (int i = 0; i < 10; i++) {   //цикл for превращается в сравнение плюс обратную ветвь
    if ((i % 2) == 0) continue;   //continue переходит к приращению, пропуская тело
    if (i > 7) break;   //Break перескакивает за конец цикла
    sum += i;
  }

  int down = 3;
  down--;   //пост-декремент и пре-инкремент компилируются в одно и то же добавление
  int up = 3;
  ++up;

  //Ожидаемый результат: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
