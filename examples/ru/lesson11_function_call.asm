# 11 - Вызов функции
#
# Выполнение с задержкой разветвления. `jal` переходит к функции и помещает адрес следующей
# инструкции в `$ra`.
#
# Соглашение о вызовах передает 17 и 42 в `$a0` и `$a1`. Функция возвращает большее значение в
# `$v0`.
#
# Подключитесь к вызову, сравните `$ra` с адресом после `jal`, затем следуйте `jr $ra` обратно к
# вызывающему абоненту.

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #первый аргумент
        li   $a1, 42            #второй аргумент
        jal  maxof

        move $a0, $v0           #результат вернулся через $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof — это конечная функция, поэтому она может возвращать значение без сохранения $ra в стеке.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
