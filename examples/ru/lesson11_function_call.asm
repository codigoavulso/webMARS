# ==========================================================
#Урок 11 – Вызов функции
#
#THE PROBLEM
#Погрузиться в рутину легко. Возврата нет, потому что
#одна и та же процедура может быть вызвана из многих мест, и
#Обратный адрес каждый раз разный.
#
#WHAT THE HARDWARE DOES
#jal делает две вещи в одной инструкции: сохраняет
#адрес следующей инструкции в $ra, затем происходит переход. младший
#переходит к тому, что хранится в регистре, поэтому jr $ra возвращается.
#
#THE SOLUTION
#Все остальное — соглашение, а не схема: аргументы в
#$a0..$a3, в результате получается $v0. Нарушьте соглашение и кодекс
#все равно собирает - просто перестает взаимодействовать.
#
#WATCH FOR
#Встаньте на джал и прочитайте $ra. Сравните его с адресом
#строки после вызова в текстовом сегменте.
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #первый аргумент
        li   $a1, 42            #второй аргумент
        #jal изменяет как поток управления, так и $ra за одну архитектурную операцию.
        jal  maxof              #$ra = адрес следующей строки

        move $a0, $v0           #результат вернулся через $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof — это конечная функция, поэтому она может возвращать значение без сохранения $ra в стеке.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
