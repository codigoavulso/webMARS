# 01 - নিবন্ধন এবং অবিলম্বে
#
# অবিলম্বে নির্দেশ এনকোড করা হয়. একত্রিত করুন এবং পরীক্ষা করুন কোন মৌলিক নির্দেশ প্রতিটি `li`
# হয়ে যায়।
#
# দুটি লোড এবং যোগ মাধ্যমে ধাপ. রেজিস্টারে, `$t0 = 12`, `$t1 = 30` এবং `$t2 = 42` অনুসরণ করুন।
#
# 30 কে `0x12345678` দিয়ে প্রতিস্থাপন করার চেষ্টা করুন এবং পুনরায় একত্রিত করুন। বৃহত্তর
# ধ্রুবকের একাধিক মৌলিক নির্দেশের প্রয়োজন।

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls ব্যবহার করে $v0 পরিষেবা নির্বাচক হিসাবে এবং $a0 প্রথম আর্গুমেন্ট হিসাবে।
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li একটি ছদ্ম-নির্দেশ; অ্যাসেম্বল দেখায় যে এটি কোন বাস্তব নির্দেশে পরিণত হয়।
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # যোগফল একটি ভিন্ন রেজিস্টারে লেখা হয়।

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
