#THE PROBLEM
#ALU এর দুটি ইনপুট পোর্ট রয়েছে এবং উভয়ই তার সাথে সংযুক্ত
#রেজিস্টার ফাইল। উৎসে লেখা একটি সংখ্যা ক-এ নেই
#নিবন্ধন করুন, তাই এটি সরাসরি সেই পোর্টগুলিতে পৌঁছাতে পারে না।
#
#WHAT THE HARDWARE DOES
#একটি অবিলম্বে নির্দেশ শব্দ নিজেই ভিতরে ভ্রমণ.
#addi একটি 16-বিট ক্ষেত্র বহন করে; li একটি সুবিধা হয়
#অ্যাসেম্বলার এক বা দুটি বাস্তব নির্দেশে প্রসারিত হয়।
#
#THE SOLUTION
#প্রথমে একটি রেজিস্টারে ধ্রুবক ল্যান্ড করুন, তারপর ALU দিন
#দুটি রেজিস্টার পড়ুন এবং একটি তৃতীয় লিখুন।
#
#WATCH FOR
#প্রতি লাইনে একবার ধাপ করুন এবং $t0, $t1 এবং $t2 অনুসরণ করুন
#রেজিস্টার প্যানেল। শুধুমাত্র তৃতীয় লাইনটি স্পর্শ করে ALU।
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls ব্যবহার করে $v0 পরিষেবা নির্বাচক হিসাবে এবং $a0 প্রথম আর্গুমেন্ট হিসাবে।
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li একটি ছদ্ম-নির্দেশ; অ্যাসেম্বল দেখায় যে এটি কোন বাস্তব নির্দেশে পরিণত হয়।
        li   $t0, 12            #অবিলম্বে -> নিবন্ধন করুন
        li   $t1, 30            #অবিলম্বে -> নিবন্ধন করুন
        add  $t2, $t0, $t1      #ALU দুটি রেজিস্টার পড়ে

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
