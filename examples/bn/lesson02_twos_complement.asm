# 02 - দুজনের পরিপূরক
#
# 32-বিট দুই-এর পরিপূরক-এ, 5-এর বিটগুলিকে উল্টানো এবং 1 যোগ করলে -5-এর উপস্থাপনা তৈরি হয়।
#
# প্রোগ্রামটি একই মান দুটি উপায়ে গণনা করে: শূন্য থেকে `sub`, তারপর `nor` এবং `addi`।
#
# উভয় পথ প্রিন্ট -5. একই বিটগুলি হেক্সাডেসিমেলে কেমন দেখায় তা দেখতে রেজিস্টারে `0xFFFFFFFB`
# পরিদর্শন করুন।

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #শূন্য থেকে বিয়োগ করলে একটি বিয়োগ-চিহ্ন বিট ছাড়াই যোজক বিপরীত হয়।
        li   $t0, 5
        sub  $t1, $zero, $t0    #যোগকারী কাজ করে
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #অথবা $zero এর সাথে বিটওয়াইজ NOT; একটি যোগ করলে দুইটির পরিপূরক সম্পূর্ণ হয়।
        nor  $t2, $t0, $zero    #সমস্ত বিট উল্টে দিন
        addi $t2, $t2, 1        #একটি যোগ করুন
        move $a0, $t2           #উপরের হিসাবে একই মান
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
