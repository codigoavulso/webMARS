#THE PROBLEM
#একটি রেজিস্টার 32টি তার, প্রতিটি উচ্চ বা নিম্ন। কোনো তার নেই
#একটি বিয়োগ চিহ্নের জন্য, তবুও ঋণাত্মক সংখ্যা অবশ্যই কাজ করবে।
#
#WHAT THE HARDWARE DOES
#এটি একটি চিহ্ন হিসাবে উপরের বিটটি পড়ে, তবে একটি পৃথক পতাকা হিসাবে নয়:
#-n বিট প্যাটার্ন হিসাবে সংরক্ষণ করা হয় যা n-এ যোগ করা হয়, এতে মোড়ানো হয়
#শূন্য প্রতিটি বিট উল্টে এবং একটি যোগ করুন এবং আপনি এটি আছে.
#
#THE SOLUTION
#বিয়োগের কোন দ্বিতীয় সার্কিটের প্রয়োজন নেই। a - b হয়ে যায়
#a + (-b), তাই একটি যোগকারী উভয় ক্রিয়াকলাপ পরিবেশন করে।
#
#WATCH FOR
#উভয় অর্ধেক মুদ্রণ -5. দ্বিতীয়টি দীর্ঘ পথ ধরে পৌঁছেছে,
#nor এবং addi সহ, সাব অভ্যন্তরীণভাবে কী করে তা দেখাচ্ছে।
#0xFFFFFFFB দেখতে হেক্সাডেসিমেলে মান সেট করুন।
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #শূন্য থেকে বিয়োগ করলে একটি বিয়োগ-চিহ্ন বিট ছাড়াই যোজক বিপরীত হয়।
        li   $t0, 5
        sub  $t1, $zero, $t0    #যোগকারী কাজ করে
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #অথবা $zero এর সাথে বিটওয়াইজ NOT; একটি যোগ করলে দুইটির পরিপূরক সম্পূর্ণ হয়।
        nor  $t2, $t0, $zero    #সমস্ত বিট উল্টে দিন
        addi $t2, $t2, 1        #একটি যোগ করুন
        move $a0, $t2           #উপরের হিসাবে একই মান
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
