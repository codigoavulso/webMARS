#পাঠ 06 - একটি কাউন্টার, সফ্টওয়্যার এবং হার্ডওয়্যারে
#
#THE PROBLEM
#একটি হার্ডওয়্যার কাউন্টার হল একটি রেজিস্টার, একটি ইনক্রিমেন্টার এবং একটি
#তুলনাকারী একই মেশিনে লেখা দেখতে কেমন লাগে
#নির্দেশাবলী হিসাবে?
#
#WHAT THE HARDWARE DOES
#ঠিক সেই তিনটি অংশ, প্রতি নির্দেশে একটি: রেজিস্টার
#গণনা ধারণ করে, addi হল ইনক্রিমেন্টার, একটি শাখা সহ slt
#তুলনাকারী যে অন্য রাউন্ড সিদ্ধান্ত নেয়.
#
#THE SOLUTION
#একটি লুপ একটি নতুন ধারণা নয়. এটি অনুক্রমিক যুক্তি বানান
#বাইরে, ঘড়ি হিসাবে পিসি সঙ্গে.
#
#WATCH FOR
#$t0 হল গণনা রেজিস্টার এবং $t1 সীমা। মাধ্যমে ধাপ
#একটি পূর্ণ রাউন্ড এবং নাম কোন লাইন কোন অংশ.
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #গণনা রেজিস্টার
        li   $t1, 11            #সীমা

loop:
        #লুপ ইনভেরিয়েন্ট: $t0 প্রিন্ট করার জন্য পরবর্তী মান এবং $t1 এর নিচে থাকে।
        slt  $t2, $t0, $t1      #তুলনাকারী
        beq  $t2, $zero, endl   #গণনা সীমায় পৌঁছে গেলে প্রস্থান করুন

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #ঝাঁপ দেওয়ার আগে কাউন্টার আপডেট করা সমাপ্তির দিকে অগ্রগতির নিশ্চয়তা দেয়।
        addi $t0, $t0, 1        #যোগকারী
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
