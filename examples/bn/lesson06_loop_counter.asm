# 06 - একটি কাউন্টার হিসাবে লুপ
#
# `$t0` প্রিন্ট করার জন্য পরবর্তী সংখ্যা। `$t1` হল একচেটিয়া উপরের সীমা, তাই 11টি প্রিন্টের সীমা
# 1 থেকে 10 পর্যন্ত।
#
# প্রতিটি পুনরাবৃত্তির আগে তুলনা চলে। বৃদ্ধি সীমার দিকে অগ্রগতি করে, এবং লাফ চেকের পুনরাবৃত্তি
# করে।
#
# সীমা পরিবর্তন করুন 1 এবং চালান। প্রথম মুদ্রণের আগে প্রস্থান শাখা নেওয়া হয়।

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #গণনা রেজিস্টার
        li   $t1, 11            #সীমা

loop:
        # লুপ টেস্টে, $t0 হল পরবর্তী প্রার্থী। $t1 এর নিচে হলেই এটি প্রিন্ট করুন।
        slt  $t2, $t0, $t1      #তুলনাকারী
        beq  $t2, $zero, endl   #গণনা সীমায় পৌঁছে গেলে প্রস্থান করুন

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #ঝাঁপ দেওয়ার আগে কাউন্টার আপডেট করা সমাপ্তির দিকে অগ্রগতির নিশ্চয়তা দেয়।
        addi $t0, $t0, 1        #যোগকারী
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
