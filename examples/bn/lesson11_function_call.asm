# 11 - একটি ফাংশন কল করা
#
# বিলম্বিত শাখা বন্ধ সঙ্গে চালান. `jal` ফাংশনে লাফ দেয় এবং পরবর্তী নির্দেশের ঠিকানা `$ra` এ
# রাখে।
#
# কলিং কনভেনশন `$a0` এবং `$a1` মধ্যে 17 এবং 42 পাস করে। ফাংশনটি `$v0`-এ বড় মান প্রদান করে।
#
# কলে প্রবেশ করুন, `jal` এর পরে ঠিকানার সাথে `$ra` তুলনা করুন, তারপর `jr $ra` অনুসরণকারীকে ফিরে
# যান৷

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #প্রথম যুক্তি
        li   $a1, 42            #দ্বিতীয় যুক্তি
        jal  maxof

        move $a0, $v0           #ফলাফল $v0 এ ফিরে এসেছে
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof একটি পাতার ফাংশন, তাই এটি স্ট্যাকের উপর $ra সংরক্ষণ না করেই ফিরে আসতে পারে।
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
