#THE PROBLEM
#একটি রুটিন মধ্যে ঝাঁপ সহজ. ফিরে পাওয়া যায় না, কারণ
#একই রুটিন অনেক জায়গা থেকে বলা হতে পারে এবং
#প্রত্যাবর্তনের ঠিকানা প্রতিবার আলাদা হয়।
#
#WHAT THE HARDWARE DOES
#jal একটি নির্দেশে দুটি জিনিস করে: এটি সংরক্ষণ করে
#$ra এ নিম্নলিখিত নির্দেশের ঠিকানা, তারপর লাফ দেয়। জুনিয়র
#একটি রেজিস্টারে যা আছে তাতে লাফ দেয়, তাই jr $ra রিটার্ন করে।
#
#THE SOLUTION
#অন্য সব কিছু চুক্তি, সার্কিট্রি নয়: আর্গুমেন্ট ইন
#$a0।$a3, ফলাফল $v0। কনভেনশন এবং কোড ভঙ্গ করুন
#এখনও একত্রিত হয় - এটি কেবল ইন্টারঅপারেটিং বন্ধ করে দেয়।
#
#WATCH FOR
#জলে যান এবং $ra পড়ুন। ঠিকানার সাথে তুলনা করুন
#টেক্সট সেগমেন্টে কলের পরে লাইনের।
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #প্রথম যুক্তি
        li   $a1, 42            #দ্বিতীয় যুক্তি
        #jal একটি আর্কিটেকচারাল অপারেশনে নিয়ন্ত্রণ প্রবাহ এবং $ra উভয়ই পরিবর্তন করে।
        jal  maxof              #$ra = পরবর্তী লাইনের ঠিকানা

        move $a0, $v0           #ফলাফল $v0 এ ফিরে এসেছে
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof একটি পাতার ফাংশন, তাই এটি স্ট্যাকের উপর $ra সংরক্ষণ না করেই ফিরে আসতে পারে।
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
