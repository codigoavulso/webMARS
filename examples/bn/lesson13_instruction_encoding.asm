# 13 - একটি নির্দেশ একটি সংখ্যা
#
# পাঠ্য বিভাগে কোড কলাম একত্রিত করুন এবং পরিদর্শন করুন। প্রতিটি মৌলিক নির্দেশ ক্ষেত্রগুলিতে
# বিভক্ত একটি 32-বিট শব্দ।
#
# দুটি `add` নির্দেশাবলী তুলনা করুন। অপারেশন ক্ষেত্রগুলি মেলে, যখন রেজিস্টার ক্ষেত্রগুলি বিভিন্ন
# অপারেন্ডগুলিকে এনকোড করে৷
#
# `addi`-এ, নিম্ন 16 বিট অবিলম্বে 100 ধরে রাখে, যা `0x0064`। এটিকে 101 এ পরিবর্তন করুন এবং
# পরিবর্তনটি দেখতে পুনরায় একত্রিত করুন।

        .text
        .globl main
main:
        #সমাবেশের পরে কোড কলাম পরিদর্শন করুন: এই স্মৃতিবিদ্যা পাঠ্য হিসাবে সংরক্ষণ করা হয় না।
        add  $t0, $t1, $t2      #আর-টাইপ: অপকোড, আরএস, আরটি, আরডি, ফাংশন
        add  $t3, $t4, $t5      #একই আকৃতি, বিভিন্ন রেজিস্টার
        addi $t0, $t1, 100      #আই-টাইপ: ধ্রুবকটি শব্দে রয়েছে
        sll  $t0, $t1, 4        #স্থানান্তরের পরিমাণের নিজস্ব ক্ষেত্র রয়েছে
        j    tail               #জে-টাইপ: একটি ঠিকানা, একটি রেজিস্টার নয়
tail:
        #মৃত্যুদন্ড কার্যকর করার আগে li নিজেই প্রসারিত হয়; প্রসেসর শুধুমাত্র এনকোড করা শব্দ দেখে।
        li   $v0, 10
        syscall
