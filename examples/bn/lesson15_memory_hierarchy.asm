#THE PROBLEM
#নিচের দুটি লুপ একই অ্যারে পড়ে এবং একই কাজ করে
#লোড সংখ্যা। একটি বাস্তব মেশিনে একটি অনেক ধীর হয়. দ
#নির্দেশের সংখ্যা এটি ব্যাখ্যা করতে পারে না।
#
#WHAT THE HARDWARE DOES
#স্মৃতি একক শব্দ প্রদান করে না। একটি মিস একটি সম্পূর্ণ আনা
#ব্লক, প্রতিবেশী শব্দ শীঘ্রই চাওয়া হবে যে পণ.
#একজনের একটি ধাপ সেই বাজি সংগ্রহ করে; ষোল বেতনের একটি ধাপ
#একটি ব্লকের জন্য এবং এটির একটি শব্দ পড়ে।
#
#THE SOLUTION
#কোডে কিছুই পরিবর্তন হয় না। স্থানীয়তা একটি সম্পত্তি
#অ্যাক্সেস প্যাটার্ন, এবং এটি এমন প্যাটার্ন যা অবশ্যই ঠিক করা উচিত।
#
#WATCH FOR
#টুল খুলুন > ডেটা ক্যাশে সিমুলেটর, কানেক্ট টু MIPS টিপুন,
#তারপর চালানো দুটি লুপের হিট রেট তুলনা করুন। উভয় যোগফল
#প্রিন্ট 0 কারণ অ্যারেটি শূন্য - সংখ্যাটি নয়
#এখানে পয়েন্ট, আঘাত হার হয়.
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- প্রতিটি ব্লকের প্রতিটি শব্দ ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #অনুক্রমিক সূচীগুলি এগিয়ে যাওয়ার আগে প্রতিটি ক্যাশে ব্লক থেকে শব্দগুলি পুনরায় ব্যবহার করে।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- প্রতি ব্লকে একটি শব্দ, ষোলটি শব্দ বাদে ----
        li   $t1, 0
        li   $t3, 0
far:
        #প্রতি পুনরাবৃত্তি 16 স্কিপ 64 বাইট যোগ করা: সাধারণত একটি সম্পূর্ণ ক্যাশে ব্লক।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
