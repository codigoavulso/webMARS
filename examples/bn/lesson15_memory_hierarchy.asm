# 15 - কেন স্ট্রাইড গতি পরিবর্তন করে?
#
# উভয় লুপ একই অ্যারে ব্যবহার করে। প্রথমটি সমস্ত 256 শব্দ পড়ে; দ্বিতীয়টি প্রতি 16তম শব্দটি
# পড়ে, মাত্র 16টি লোড তৈরি করে।
#
# 16টি শব্দের ক্যাশে ব্লক সহ, অনুক্রমিক রিড প্রতিটি আনা ব্লক পুনরায় ব্যবহার করতে পারে। দ্বিতীয়
# লুপ প্রতিটি লোডে একটি নতুন ব্লকে অগ্রসর হয়।
#
# সিমুলেটরটি MIPS-এর সঙ্গে যুক্ত করুন, «সক্রিয়» টিক দিন এবং ব্লকের আকার ১৬ ওয়ার্ড রাখুন।
# প্রথম লুপ পরিদর্শন করতে `far` এ ব্রেকপয়েন্ট সহ ডেটা ক্যাশে সিমুলেটর ব্যবহার করুন। দ্বিতীয়
# লুপ চালানোর আগে সেখানে ক্যাশে পরিসংখ্যান রিসেট করুন এবং হিট রেট তুলনা করুন।

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# অনুক্রমিক পাস: সমস্ত 256 শব্দ।
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #অনুক্রমিক সূচীগুলি এগিয়ে যাওয়ার আগে প্রতিটি ক্যাশে ব্লক থেকে শব্দগুলি পুনরায় ব্যবহার করে।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# স্ট্রাইডেড পাস: প্রতি ষোলটি শব্দে একটি লোড।
        li   $t1, 0
        li   $t3, 0
far:
        # পরবর্তী ঠিকানাটি 64 বাইট দূরে: চার বাইটে ষোলটি শব্দ।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
