#পাঠ 10 - স্ট্যাকটি একটি রেজিস্টার এবং একটি অফসেট
#
#THE PROBLEM
#32টি রেজিস্টার রয়েছে এবং সেগুলি প্রতিটি অংশ দ্বারা ভাগ করা হয়
#কোড একটি মান কোথায় যায় যখন এটি কাজ করে বেঁচে থাকতে হবে
#সেই রেজিস্টারগুলো কি পুনরায় ব্যবহার করা হবে?
#
#WHAT THE HARDWARE DOES
#বিশেষ কিছু না। $sp একটি সাধারণ নিবন্ধন যা
#মেমরির দিকে নির্দেশ করে এবং স্ট্যাকের দিকে বৃদ্ধি পায়
#নিম্ন ঠিকানাগুলি বিশুদ্ধভাবে নিয়মানুযায়ী।
#
#THE SOLUTION
#স্থান সংরক্ষণ করা হল $sp থেকে একটি বিয়োগ, এটিকে ছেড়ে দেওয়া
#সংযোজন পুশ এবং পপ শুধু sw এবং lw।
#
#WATCH FOR
#রেজিস্টারগুলি ইচ্ছাকৃতভাবে দোকানের মধ্যে সাফ করা হয়
#এবং লোড, তাই মুদ্রিত মান শুধুমাত্র আসতে পারে
#স্মৃতি থেকে ফিরে $sp 8 এবং পিছনে সরানো দেখুন।
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #স্ট্যাক নিচের দিকে বৃদ্ধি পায়, তাই বরাদ্দ $sp থেকে বিয়োগ হয়।
        addi $sp, $sp, -8       #দুটি শব্দ সংরক্ষণ করুন
        sw   $t0, 0($sp)        #ধাক্কা
        sw   $t1, 4($sp)

        li   $t0, 0             #রেজিস্টার ক্লোবার
        li   $t1, 0

        lw   $t0, 0($sp)        #পপ
        lw   $t1, 4($sp)
        #প্রতিটি বরাদ্দ অবশ্যই ভারসাম্যপূর্ণ হতে হবে যাতে কলকারী তার আসল $sp দেখতে পান।
        addi $sp, $sp, 8        #মুক্তি

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
