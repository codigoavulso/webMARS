# 10 - স্ট্যাক
#
# নিয়ম অনুযায়ী স্ট্যাক নিম্ন ঠিকানার দিকে বৃদ্ধি পায়। দুটি শব্দের জন্য স্থান সংরক্ষণ করতে
# `$sp` থেকে 8 বিয়োগ করুন।
#
# প্রোগ্রামটি `sw` দিয়ে দুটি রেজিস্টার সংরক্ষণ করে, তাদের সাফ করে, তারপর `lw` দিয়ে তাদের মান
# পুনরুদ্ধার করে।
#
# রিজার্ভেশনের আগে, দুটি স্টোরের সময় এবং রিলিজের পরে `$sp` দেখুন। এর চূড়ান্ত মান এর প্রাথমিক
# মানের সাথে মেলে।

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #স্ট্যাক নিচের দিকে বৃদ্ধি পায়, তাই বরাদ্দ $sp থেকে বিয়োগ হয়।
        addi $sp, $sp, -8       #দুটি শব্দ সংরক্ষণ করুন
        sw   $t0, 0($sp)        #ধাক্কা
        sw   $t1, 4($sp)

        li   $t0, 0             #রেজিস্টার ক্লোবার
        li   $t1, 0

        lw   $t0, 0($sp)        #পপ
        lw   $t1, 4($sp)
        #প্রতিটি বরাদ্দ অবশ্যই ভারসাম্যপূর্ণ হতে হবে যাতে কলকারী তার আসল $sp দেখতে পান।
        addi $sp, $sp, 8        #মুক্তি

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
