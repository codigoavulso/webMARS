#THE PROBLEM
#একটি সিদ্ধান্ত এক বিট প্রয়োজন, কিন্তু দুটি 32-বিট সংখ্যা তুলনা
#একটি বিয়োগ. কিভাবে একটি বিয়োগ একটি পছন্দ হয়ে ওঠে?
#
#WHAT THE HARDWARE DOES
#slt বিয়োগ করে এবং চিহ্ন ছাড়া সবকিছু ফেলে দেয়,
#0 বা 1 লেখা। শাখাটি তখন সেই বিটটিকে পিসিতে ফিড করে
#লজিক, যা হয় একটি অফসেট যোগ করে বা পিসিকে অগ্রসর হতে দেয়।
#
#THE SOLUTION
#একটি রেজিস্টারের সাথে তুলনা করুন, সেই রেজিস্টারে শাখা। নিয়ন্ত্রণ
#ফ্লো হল গাণিতিক প্লাস পিসিতে এক মাল্টিপ্লেক্সার।
#
#WATCH FOR
#slt-এর পরে, $t2 1 ধারণ করে। beq এর পাশ কাটিয়ে পিসি দেখুন
#স্ট্যাটাস বারে: এটি চার দ্বারা অগ্রসর হওয়ার পরিবর্তে লাফ দেয়।
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ক
        li   $t1, 12            #খ
        #slt তুলনাটিকে একটি সাধারণ পূর্ণসংখ্যা হিসাবে বাস্তবায়িত করে, কখনও লুকানো পতাকা হিসাবে নয়।
        slt  $t2, $t0, $t1      #t2 = 1 যদি a < b
        #যে বুলিয়ান ফলাফল শূন্য শুধুমাত্র যখন নটলেস শাখা.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
