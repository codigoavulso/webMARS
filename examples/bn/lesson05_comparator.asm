# 05 - তুলনাকারী এবং শাখা
#
# `slt` দুটি স্বাক্ষরিত পূর্ণসংখ্যার তুলনা করে এবং প্রথমটি ছোট হলে 1 লেখে, অথবা অন্যথায় 0।
#
# 7 এবং 12 এর জন্য, `$t2` হল 1, তাই `beq` লাফিয়ে `notless` এ যাবে না এবং কার্যকর করা পরবর্তী
# নির্দেশে চলতে থাকবে।
#
# বিলম্বিত শাখা বন্ধ হলে, `beq` অতিক্রম করুন এবং পিসি পর্যবেক্ষণ করুন। দুটি ইনপুট মান অদলবদল
# করুন এবং নতুন গন্তব্যের তুলনা করুন।

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ক
        li   $t1, 12            #খ
        #slt তুলনাটিকে একটি সাধারণ পূর্ণসংখ্যা হিসাবে বাস্তবায়িত করে, কখনও লুকানো পতাকা হিসাবে নয়।
        slt  $t2, $t0, $t1      #t2 = 1 যদি a < b
        #যে বুলিয়ান ফলাফল শূন্য শুধুমাত্র যখন নটলেস শাখা.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
