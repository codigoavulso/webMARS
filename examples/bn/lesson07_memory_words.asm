# 07 - স্মৃতিতে শব্দ
#
# মেমরি ঠিকানা বাইট গণনা. প্রতিটি শব্দ চারটি বাইট দখল করে, তাই `lw` এবং `sw` এখানে অফসেট 0, 4
# এবং 8 ব্যবহার করুন৷
#
# একটি শব্দ ঠিকানা অবশ্যই চারটির একাধিক হতে হবে। 4 এর পরিবর্তে অফসেট 1 ব্যবহার করা এই প্রোগ্রামে
# একটি প্রান্তিককরণ ব্যতিক্রম ঘটায়।
#
# স্টোরের পরে, ডেটা সেগমেন্টে `cell` দেখুন। তিনটি সন্নিহিত শব্দে 111, 222 এবং 333 থাকা উচিত।

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #ভিত্তি ঠিকানা

        #নীচের প্রতিটি অফসেট $t0 এর সাথে আপেক্ষিক এবং শব্দ-সারিবদ্ধ থাকে।
        li   $t1, 111
        sw   $t1, 0($t0)        #প্রথম শব্দ
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 বাইট = পরবর্তী শব্দ
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 বাইট

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw পূর্বে sw দ্বারা লিখিত একই 32-বিট মানগুলি পুনর্গঠন করে।
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
