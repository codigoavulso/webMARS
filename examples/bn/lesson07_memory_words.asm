#পাঠ 07 - মেমরিতে শব্দ, এবং কেন ঠিকানাগুলি চার দ্বারা লাফিয়ে ওঠে
#
#THE PROBLEM
#মেমরি একবারে একটি বাইট সম্বোধন করা হয়, কিন্তু একটি রেজিস্টার ধারণ করে
#চার বাইট। একটি একক ঠিকানা আসলে কি নির্বাচন করে?
#
#WHAT THE HARDWARE DOES
#lw এবং sw এক অ্যাক্সেসে চার বাইট সরান, তাই পরপর
#শব্দ চারটি ঠিকানা আলাদা করে বসে। কম দুই বিট
#ঠিকানা শূন্য হতে হবে: যে প্রান্তিককরণ করতে দেয় কি
#হার্ডওয়্যার এক চক্রে একটি সম্পূর্ণ শব্দ আনয়ন করে।
#
#THE SOLUTION
#ঠিকানার পাটিগণিত বাইটে করা হয়, তাই শব্দের মধ্যে একটি সূচক
#সর্বদা চার দ্বারা স্কেল করা হয়।
#
#WATCH FOR
#একত্রিত করুন, তারপর 0x10010000 এ ডেটা সেগমেন্ট খুলুন। দ
#একটি সারির সন্নিহিত কলামে তিনটি মান উপস্থিত হয়।
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #ভিত্তি ঠিকানা

        #নীচের প্রতিটি অফসেট $t0 এর সাথে আপেক্ষিক এবং শব্দ-সারিবদ্ধ থাকে।
        li   $t1, 111
        sw   $t1, 0($t0)        #প্রথম শব্দ
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 বাইট = পরবর্তী শব্দ
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 বাইট

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw পূর্বে sw দ্বারা লিখিত একই 32-বিট মানগুলি পুনর্গঠন করে।
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
