#Hello World for Run I/O
#একটি সাধারণ বার্তা প্রিন্ট করে এবং প্রস্থান করে।
#এটি ডেটা/টেক্সট স্প্লিট এবং সিস্কাল কনভেনশনের সবচেয়ে ছোট উদাহরণ।

.data
#.asciiz syscall 4-এর জন্য প্রয়োজনীয় শূন্য টার্মিনেটর অনুসরণ করে অক্ষর সংরক্ষণ করে।
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #$v0-এ প্রিন্ট-স্ট্রিং (4) নির্বাচন করুন এবং $a0 এ স্ট্রিং ঠিকানাটি পাস করুন।
  li $v0, 4
  la $a0, msg
  syscall

  #প্রস্থান করুন (10) সিমুলেটেড প্রোগ্রামটিকে পরিষ্কারভাবে থামিয়ে দেয়।
  li $v0, 10
  syscall
