#THE PROBLEM
#একটি লোড নির্দেশ একটি বেস রেজিস্টার এবং একটি ধ্রুবক অফার করে
#অফসেট আর কিছু না। তাহলে কিভাবে একটি [i] পৌঁছানো হয় যখন আমি শুধুমাত্র
#রান টাইমে পরিচিত, রেজিস্টারে বসে?
#
#WHAT THE HARDWARE DOES
#এটি রেজিস্টারে যা থাকে তার সাথে বেস যোগ করে। সূচক
#তাই ইতিমধ্যেই বাইটে থাকতে হবে, উপাদানে নয়।
#
#THE SOLUTION
#উপাদান আকার দ্বারা সূচক স্কেল, তারপর যোগ করুন. চার-বাইটের জন্য
#শব্দ যে স্কেলিং হল দুটি বামে একটি স্থানান্তর, যার খরচ হয়
#কিছুই না
#
#WATCH FOR
#তিনটি লাইন sll, add, lw হল যা একটি [i] কম্পাইল করে।
#একটি পুনরাবৃত্তির মধ্য দিয়ে যান এবং $t5 এবং $t6 পড়ুন।
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #ভিত্তি
        li   $t1, 0             #i
        li   $t2, 5             #দৈর্ঘ্য
        li   $t3, 0             #সঞ্চয়কারী

sum:
        #লুপ ইনভেরিয়েন্ট: $t3 হল arr[0] এর মাধ্যমে arr[i-1] এর যোগফল।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i*4 বাইট
        add  $t6, $t0, $t5      #ভিত্তি + স্কেল করা সূচক
        #$t6 এখন ঠিক একটি উপাদানের নাম দেয়; lw এর 32-বিট মান নিয়ে আসে।
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
