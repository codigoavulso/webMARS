# 09 - একটি অ্যারে সূচীকরণ
#
# প্রতিটি অ্যারে উপাদান চার বাইট দখল করে। এর বাইট অফসেট গণনা করতে সূচকটি দুই দ্বারা বামে
# স্থানান্তর করুন।
#
# অনুক্রমটি অনুসরণ করুন `sll`, `add`, `lw`: সূচকটি স্কেল করুন, মূল ঠিকানা যোগ করুন এবং উপাদানটি
# লোড করুন।
#
# সূচী 2 এ, `$t5` 8 এবং `$t6` মান 30 পয়েন্ট করে। পাঁচটি উপাদান 150 পর্যন্ত যোগ করে।

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #ভিত্তি
        li   $t1, 0             #i
        li   $t2, 5             #দৈর্ঘ্য
        li   $t3, 0             #সঞ্চয়কারী

sum:
        #লুপ ইনভেরিয়েন্ট: $t3 হল arr[0] এর মাধ্যমে arr[i-1] এর যোগফল।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i*4 বাইট
        add  $t6, $t0, $t5      #ভিত্তি + স্কেল করা সূচক
        #$t6 এখন ঠিক একটি উপাদানের নাম দেয়; lw এর 32-বিট মান নিয়ে আসে।
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
