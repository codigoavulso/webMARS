//@requires \length(row) == 3;
int row_sum(int row[]) {   //প্যারামিটারটি একটি ঠিকানা: সারিটি অনুলিপি করা হয়নি
  int total = 0;
  for (int i = 0; i < 3; i++) {
    total += row[i];   //সারি[i] বেস + i*4 এ কম্পাইল করে
  }
  return total;
}

int main(void) {
  //S3 অ্যারে বিষয়: স্থানীয় অ্যারে, ইনিশিয়ালাইজার তালিকা, বহুমাত্রিক আকার এবং অ্যারে প্যারামিটার।
  int matrix[2][3] = { {1, 2, 3}, {4, 5, 6} };   //তিনটি শব্দের দুটি সারি, স্মৃতিতে সংলগ্ন
  int total = row_sum(matrix[0]) + row_sum(matrix[1]);   //ম্যাট্রিক্স[0] এবং ম্যাট্রিক্স[1] হল ঠিকানা 12 বাইট আলাদা

  //প্রত্যাশিত আউটপুট: 21
  print_int(total);
  print_char(10);
  return 0;
}
