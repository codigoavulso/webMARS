# 14 - 32 বিটে বাস্তব সংখ্যা
#
# একটি একক-নির্ভুল ফ্লোটে একটি সাইন বিট, আটটি সূচক বিট এবং 23টি ভগ্নাংশ বিট থাকে।
#
# `lwc1` একটি ফ্লোটিং-পয়েন্ট রেজিস্টারে বিট প্যাটার্ন কপি করে। তারপর `add.s` 3.5 এবং 1.25 যোগ
# করে 4.75 উৎপন্ন করে।
#
# ফ্লোটিং পয়েন্ট প্রতিনিধিত্ব টুলে 4.75 এবং 0.1 এর এনকোডিং তুলনা করুন। 4.75 সঠিক; 0.1 বৃত্তাকার
# প্রয়োজন।

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU রেজিস্টার ফাইলে
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU যোগকারী

        #Syscall 2 বিশেষভাবে $f12-এ তার ফ্লোট আর্গুমেন্ট আশা করে।
        mov.s $f12, $f4
        li   $v0, 2             #প্রিন্ট ফ্লোট
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
