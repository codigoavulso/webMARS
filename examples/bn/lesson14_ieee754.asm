#
#THE PROBLEM
#একটি পূর্ণসংখ্যা রেজিস্টারে 3.5 এর কোন স্থান নেই। যেখানে আছে
#ভগ্নাংশ অংশ যান, এবং কিভাবে একটি খুব বড় সংখ্যা সংরক্ষণ করা হয়
#একটি খুব ছোট এক হিসাবে একই 32 বিট?
#
#WHAT THE HARDWARE DOES
#IEEE-754 শব্দটিকে তিনটি ক্ষেত্রে বিভক্ত করে: একটি সাইন বিট,
#আটটি সূচক বিট এবং তেইশটি ভগ্নাংশ বিট। দ
#এক্সপোনেন্ট বাইনারি পয়েন্ট স্লাইড করে, যে কারণে ফরম্যাট
#ফ্লোটিং পয়েন্ট বলে।
#
#THE SOLUTION
#একটি পৃথক রেজিস্টার ফাইল ($f0..$f31) এবং একটি পৃথক অ্যাডার
#এই মানগুলি পরিচালনা করুন, এই কারণেই স্মৃতিবিদ্যা আলাদা:
#লোড করতে lwc1, যোগ করতে add.s, প্রিন্ট করতে syscall 2।
#
#WATCH FOR
#টুল খুলুন > ফ্লোটিং পয়েন্ট রিপ্রেজেন্টেশন এবং 3.5 লিখুন।
#তিনটি ক্ষেত্র দেখুন, তারপর পরীক্ষা করুন যে 4.75 সঠিক -
#0.1 এর বিপরীতে, যার কোন সীমাবদ্ধ বাইনারি ভগ্নাংশ নেই।
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #পূর্ণসংখ্যা ঠিকানাগুলি এখনও ডেটা সনাক্ত করে; lwc1 তার বিটগুলিকে COP1 এ স্থানান্তরিত করে।
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU রেজিস্টার ফাইলে
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU যোগকারী

        #Syscall 2 বিশেষভাবে $f12-এ তার ফ্লোট আর্গুমেন্ট আশা করে।
        mov.s $f12, $f4
        li   $v0, 2             #প্রিন্ট ফ্লোট
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
