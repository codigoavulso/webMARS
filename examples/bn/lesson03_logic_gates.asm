#THE PROBLEM
#AND, OR এবং XOR হল এক-বিট গেট। একটি রেজিস্টার 32 বিট ধারণ করে।
#যে প্রস্থ একটি গেট মানে কি?
#
#WHAT THE HARDWARE DOES
#এটি পাশে পাশে গেটের 32 টি কপি রাখে। এর বিট 0
#ফলাফল শুধুমাত্র প্রতিটি অপারেন্ডের বিট 0 এর উপর নির্ভর করে, শুধুমাত্র বিট 1 এর উপর
#বিট 1, এবং তাই। তাদের মধ্যে কোনো বহনযোগ্য ভ্রমণ নেই।
#
#THE SOLUTION
#সেই স্বাধীনতাই মুখোশকে কাজ করে: কোনটি বেছে নিন
#AND এর সাথে রাখার জন্য বিট, OR এর সাথে একটিতে জোর করুন, XOR] দিয়ে ফ্লিপ করুন।
#
#WATCH FOR
#0xCC হল 11001100 এবং মাস্ক 0x0F হল 00001111। AND রাখে।
#নিম্ন চারটি বিট, অথবা সেগুলিকে সেট করে, XOR এগুলিকে উল্টে দেয়। শুধুমাত্র
#নিম্ন নিবল কখনও পরিবর্তন.
# ==========================================================
        .data
ma:     .asciiz "AND keeps the low nibble: "
mo:     .asciiz "OR sets the low nibble:   "
mx:     .asciiz "XOR flips the low nibble: "
        .text
        .globl main
main:
        li   $t0, 204           #0xCC
        li   $t1, 15            #0x0F মুখোশ

        la   $a0, ma
        li   $v0, 4
        syscall
        #AND মাস্কে শূন্য থাকে এমন প্রতিটি অবস্থান পরিষ্কার করে।
        and  $t2, $t0, $t1
        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mo
        li   $v0, 4
        syscall
        or   $t3, $t0, $t1
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mx
        li   $v0, 4
        syscall
        #XOR শুধুমাত্র মুখোশের দ্বারা নির্বাচিত অবস্থানগুলিকে টগল করে৷
        xor  $t4, $t0, $t1
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
