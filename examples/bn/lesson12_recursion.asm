#
#THE PROBLEM
#একটি পুনরাবৃত্ত কল $ra এবং আর্গুমেন্ট রেজিস্টার ওভাররাইট করে।
#বাইরের কলটির তখন আর ফিরে যাওয়ার উপায় নেই এবং কোন ধারণা নেই যে এটি কী
#নিজস্ব n ছিল।
#
#WHAT THE HARDWARE DOES
#এটি একটি $ra প্রদান করে, তাদের একটি স্ট্যাক নয়। কিছুই সংরক্ষণ করা হয় না
#স্বয়ংক্রিয়ভাবে; যদি কোডটি সংরক্ষণ না করে তবে এটি চলে গেছে।
#
#THE SOLUTION
#প্রতিটি অ্যাক্টিভেশন স্ট্যাকের একটি ফ্রেম খোলে, যা রাখে
#কল করার পরেও প্রয়োজন হবে, এবং পথে এটি পুনরুদ্ধার করবে
#আউট স্ট্যাকের গভীরতা হল পুনরাবৃত্তি গভীরতা।
#
#WATCH FOR
#mul-এ একটি ব্রেকপয়েন্ট সেট করুন এবং $sp প্রতি 8 দ্বারা নামা দেখুন
#স্তর n এর পাঁচটি সংরক্ষিত কপি যা তৈরি করে
#ফিরে আসার পথে গুণন।
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #প্রতিটি আমন্ত্রণ একটি স্বতন্ত্র আট-বাইট ফ্রেমের মালিক।
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #এই কল ফেরত ঠিকানা
        sw   $a0, 4($sp)        #এই কল এর এন

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #বেস কেস: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #আমাদের n আবার
        mul  $v0, $v0, $a0

factend:
        #কলী অবস্থা পুনরুদ্ধার করুন এবং প্রবেশের সময় বরাদ্দকৃত ফ্রেমটি ঠিক বাদ দিন।
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
