# 12 - পুনরাবৃত্তি এবং ফ্রেম
#
# একটি পুনরাবৃত্ত কল `$ra` ওভাররাইট করে এবং তার নিজস্ব যুক্তির জন্য `$a0` ব্যবহার করে। কল করার
# আগে উভয় মান সংরক্ষণ করুন.
#
# 5 থেকে 1 পর্যন্ত প্রতিটি মানের জন্য `fact` এ ধাপ করুন। প্রতিটি কল আট বাইট সংরক্ষণ করে, যার
# মধ্যে 1 রিটার্ন করা কল সহ।
#
# ফেরার পথ দেখতে `mul`-এ একটি ব্রেকপয়েন্ট সেট করুন। প্রতিটি কল তার নিজস্ব যুক্তি পুনরায় লোড
# করে, গুণিত করে এবং তার ফ্রেম প্রকাশ করে।

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #প্রতিটি আমন্ত্রণ একটি স্বতন্ত্র আট-বাইট ফ্রেমের মালিক।
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #এই কল ফেরত ঠিকানা
        sw   $a0, 4($sp)        #এই কল এর এন

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #বেস কেস: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #আমাদের n আবার
        mul  $v0, $v0, $a0

factend:
        # এই কলের ফ্রেম প্রকাশ করার আগে সংরক্ষিত ফেরত ঠিকানা পুনরুদ্ধার করুন।
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
