#পাঠ 04 - স্থানান্তর, বা তারের সাথে গুণ করা
#
#THE PROBLEM
#একটি সাধারণ গুণক হল সবচেয়ে ব্যয়বহুল ব্লকগুলির মধ্যে একটি
#একটি ডেটাপথ। 8 দিয়ে গুণ করলে এতটা খরচ হবে না।
#
#WHAT THE HARDWARE DOES
#একটি স্থানান্তর মোটেও গাণিতিক নয়: এটি একই বিট পড়া
#বিভিন্ন তার থেকে। n দ্বারা বাম স্থানান্তর 2^n দ্বারা গুণিত হয়
#এবং খরচ শুধুমাত্র রাউটিং.
#
#THE SOLUTION
#দুজনের ক্ষমতা পাল্টে যায়। দুটি ডান শিফট নোট করুন: srl
#উপরে শূন্য ফিড করে, sra সাইন বিট কপি করে, তাই শুধুমাত্র
#sra একটি ঋণাত্মক সংখ্যা সঠিকভাবে ভাগ করে।
#
#WATCH FOR
#-16 >> 2 sra দিয়ে -4 দেয় কিন্তু srl এর সাথে বিশাল পজিটিভ। দ
#বিট একইভাবে সরানো হয়েছে; শুধুমাত্র শীর্ষে যা প্রবেশ করানো হয়েছে তা ভিন্ন।
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #তিনটি বাম স্থানান্তর 2^3 দ্বারা গুণিত হয় যখন শুধুমাত্র 32 ফলাফল বিট বজায় থাকে।
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #বিভিন্ন ইনকামিং বিট দেখতে হেক্সাডেসিমেলে $t3 এবং $t4 তুলনা করুন।
        sra  $t3, $t2, 2        #চিহ্ন সংরক্ষিত: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #শূন্য স্থানান্তরিত হয়েছে: বিশাল ইতিবাচক
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
