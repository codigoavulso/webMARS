# 04 - দুটির স্থানান্তর এবং ক্ষমতা
#
# একটি বাম স্থানান্তর 3 দ্বারা 8 দ্বারা গুণিত হয় যখন ফলাফল ফিট হয়। প্রান্তের অতীত স্থানান্তরিত
# বিট বাতিল করা হয়।
#
# ডানদিকে, `srl` শূন্য দিয়ে পূর্ণ করে এবং `sra` সাইন বিট কপি করে। 2 দ্বারা স্থানান্তরিত -16 এর
# জন্য, যথাক্রমে 1073741820 এবং -4 আশা করুন।
#
# `sra` দিয়ে -15 চেষ্টা করুন। ফলাফল হল -4 কারণ শিফট বৃত্তাকার নিচে; স্বাক্ষরিত বিভাজন রাউন্ড
# শূন্যের দিকে।

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #তিনটি বাম স্থানান্তর 2^3 দ্বারা গুণিত হয় যখন শুধুমাত্র 32 ফলাফল বিট বজায় থাকে।
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #বিভিন্ন ইনকামিং বিট দেখতে হেক্সাডেসিমেলে $t3 এবং $t4 তুলনা করুন।
        sra  $t3, $t2, 2        #চিহ্ন সংরক্ষিত: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #শূন্য স্থানান্তরিত হয়েছে: বিশাল ইতিবাচক
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
