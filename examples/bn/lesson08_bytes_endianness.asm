#ঐ ঠিকানার নাম?
#
#WHAT THE HARDWARE DOES
#সেই পছন্দটি হল বাইট অর্ডার, এবং এটি একটি ওয়্যারিং সিদ্ধান্ত
#পুরো মেশিনের জন্য একবার। MIPS এখানে লিটল-এন্ডিয়ান: the
#সর্বনিম্ন গুরুত্বপূর্ণ বাইট সর্বনিম্ন ঠিকানায় বসবাস করে।
#
#THE SOLUTION
#একটি শব্দ সংরক্ষণ করুন, তারপর এটি একবারে একটি বাইট পড়ুন এবং দিন
#আদেশ আপনার জন্য প্রশ্নের উত্তর.
#
#WATCH FOR
#0x04030201 1 2 3 4 হিসাবে ফিরে আসে। বাইটটি সর্বশেষ লেখা হয়েছিল
#আক্ষরিক প্রথম পড়া হয়. lb এর পরিবর্তে lbu ব্যবহার করা হয় তাই a
#127 এর উপরে বাইট সাইন-বর্ধিত নয়।
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #বাইট 01 কম গুরুত্বপূর্ণ
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #বাইট অফসেট
bloop:
        #লুপটি সংরক্ষিত শব্দের ভিতরে 0, 1, 2 এবং 3 অফসেট পরিদর্শন করে।
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #কার্যকরী ঠিকানা = ভিত্তি ঠিকানা + বর্তমান বাইট অফসেট।
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #স্বাক্ষরবিহীন বাইট
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
