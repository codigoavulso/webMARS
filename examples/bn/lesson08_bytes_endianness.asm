# 08 - বাইট এবং বাইট অর্ডার
#
# এই সিমুলেটরের লিটল-এন্ডিয়ান মেমরিতে, একটি শব্দের সর্বনিম্ন উল্লেখযোগ্য বাইট সর্বনিম্ন
# ঠিকানায় থাকে।
#
# একটি শব্দ হিসাবে `0x04030201` সংরক্ষণ করুন এবং অফসেট 0 থেকে 3 বাইট হিসাবে পড়ুন। আউটপুট হল 1,
# 2, 3, 4।
#
# `0xFF` এর একটি কম বাইট চেষ্টা করুন। `lbu` সহ একটি স্বাক্ষরবিহীন লোড 255 দেয়, যখন `lb` সহ একটি
# স্বাক্ষরিত লোড -1 দেয়।

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #বাইট 01 কম গুরুত্বপূর্ণ
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #বাইট অফসেট
bloop:
        #লুপটি সংরক্ষিত শব্দের ভিতরে 0, 1, 2 এবং 3 অফসেট পরিদর্শন করে।
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #কার্যকরী ঠিকানা = ভিত্তি ঠিকানা + বর্তমান বাইট অফসেট।
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #স্বাক্ষরবিহীন বাইট
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
