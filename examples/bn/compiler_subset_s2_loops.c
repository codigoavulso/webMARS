int main(void) {
  //প্রয়োজন C0-S2- বা উচ্চতর: লুপ, বিরতি/চালিয়ে, এবং ++/--এর জন্য।
  int sum = 0;   //সঞ্চয়কারী একবার সংকলিত একটি রেজিস্টারে থাকে

  for (int i = 0; i < 10; i++) {   //a for loop একটি তুলনা প্লাস একটি পশ্চাদগামী শাখা হয়ে যায়
    if ((i % 2) == 0) continue;   //শরীর বাদ দিয়ে, বৃদ্ধিতে জাম্প চালিয়ে যান
    if (i > 7) break;   //বিরতি লুপের শেষের দিকে চলে যায়
    sum += i;
  }

  int down = 3;
  down--;   //পোস্ট-ডিক্রিমেন্ট এবং প্রি-ইনক্রিমেন্ট একই অ্যাডে কম্পাইল করুন
  int up = 3;
  ++up;

  //প্রত্যাশিত আউটপুট: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
