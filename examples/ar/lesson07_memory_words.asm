# 07 - كلمات في الذاكرة
#
# عناوين الذاكرة تحسب البايتات. تشغل كل كلمة أربعة بايتات، لذا استخدم `lw` و`sw` الإزاحات 0 و4
# و8 هنا.
#
# يجب أن يكون عنوان الكلمة مضاعفًا للأربعة. يؤدي استخدام الإزاحة 1 بدلاً من 4 إلى حدوث استثناء
# في المحاذاة في هذا البرنامج.
#
# بعد المتاجر، انظر إلى `cell` في مقطع البيانات. يجب أن تحتوي الكلمات الثلاث المتجاورة على 111
# و222 و333.

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #العنوان الأساسي

        #كل إزاحة أدناه مرتبطة بـ $t0 وتظل محاذية للكلمات.
        li   $t1, 111
        sw   $t1, 0($t0)        #الكلمة الأولى
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بايت = الكلمة التالية
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بايت

        la   $a0, m1
        li   $v0, 4
        syscall

        #يعيد lw بناء نفس قيم 32 بت التي كتبها sw.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
