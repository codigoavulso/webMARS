# ==========================================================
#الدرس 07 - الكلمات في الذاكرة، ولماذا تقفز العناوين بمقدار أربعة
#
#THE PROBLEM
#تتم معالجة الذاكرة بايت واحد في كل مرة، ولكن يتم الاحتفاظ بالسجل
#أربعة بايت. ما الذي يختاره عنوان واحد فعليًا؟
#
#WHAT THE HARDWARE DOES
#ينقل lw وsw أربع بايتات في وصول واحد، وبالتالي متتالية
#الكلمات تفصل بين أربعة عناوين. القطعتين المنخفضتين من
#يجب أن يكون العنوان صفرًا: هذه المحاذاة هي ما يتيح لـ
#تجلب الأجهزة كلمة كاملة في دورة واحدة.
#
#THE SOLUTION
#يتم إجراء حساب العنوان بالبايت، لذلك يتم تحويل الفهرس إلى كلمات
#يتم تحجيمها دائمًا بأربعة.
#
#WATCH FOR
#قم بالتجميع، ثم افتح مقطع البيانات في 0x10010000. ال
#تظهر ثلاث قيم في الأعمدة المجاورة لصف واحد.
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #العنوان الأساسي

        #كل إزاحة أدناه مرتبطة بـ $t0 وتظل محاذية للكلمات.
        li   $t1, 111
        sw   $t1, 0($t0)        #الكلمة الأولى
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بايت = الكلمة التالية
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بايت

        la   $a0, m1
        li   $v0, 4
        syscall

        #يعيد lw بناء نفس قيم 32 بت التي كتبها sw.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
