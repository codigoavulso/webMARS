# تقوم المكالمة المتكررة بالكتابة فوق `$ra` وتستخدم `$a0` للوسيطة الخاصة بها. احفظ كلا القيمتين
# قبل إجراء المكالمة.
#
# ادخل إلى `fact` لكل قيمة من 5 إلى 1. تحتفظ كل مكالمة بثمانية بايت، بما في ذلك المكالمة التي
# ترجع 1.
#
# قم بتعيين نقطة توقف على `mul` لمشاهدة مسار العودة. تقوم كل مكالمة بإعادة تحميل الوسيطة الخاصة
# بها، وتضاعفها وتحرر إطارها.

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- حقيقة كثافة العمليات (كثافة العمليات ن) ----
fact:
        #يمتلك كل استدعاء إطارًا مميزًا مكونًا من ثمانية بايت.
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #عنوان إرجاع هذه المكالمة
        sw   $a0, 4($sp)        #هذه المكالمة ن

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #الحالة الأساسية: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #لدينا ن مرة أخرى
        mul  $v0, $v0, $a0

factend:
        # قم باستعادة عنوان المرسل المحفوظ قبل تحرير إطار هذه المكالمة.
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
