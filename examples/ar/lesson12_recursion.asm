# ==========================================================
#الدرس 12 - العودية تحتاج إلى إطار لكل مكالمة
#
#THE PROBLEM
#يقوم الاستدعاء المتكرر بالكتابة فوق $ra وسجل الوسيطة.
#المكالمة الخارجية ليس لها طريق للرجوع وليس لديها أي فكرة عما هي عليه
#كان ن الخاصة.
#
#WHAT THE HARDWARE DOES
#فهو يوفر واحدًا $ra، وليس مجموعة منهم. لم يتم حفظ أي شيء
#تلقائيا؛ إذا لم يحفظه الرمز، فقد اختفى.
#
#THE SOLUTION
#كل عملية تنشيط تفتح إطارًا على المكدس، وتحتفظ به
#سوف لا تزال بحاجة بعد المكالمة، ويستعيده على الطريق
#خارج. عمق المكدس هو عمق العودية.
#
#WATCH FOR
#قم بتعيين نقطة توقف على mul وشاهد $sp ينزل بمقدار 8 لكل
#المستوى. النسخ الخمس المحفوظة من n هي ما يجعل
#الضرب في طريق العودة ممكن.
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- حقيقة كثافة العمليات (كثافة العمليات ن) ----
fact:
        #يمتلك كل استدعاء إطارًا مميزًا مكونًا من ثمانية بايت.
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #عنوان إرجاع هذه المكالمة
        sw   $a0, 4($sp)        #هذه المكالمة ن

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #الحالة الأساسية: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #لدينا ن مرة أخرى
        mul  $v0, $v0, $a0

factend:
        #قم باستعادة حالة المستدعي وتخلص تمامًا من الإطار المخصص عند الإدخال.
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
