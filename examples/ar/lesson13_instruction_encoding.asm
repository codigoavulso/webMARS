# 13 - التعليمات هي رقم
#
# تجميع وفحص عمود التعليمات البرمجية في مقطع النص. كل تعليمات أساسية عبارة عن كلمة مكونة من 32
# بت مقسمة إلى حقول.
#
# قارن بين التعليمات `add`. تتطابق حقول العملية، بينما تقوم حقول التسجيل بتشفير المعاملات
# المختلفة.
#
# في `addi`، تحتوي الـ 16 بت المنخفضة على 100 الفوري، وهو `0x0064`. قم بتغييره إلى 101 وأعد
# التجميع لرؤية التغيير.

        .text
        .globl main
main:
        #افحص عمود "الرمز" بعد التجميع: لا يتم تخزين أساليب الإستذكار هذه كنص.
        add  $t0, $t1, $t2      #نوع R: كود التشغيل، rs، rt، rd، funct
        add  $t3, $t4, $t5      #نفس الشكل، وسجلات مختلفة
        addi $t0, $t1, 100      #النوع I: الثابت في الكلمة
        sll  $t0, $t1, 4        #مبلغ التحول له مجاله الخاص
        j    tail               #النوع J: عنوان وليس سجل
tail:
        #يتم توسيع li نفسه قبل التنفيذ؛ يرى المعالج الكلمات المشفرة فقط.
        li   $v0, 10
        syscall
