#THE PROBLEM
#يقوم المعالج بجلب الكلمات من الذاكرة. الكود يعيش في
#الذاكرة أيضا. إذن ما الذي يميز التعليمات عن أ
#قطعة من البيانات؟
#
#WHAT THE HARDWARE DOES
#لا شيء يتم بعده تسجيل الكلمة. ال
#يختار الكمبيوتر الكلمات التي تذهب إلى وحدة فك التشفير؛ lw يختار الكلمات
#التي تذهب إلى ملف التسجيل. البتات هي نفس النوع.
#
#THE SOLUTION
#قراءة الترميز مباشرة. تجميع وفتح
#رئيسي > تنفيذ: يُظهر عمود التعليمات البرمجية كل تعليمات على النحو التالي
#الكلمة 32 بت هي حقا.
#
#WATCH FOR
#لا يطبع هذا الدرس أي شيء عن قصد - فالإخراج هو
#شريحة النص نفسها. قارن بين الإضافات: نفس كود التشغيل و
#حقول الوظائف، أرقام التسجيل المختلفة. ثم ابحث عن
#الحرفي 100 داخل كلمة Addi.
# ==========================================================
        .text
        .globl main
main:
        #افحص عمود "الرمز" بعد التجميع: لا يتم تخزين أساليب الإستذكار هذه كنص.
        add  $t0, $t1, $t2      #نوع R: كود التشغيل، rs، rt، rd، funct
        add  $t3, $t4, $t5      #نفس الشكل، وسجلات مختلفة
        addi $t0, $t1, 100      #النوع I: الثابت في الكلمة
        sll  $t0, $t1, 4        #مبلغ التحول له مجاله الخاص
        j    tail               #النوع J: عنوان وليس سجل
tail:
        #يتم توسيع li نفسه قبل التنفيذ؛ يرى المعالج الكلمات المشفرة فقط.
        li   $v0, 10
        syscall
