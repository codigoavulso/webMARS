#الدرس 05 - المقارنة والفرع
#
#THE PROBLEM
#يحتاج القرار إلى بت واحد، ولكن مقارنة رقمين كل منهما 32 بت
#هو الطرح. كيف يصبح الطرح اختيارا؟
#
#WHAT THE HARDWARE DOES
#slt يطرح ويرمي كل شيء باستثناء الإشارة،
#كتابة 0 أو 1. ثم يقوم الفرع بتغذية هذا البت إلى جهاز الكمبيوتر
#المنطق، الذي إما يضيف إزاحة أو يسمح للكمبيوتر بالتقدم.
#
#THE SOLUTION
#قارن في سجل، فرع في هذا السجل. السيطرة
#التدفق حسابي بالإضافة إلى معدد إرسال واحد على جهاز الكمبيوتر.
#
#WATCH FOR
#بعد slt، $t2 يحمل 1. تجاوز beq وشاهد الكمبيوتر
#في شريط الحالة: يقفز بدلاً من التقدم بمقدار أربعة.
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #أ
        li   $t1, 12            #ب
        #slt يجسد المقارنة كعدد صحيح عادي، وليس كأعلام مخفية أبدًا.
        slt  $t2, $t0, $t1      #t2 = 1 إذا كان أ < ب
        #تفرع إلى notless فقط عندما تكون النتيجة المنطقية صفرًا.
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
