# 08 - البايتات وترتيب البايتات
#
# في الذاكرة ذات النهاية الصغيرة لهذه المحاكاة، يوجد البايت الأقل أهمية للكلمة في العنوان
# الأدنى.
#
# قم بتخزين `0x04030201` ككلمة وقراءة الإزاحات من 0 إلى 3 كبايت. الناتج هو 1، 2، 3، 4.
#
# حاول بايت منخفض من `0xFF`. الحمل غير الموقع بـ `lbu` يعطي 255، بينما الحمل الموقع بـ `lb` يعطي
# -1.

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #البايت 01 هو الأقل أهمية
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #إزاحة البايت
bloop:
        #تقوم زيارات الحلقة بإزاحة 0 و1 و2 و3 داخل الكلمة المخزنة.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #العنوان الفعال = العنوان الأساسي + إزاحة البايت الحالية.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #بايت غير موقعة
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
