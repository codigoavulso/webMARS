# ==========================================================
#الدرس 08 - البايتات داخل الكلمة وترتيب البايتات
#
#THE PROBLEM
#الكلمة تحتل أربعة عناوين. أي بايت يفعل أقل
#من تلك العناوين الاسم؟
#
#WHAT THE HARDWARE DOES
#هذا الاختيار هو ترتيب البايت، وهو قرار يتم اتخاذه بشأن توصيل الأسلاك
#مرة واحدة للجهاز كله. MIPS هنا هو endian الصغير: the
#البايت الأقل أهمية يعيش في العنوان الأدنى.
#
#THE SOLUTION
#قم بتخزين كلمة واحدة، ثم قم بقراءتها مرة أخرى بايتًا تلو الآخر واتركها
#الطلب يجيب على السؤال بالنسبة لك.
#
#WATCH FOR
#0x04030201 يعود بالرقم 1 2 3 4. البايت المكتوب آخر مرة في
#تتم قراءة الحرفي أولا. يتم استخدام lbu بدلاً من lb لذلك أ
#البايت فوق 127 غير ممتد.
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #البايت 01 هو الأقل أهمية
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #إزاحة البايت
bloop:
        #تقوم زيارات الحلقة بإزاحة 0 و1 و2 و3 داخل الكلمة المخزنة.
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #العنوان الفعال = العنوان الأساسي + إزاحة البايت الحالية.
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #بايت غير موقعة
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
