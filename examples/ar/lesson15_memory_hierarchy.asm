# 15- لماذا الخطوة تغير السرعة
#
# كلا الحلقتين تستخدمان نفس المصفوفة. الأول يقرأ جميع الكلمات البالغ عددها 256 كلمة؛ والثاني
# يقرأ كل 16 كلمة، مما يؤدي إلى 16 تحميلًا فقط.
#
# مع كتل ذاكرة التخزين المؤقت المكونة من 16 كلمة، يمكن للقراءات المتسلسلة إعادة استخدام كل كتلة
# تم جلبها. تتقدم الحلقة الثانية إلى كتلة جديدة عند كل تحميل.
#
# صِل المحاكي بـ MIPS وحدّد «ممكّن» واضبط حجم الكتلة على 16 كلمة.
# استخدم محاكي ذاكرة التخزين المؤقت للبيانات مع نقطة توقف عند `far` لفحص الحلقة الأولى. قم
# بإعادة تعيين إحصائيات ذاكرة التخزين المؤقت هناك قبل تشغيل الحلقة الثانية، وقارن معدلات
# الإصابة.

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# التمريرة التسلسلية: جميع الكلمات البالغ عددها 256 كلمة.
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #تعيد الفهارس التسلسلية استخدام الكلمات من كل كتلة ذاكرة تخزين مؤقت قبل المضي قدمًا.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# تمريرة متقنة: حمولة واحدة كل ستة عشر كلمة.
        li   $t1, 0
        li   $t3, 0
far:
        # العنوان التالي على بعد 64 بايت: ستة عشر كلمة بأربع بايت لكل منها.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
