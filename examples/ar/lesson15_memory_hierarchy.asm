# ==========================================================
#الدرس 15 - لماذا تغير الخطوة السرعة؟
#
#THE PROBLEM
#الحلقتان أدناه تقرأان نفس المصفوفة وتؤديان نفس الشيء
#عدد الأحمال. على جهاز حقيقي يكون الأمر أبطأ بكثير. ال
#عدد التعليمات لا يمكن أن يفسر ذلك.
#
#WHAT THE HARDWARE DOES
#الذاكرة لا تقدم كلمات واحدة. ملكة جمال تجلب الكل
#كتلة، الرهان على أن الكلمات المجاورة سوف تكون مطلوبة قريبا.
#خطوة واحدة تجمع هذا الرهان؛ خطوة ستة عشر تدفع
#للكتلة ويقرأ كلمة واحدة منها.
#
#THE SOLUTION
#لا شيء في الكود يتغير. المنطقة هي ملك لل
#نمط الوصول، وهو النمط الذي يجب إصلاحه.
#
#WATCH FOR
#افتح الأدوات > محاكي ذاكرة التخزين المؤقت للبيانات، اضغط على الاتصال بـ MIPS،
#ثم تشغيل. قارن معدل ضرب الحلقتين. كلا المبلغين
#اطبع 0 لأن المصفوفة صفر - الرقم ليس هو
#النقطة هنا، معدل الإصابة هو.
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- كل كلمة من كل كتلة ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #تعيد الفهارس التسلسلية استخدام الكلمات من كل كتلة ذاكرة تخزين مؤقت قبل المضي قدمًا.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- كلمة واحدة لكل كتلة، بفارق ستة عشر كلمة ----
        li   $t1, 0
        li   $t3, 0
far:
        #إضافة 16 تخطيًا لـ 64 بايت لكل تكرار: عادةً ما تكون كتلة ذاكرة تخزين مؤقت كاملة واحدة.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
