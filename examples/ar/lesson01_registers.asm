# 01 - السجلات والفوريات
#
# يتم ترميز الفوري في التعليمات. قم بتجميع وتحقق من التعليمات الأساسية لكل `li`.
#
# خطوة من خلال التحميلين والإضافة. في السجلات، اتبع `$t0 = 12` و`$t1 = 30` و`$t2 = 42`.
#
# حاول استبدال 30 بـ `0x12345678` وأعد التجميع. الثابت الأكبر يحتاج إلى أكثر من تعليمة أساسية.

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #تستخدم Syscalls $v0 كمحدد الخدمة و$a0 كوسيطة أولى.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #لي هي تعليمات زائفة. يعرض التجميع التعليمات الحقيقية التي سيصبح عليها.
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # يتم كتابة المبلغ إلى سجل مختلف.

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
