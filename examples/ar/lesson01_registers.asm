#
#THE PROBLEM
#يحتوي ALU على منفذي إدخال وكلاهما متصل بسلك
#تسجيل الملف. الرقم المكتوب في المصدر ليس في
#التسجيل، لذلك لا يمكن الوصول إلى تلك المنافذ مباشرة.
#
#WHAT THE HARDWARE DOES
#ينتقل فوري داخل كلمة التعليمات نفسها.
#addi يحمل حقلاً بطول 16 بت؛ لى هو الراحة
#يتوسع المجمع إلى واحد أو اثنين من التعليمات الحقيقية.
#
#THE SOLUTION
#قم بوضع الثابت في السجل أولاً، ثم اترك ALU
#اقرأ سجلين واكتب سجلًا ثالثًا.
#
#WATCH FOR
#خطوة مرة واحدة في كل سطر واتبع $t0، $t1 و $t2 في
#لوحة التسجيلات. السطر الثالث فقط يلامس ALU.
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #تستخدم Syscalls $v0 كمحدد الخدمة و$a0 كوسيطة أولى.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #لي هي تعليمات زائفة. يعرض التجميع التعليمات الحقيقية التي سيصبح عليها.
        li   $t0, 12            #فوري -> التسجيل
        li   $t1, 30            #فوري -> التسجيل
        add  $t2, $t0, $t1      #ALU يقرأ سجلين

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
