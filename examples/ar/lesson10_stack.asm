# 10 - المكدس
#
# وفقًا للاتفاقية، ينمو المكدس نحو العناوين الأقل. اطرح 8 من `$sp` لحجز مساحة لكلمتين.
#
# يقوم البرنامج بحفظ سجلين بـ `sw`، ومسحهما، ثم استعادة قيمهما بـ `lw`.
#
# شاهد `$sp` قبل الحجز وخلال المتجرين وبعد الإصدار. يجب أن تتطابق قيمته النهائية مع قيمته
# الأولية.

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #يزداد حجم المكدس للأسفل، لذا يتم خصم التخصيص من $sp.
        addi $sp, $sp, -8       #حجز كلمتين
        sw   $t0, 0($sp)        #ادفع
        sw   $t1, 4($sp)

        li   $t0, 0             #تحطيم السجلات
        li   $t1, 0

        lw   $t0, 0($sp)        #البوب
        lw   $t1, 4($sp)
        #يجب أن يكون كل تخصيص متوازنًا حتى يرى المتصل أصله $sp.
        addi $sp, $sp, 8        #الافراج

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
