#الدرس 10 - المكدس عبارة عن سجل وإزاحة
#
#THE PROBLEM
#هناك 32 سجلاً ويتم مشاركتها بواسطة كل قطعة
#كود. أين تذهب القيمة عندما يجب أن تستمر في العمل؟
#سوف إعادة استخدام تلك السجلات؟
#
#WHAT THE HARDWARE DOES
#لا شيء خاص على الإطلاق. $sp هو سجل عادي
#يحدث أن يشير إلى الذاكرة، وينمو المكدس نحو
#عناوين أقل بحتة عن طريق الاتفاقية.
#
#THE SOLUTION
#حجز المساحة هو طرح من $sp، وتحريره
#إضافة. الدفع والبوب ​​هما فقط sw وlw.
#
#WATCH FOR
#يتم مسح السجلات عمدا بين المخازن
#والأحمال، لذلك لا يمكن أن تأتي القيم المطبوعة إلا
#العودة من الذاكرة. شاهد $sp يتحرك بمقدار 8 ثم يعود.
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #يزداد حجم المكدس للأسفل، لذا يتم خصم التخصيص من $sp.
        addi $sp, $sp, -8       #حجز كلمتين
        sw   $t0, 0($sp)        #ادفع
        sw   $t1, 4($sp)

        li   $t0, 0             #تحطيم السجلات
        li   $t1, 0

        lw   $t0, 0($sp)        #البوب
        lw   $t1, 4($sp)
        #يجب أن يكون كل تخصيص متوازنًا حتى يرى المتصل أصله $sp.
        addi $sp, $sp, 8        #الافراج

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
