# 14- الأعداد الحقيقية في 32 بت
#
# يحتوي التعويم ذو الدقة الواحدة على بت إشارة واحدة وثمانية بتات أسية و23 بتة كسرية.
#
# `lwc1` ينسخ نمط البت إلى سجل الفاصلة العائمة. ثم يضيف `add.s` 3.5 و1.25 لينتج 4.75.
#
# قارن ترميز 4.75 و0.1 في الأداة تمثيل النقطة العائمة. 4.75 دقيق؛ 0.1 يحتاج إلى التقريب.

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #في ملف التسجيل FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #الأفعى FPU

        #يتوقع Syscall 2 الوسيطة العائمة الخاصة به على وجه التحديد في $f12.
        mov.s $f12, $f4
        li   $v0, 2             #تعويم الطباعة
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
