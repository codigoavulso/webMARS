# ==========================================================
#الدرس 14 - الأعداد الحقيقية في 32 بت
#
#THE PROBLEM
#3.5 ليس له مكان في سجل الأعداد الصحيحة. أين يفعل
#الجزء الكسري يذهب، وكيف يتم تخزين عدد كبير جدا
#في نفس 32 بت كواحدة صغيرة جدًا؟
#
#WHAT THE HARDWARE DOES
#IEEE-754 يقسم الكلمة إلى ثلاثة حقول: بت إشارة واحد،
#ثمانية بتات أسية وثلاثة وعشرون بتة كسرية. ال
#الأس ينزلق النقطة الثنائية، وهذا هو سبب التنسيق
#تسمى النقطة العائمة.
#
#THE SOLUTION
#ملف تسجيل منفصل ($f0)..$f31) ومضيف منفصل
#التعامل مع هذه القيم، وهذا هو سبب اختلاف فن الإستذكار:
#lwc1 للتحميل، add.s للإضافة، syscall 2 للطباعة.
#
#WATCH FOR
#افتح الأدوات > تمثيل النقطة العائمة وأدخل 3.5.
#شاهد الحقول الثلاثة، ثم تأكد من أن 4.75 هو الصحيح -
#على عكس 0.1، الذي لا يحتوي على جزء ثنائي محدود.
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #لا تزال العناوين الصحيحة تحدد موقع البيانات؛ يقوم lwc1 بنقل وحدات البت الخاصة به إلى COP1.
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #في ملف التسجيل FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #الأفعى FPU

        #يتوقع Syscall 2 الوسيطة العائمة الخاصة به على وجه التحديد في $f12.
        mov.s $f12, $f4
        li   $v0, 2             #تعويم الطباعة
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
