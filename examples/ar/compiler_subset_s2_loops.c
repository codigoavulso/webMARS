int main(void) {
  //يتطلب C0-S2- أو أعلى: للحلقات، والفاصل/المتابعة، و++/--.
  int sum = 0;   //يعيش المجمع في السجل بمجرد تجميعه

  for (int i = 0; i < 10; i++) {   //تصبح حلقة for مقارنة بالإضافة إلى فرع خلفي
    if ((i % 2) == 0) continue;   //مواصلة القفزات إلى الزيادة، وتخطي الجسم
    if (i > 7) break;   //يقفز الكسر بعد نهاية الحلقة
    sum += i;
  }

  int down = 3;
  down--;   //يتم تجميع ما بعد التخفيض والزيادة المسبقة إلى نفس الإضافة
  int up = 3;
  ++up;

  //الناتج المتوقع: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
