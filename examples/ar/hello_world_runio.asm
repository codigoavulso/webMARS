#Hello World لتشغيل الإدخال/الإخراج
#يطبع رسالة بسيطة ويخرج.
#هذا هو أصغر مثال على تقسيم البيانات/النص واتفاقية syscall.

.data
#يقوم .asciiz بتخزين الأحرف المتبوعة بالفاصل الصفري المطلوب بواسطة syscall 4.
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #حدد سلسلة الطباعة (4) في $v0 وقم بتمرير عنوان السلسلة في $a0.
  li $v0, 4
  la $a0, msg
  syscall

  #يؤدي المخرج (10) إلى إيقاف البرنامج المحاكى بشكل نظيف.
  li $v0, 10
  syscall
