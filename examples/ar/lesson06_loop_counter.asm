# 06 - حلقة كعداد
#
# `$t0` هو الرقم التالي الذي سيتم طباعته. `$t1` هو الحد الأعلى الحصري، لذا فإن الحد الأقصى هو 11
# مطبوعة من 1 إلى 10.
#
# يتم تشغيل المقارنة قبل كل تكرار. تؤدي الزيادة إلى تقدم نحو الحد، وتكرر القفزة عملية التحقق.
#
# قم بتغيير الحد إلى 1 ثم قم بالتشغيل. يتم أخذ فرع الخروج قبل الطباعة الأولى.

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #سجل العد
        li   $t1, 11            #الحد

loop:
        # في اختبار الحلقة، $t0 هو المرشح التالي. اطبعها فقط إذا كانت أدناه $t1.
        slt  $t2, $t0, $t1      #المقارنة
        beq  $t2, $zero, endl   #الخروج عندما يصل العدد إلى الحد الأقصى

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #تحديث العداد قبل القفز يضمن التقدم نحو الإنهاء.
        addi $t0, $t0, 1        #الأفعى
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
