#
#THE PROBLEM
#عداد الأجهزة عبارة عن سجل وتزايد و
#المقارنة. كيف تبدو نفس الآلة مكتوبة
#كتعليمات؟
#
#WHAT THE HARDWARE DOES
#بالضبط تلك الأجزاء الثلاثة، واحد لكل تعليمات: السجل
#يحمل العد، addi هو المتزايد، slt مع فرع
#هو المقارن الذي يقرر في جولة أخرى.
#
#THE SOLUTION
#الحلقة ليست مفهوما جديدا. إنه منطق متسلسل مكتوب
#خارج، مع جهاز الكمبيوتر والساعة.
#
#WATCH FOR
#$t0 هو سجل العد و$t1 هو الحد. خطوة من خلال
#جولة واحدة كاملة واسم أي سطر هو أي جزء.
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #سجل العد
        li   $t1, 11            #الحد

loop:
        #الحلقة الثابتة: $t0 هي القيمة التالية المطلوب طباعتها وتظل أقل من $t1.
        slt  $t2, $t0, $t1      #المقارنة
        beq  $t2, $zero, endl   #الخروج عندما يصل العدد إلى الحد الأقصى

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #تحديث العداد قبل القفز يضمن التقدم نحو الإنهاء.
        addi $t0, $t0, 1        #الأفعى
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
