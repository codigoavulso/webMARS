#THE PROBLEM
#توفر تعليمات التحميل سجلًا أساسيًا وثابتًا
#إزاحة. لا شيء آخر. فكيف يتم الوصول إلى [i] عندما أكون فقط
#المعروفة في وقت التشغيل، ويجلس في السجل؟
#
#WHAT THE HARDWARE DOES
#ويضيف القاعدة إلى كل ما يحمله السجل. الفهرس
#لذلك يجب أن يكون بالفعل بالبايت، وليس بالعناصر.
#
#THE SOLUTION
#قم بقياس الفهرس حسب حجم العنصر، ثم أضفه. لأربعة بايت
#الكلمات التي القياس هو التحول الذي تركه اثنان، وهو ما يكلف
#لا شيء.
#
#WATCH FOR
#الأسطر الثلاثة sll، add، lw هي ما يُترجم إليه a[i].
#قم بإجراء تكرار واحد واقرأ $t5 و $t6.
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #قاعدة
        li   $t1, 0             #أنا
        li   $t2, 5             #الطول
        li   $t3, 0             #تراكم

sum:
        #حلقة ثابتة: $t3 هو مجموع arr[0] حتى arr[i-1].
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #ط * 4 بايت
        add  $t6, $t0, $t5      #قاعدة + مؤشر متدرج
        #$t6 يقوم الآن بتسمية عنصر واحد بالضبط؛ lw يجلب قيمته 32 بت.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
