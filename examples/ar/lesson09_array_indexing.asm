# 09 - فهرسة المصفوفة
#
# يحتل كل عنصر صفيف أربعة بايت. قم بإزاحة الفهرس إلى اليسار بمقدار اثنين لحساب إزاحة البايت
# الخاصة به.
#
# اتبع التسلسل `sll`، `add`، `lw`: قم بقياس الفهرس وإضافة العنوان الأساسي وتحميل العنصر.
#
# في الفهرس 2، `$t5` يساوي 8 و`$t6` يشير إلى القيمة 30. مجموع العناصر الخمسة يصل إلى 150.

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #قاعدة
        li   $t1, 0             #أنا
        li   $t2, 5             #الطول
        li   $t3, 0             #تراكم

sum:
        #حلقة ثابتة: $t3 هو مجموع arr[0] حتى arr[i-1].
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #ط * 4 بايت
        add  $t6, $t0, $t5      #قاعدة + مؤشر متدرج
        #$t6 يقوم الآن بتسمية عنصر واحد بالضبط؛ lw يجلب قيمته 32 بت.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
