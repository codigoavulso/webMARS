#
#THE PROBLEM
#القفز إلى الروتين أمر سهل. العودة ليست كذلك، لأن
#يمكن استدعاء نفس الروتين من العديد من الأماكن و
#عنوان المرسل يختلف في كل مرة.
#
#WHAT THE HARDWARE DOES
#يقوم jal بأمرين في تعليمات واحدة: فهو يخزن ملف
#عنوان التعليمات التالية في $ra، ثم يقفز. الابن
#ينتقل إلى أي شيء يحتوي عليه السجل، لذلك يعود jr $ra.
#
#THE SOLUTION
#كل شيء آخر هو اتفاق، وليس دائرة: الحجج في
#$a0..$a3، ينتج عنه $v0. كسر الاتفاقية والرمز
#لا يزال يتم تجميعه - فهو ببساطة يتوقف عن التشغيل البيني.
#
#WATCH FOR
#ادخل إلى الجال واقرأ $ra. قارنه بالعنوان
#من السطر بعد المكالمة في مقطع النص.
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #الحجة الأولى
        li   $a1, 42            #الحجة الثانية
        #يقوم jal بتغيير تدفق التحكم و$ra في عملية معمارية واحدة.
        jal  maxof              #$ra = عنوان السطر التالي

        move $a0, $v0           #عادت النتيجة في $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- كثافة العمليات ماكسوف (كثافة العمليات أ، كثافة العمليات ب) ----
maxof:
        #maxof هي دالة طرفية، لذا يمكنها العودة دون حفظ $ra على المكدس.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
