# 11 - استدعاء وظيفة
#
# تشغيل مع تأخر المتفرعة. `jal` ينتقل إلى الوظيفة ويضع عنوان التعليمات التالية في `$ra`.
#
# اصطلاح الاتصال يمرر 17 و 42 في `$a0` و `$a1`. ترجع الدالة القيمة الأكبر في `$v0`.
#
# ابدأ المكالمة، وقارن `$ra` بالعنوان الذي يلي `jal`، ثم اتبع `jr $ra` للرجوع إلى المتصل.

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #الحجة الأولى
        li   $a1, 42            #الحجة الثانية
        jal  maxof

        move $a0, $v0           #عادت النتيجة في $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- كثافة العمليات ماكسوف (كثافة العمليات أ، كثافة العمليات ب) ----
maxof:
        #maxof هي دالة طرفية، لذا يمكنها العودة دون حفظ $ra على المكدس.
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
