# ==========================================================
#الدرس 02 - تكملة اثنين
#
#THE PROBLEM
#السجل عبارة عن 32 سلكًا، كل منها مرتفع أو منخفض. لا يوجد سلك
#لعلامة الطرح، ولكن الأرقام السالبة يجب أن تعمل.
#
#WHAT THE HARDWARE DOES
#يُقرأ الجزء العلوي كعلامة، ولكن ليس كعلم منفصل:
#-n يتم تخزينه كنمط البت الذي يضاف إلى n ويلتف عليه
#صفر. اقلب كل جزء وأضف واحدًا وستحصل عليه.
#
#THE SOLUTION
#لا يحتاج الطرح إلى دائرة ثانية. أ - ب يصبح
#a + (-b)، لذا فإن جامعًا واحدًا يخدم كلا العمليتين.
#
#WATCH FOR
#طباعة كلا النصفين -5. والثاني يصل إليه على طول الطريق،
#مع ولا وaddi، تظهر ما يفعله الفرعي داخليا.
#اضبط القيم على النظام الست عشري لرؤية 0xFFFFFFFB.
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #الطرح من الصفر يشكل المعكوس الجمعي بدون بتة علامة الطرح.
        li   $t0, 5
        sub  $t1, $zero, $t0    #الأفعى يقوم بالعمل
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #ولا مع $zero يكون ثنائي الاتجاه NOT؛ إضافة واحد يكمل تكملة الاثنين.
        nor  $t2, $t0, $zero    #عكس كل البتات
        addi $t2, $t2, 1        #إضافة واحدة
        move $a0, $t2           #نفس القيمة المذكورة أعلاه
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
