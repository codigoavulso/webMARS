# 04 - التحولات وصلاحيات اثنين
#
# التحول الأيسر بمقدار 3 يضرب في 8 عندما تكون النتيجة مناسبة. يتم تجاهل البتات التي تم إزاحتها
# بعد الحافة.
#
# على اليمين، `srl` يملأ بالأصفار و `sra` ينسخ بت الإشارة. بالنسبة إلى -16 تم إزاحتها بمقدار 2،
# توقع 1073741820 و -4 على التوالي.
#
# جرب -15 مع `sra`. والنتيجة هي -4 لأن الإزاحة يتم تقريبها إلى الأسفل؛ وقعت جولات التقسيم نحو
# الصفر.

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #يتم ضرب ثلاث إزاحات يسارية في 2^3 مع الاحتفاظ بـ 32 بت نتيجة فقط.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #قارن $t3 و $t4 بالنظام الست عشري لرؤية البتات الواردة المختلفة.
        sra  $t3, $t2, 2        #العلامة المحفوظة: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #تحولت الأصفار إلى: إيجابية ضخمة
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
