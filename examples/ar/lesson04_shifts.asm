# ==========================================================
#الدرس 04 - التحولات، أو الضرب بالأسلاك
#
#THE PROBLEM
#يعد المضاعف العام واحدًا من أغلى الكتل في
#مسار البيانات. الضرب في 8 لا ينبغي أن يكلف الكثير.
#
#WHAT THE HARDWARE DOES
#التحول ليس حسابيًا على الإطلاق: فهو نفس البتات التي يتم قراءتها
#من أسلاك مختلفة. التحول إلى اليسار بمقدار n يتضاعف بمقدار 2^n
#وتكاليف التوجيه فقط.
#
#THE SOLUTION
#صلاحيات اثنين تصبح التحولات. لاحظ التحولين الصحيحين: srl
#يغذي الأصفار في الأعلى، وينسخ sra بت الإشارة، لذلك فقط
#sra يقسم رقمًا سالبًا بشكل صحيح.
#
#WATCH FOR
#-16 >> 2 يعطي -4 مع sra لكن إيجابي كبير مع srl. ال
#تحركت البتات بشكل مماثل؛ يختلف فقط ما تم إدخاله في الأعلى.
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #يتم ضرب ثلاث إزاحات يسارية في 2^3 مع الاحتفاظ بـ 32 بت نتيجة فقط.
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #قارن $t3 و $t4 بالنظام الست عشري لرؤية البتات الواردة المختلفة.
        sra  $t3, $t2, 2        #العلامة المحفوظة: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #تحولت الأصفار إلى: إيجابية ضخمة
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
