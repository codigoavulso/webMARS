# 01 - رجسٹر اور فوری
#
# فوری کو ہدایات میں انکوڈ کیا گیا ہے۔ جمع کریں اور چیک کریں کہ کون سی بنیادی ہدایات ہر `li`
# بنتی ہے۔
#
# دو بوجھ اور اضافے کے ذریعے قدم رکھیں۔ رجسٹروں میں، `$t0 = 12`، `$t1 = 30` اور `$t2 = 42` کی
# پیروی کریں۔
#
# 30 کو `0x12345678` سے بدل کر دوبارہ جوڑنے کی کوشش کریں۔ بڑے مستقل کو ایک سے زیادہ بنیادی
# ہدایات کی ضرورت ہوتی ہے۔

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls $v0 کو بطور سروس سلیکٹر اور $a0 کو پہلی دلیل کے طور پر استعمال کرتے ہیں۔
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li ایک چھدم ہدایت ہے۔ جمع دکھاتا ہے کہ یہ کون سی حقیقی ہدایت بنتی ہے۔
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # رقم ایک مختلف رجسٹر میں لکھی جاتی ہے۔

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
