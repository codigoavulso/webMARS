#سبق 01 - رجسٹر اور فوری اقدار
#
#THE PROBLEM
#ALU میں دو ان پٹ پورٹس ہیں اور دونوں میں وائرڈ ہیں
#رجسٹر فائل. ماخذ میں لکھا ہوا نمبر a میں نہیں ہے۔
#رجسٹر کریں، لہذا یہ ان بندرگاہوں تک براہ راست نہیں پہنچ سکتا۔
#
#WHAT THE HARDWARE DOES
#فوری طور پر ہدایت کے لفظ کے اندر ہی سفر کرتا ہے۔
#addi ایک 16 بٹ فیلڈ رکھتا ہے۔ li ایک سہولت ہے
#جمع کرنے والا ایک یا دو حقیقی ہدایات میں پھیلتا ہے۔
#
#THE SOLUTION
#پہلے ایک رجسٹر میں مستقل کو لینڈ کریں، پھر ALU
#دو رجسٹر پڑھیں اور تیسرا لکھیں۔
#
#WATCH FOR
#فی لائن ایک بار قدم بڑھائیں اور $t0، $t1 اور $t2 کی پیروی کریں
#رجسٹر پینل۔ صرف تیسری لائن ALU کو چھوتی ہے۔
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls $v0 کو بطور سروس سلیکٹر اور $a0 کو پہلی دلیل کے طور پر استعمال کرتے ہیں۔
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li ایک چھدم ہدایت ہے۔ جمع دکھاتا ہے کہ یہ کون سی حقیقی ہدایت بنتی ہے۔
        li   $t0, 12            #فوری -> رجسٹر کریں۔
        li   $t1, 30            #فوری -> رجسٹر کریں۔
        add  $t2, $t0, $t1      #ALU دو رجسٹر پڑھتا ہے۔

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
