# 10 - اسٹیک
#
# کنونشن کے مطابق اسٹیک نچلے پتوں کی طرف بڑھتا ہے۔ دو الفاظ کے لیے جگہ محفوظ کرنے کے لیے `$sp`
# سے 8 کو گھٹائیں۔
#
# پروگرام `sw` کے ساتھ دو رجسٹروں کو محفوظ کرتا ہے، انہیں صاف کرتا ہے، پھر `lw` کے ساتھ ان کی
# اقدار کو بحال کرتا ہے۔
#
# ریزرویشن سے پہلے، دو اسٹورز کے دوران اور ریلیز کے بعد `$sp` دیکھیں۔ اس کی حتمی قیمت اس کی
# ابتدائی قدر سے مماثل ہونی چاہیے۔

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #اسٹیک نیچے کی طرف بڑھتا ہے، لہذا مختص $sp سے گھٹ جاتا ہے۔
        addi $sp, $sp, -8       #دو الفاظ محفوظ کریں
        sw   $t0, 0($sp)        #دھکا
        sw   $t1, 4($sp)

        li   $t0, 0             #رجسٹروں کو بند کرو
        li   $t1, 0

        lw   $t0, 0($sp)        #پاپ
        lw   $t1, 4($sp)
        #ہر مختص کو متوازن ہونا چاہیے تاکہ کال کرنے والے کو اس کی اصل $sp نظر آئے۔
        addi $sp, $sp, 8        #رہائی

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
