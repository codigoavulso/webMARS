#THE PROBLEM
#32 رجسٹر ہیں اور وہ ہر ایک کے ذریعہ شیئر کیے جاتے ہیں۔
#کوڈ ایک قدر کہاں جاتی ہے جب اسے زندہ رہنا چاہیے کہ وہ کام کرے۔
#کیا ان رجسٹروں کو دوبارہ استعمال کریں گے؟
#
#WHAT THE HARDWARE DOES
#کچھ بھی خاص نہیں۔ $sp ایک عام رجسٹر ہے۔
#میموری کی طرف اشارہ کرتا ہے، اور اسٹیک کی طرف بڑھتا ہے۔
#نچلے پتے خالصتاً کنونشن کے ذریعے۔
#
#THE SOLUTION
#جگہ محفوظ کرنا $sp سے ایک گھٹاؤ ہے، اسے جاری کرنا
#اضافہ پش اور پاپ صرف sw اور lw ہیں۔
#
#WATCH FOR
#دکانوں کے درمیان رجسٹروں کو جان بوجھ کر صاف کیا جاتا ہے۔
#اور بوجھ، لہذا پرنٹ شدہ اقدار صرف آ سکتے ہیں
#یادداشت سے واپس. $sp کو 8 اور پیچھے کی طرف بڑھتے ہوئے دیکھیں۔
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #اسٹیک نیچے کی طرف بڑھتا ہے، لہذا مختص $sp سے گھٹ جاتا ہے۔
        addi $sp, $sp, -8       #دو الفاظ محفوظ کریں
        sw   $t0, 0($sp)        #دھکا
        sw   $t1, 4($sp)

        li   $t0, 0             #رجسٹروں کو بند کرو
        li   $t1, 0

        lw   $t0, 0($sp)        #پاپ
        lw   $t1, 4($sp)
        #ہر مختص کو متوازن ہونا چاہیے تاکہ کال کرنے والے کو اس کی اصل $sp نظر آئے۔
        addi $sp, $sp, 8        #رہائی

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
