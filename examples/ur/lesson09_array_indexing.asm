#THE PROBLEM
#بوجھ کی ہدایات ایک بیس رجسٹر اور ایک مستقل پیش کرتی ہے۔
#آفسیٹ اور کچھ نہیں۔ تو ایک [i] تک کیسے پہنچتا ہے جب میں صرف ہوں۔
#رن ٹائم پر جانا جاتا ہے، ایک رجسٹر میں بیٹھا ہے؟
#
#WHAT THE HARDWARE DOES
#یہ رجسٹر میں جو کچھ بھی رکھتا ہے اس میں بنیاد شامل کرتا ہے۔ انڈیکس
#اس لیے پہلے سے ہی بائٹس میں ہونا چاہیے، عناصر میں نہیں۔
#
#THE SOLUTION
#عنصر کے سائز سے انڈیکس کو اسکیل کریں، پھر شامل کریں۔ چار بائٹ کے لیے
#الفاظ کہ پیمانہ ایک شفٹ ہے جس کی قیمت دو سے رہ جاتی ہے۔
#کچھ نہیں
#
#WATCH FOR
#تین لائنیں sll, add, lw وہ ہیں جو a[i] کو مرتب کرتی ہے۔
#ایک تکرار سے گزریں اور $t5 اور $t6 پڑھیں۔
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #بنیاد
        li   $t1, 0             #i
        li   $t2, 5             #لمبائی
        li   $t3, 0             #جمع کرنے والا

sum:
        #لوپ انویرینٹ: $t3 arr[0] سے arr[i-1] کا مجموعہ ہے۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i * 4 بائٹس
        add  $t6, $t0, $t5      #بیس + اسکیلڈ انڈیکس
        #$t6 اب بالکل ایک عنصر کا نام ہے؛ lw اپنی 32 بٹ ویلیو لاتا ہے۔
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
