# 09 - ایک صف کو ترتیب دینا
#
# ہر صف کا عنصر چار بائٹس پر قابض ہے۔ اس کے بائٹ آفسیٹ کی گنتی کرنے کے لیے انڈیکس کو دو سے بائیں
# شفٹ کریں۔
#
# ترتیب کی پیروی کریں `sll`, `add`, `lw`: انڈیکس کو پیمانہ کریں، بنیادی پتہ شامل کریں اور عنصر
# کو لوڈ کریں۔
#
# انڈیکس 2 پر، `$t5` 8 ہے اور `$t6` قدر 30 کی طرف اشارہ کرتا ہے۔ پانچ عناصر 150 تک جوڑتے ہیں۔

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #بنیاد
        li   $t1, 0             #i
        li   $t2, 5             #لمبائی
        li   $t3, 0             #جمع کرنے والا

sum:
        #لوپ انویرینٹ: $t3 arr[0] سے arr[i-1] کا مجموعہ ہے۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i * 4 بائٹس
        add  $t6, $t0, $t5      #بیس + اسکیلڈ انڈیکس
        #$t6 اب بالکل ایک عنصر کا نام ہے؛ lw اپنی 32 بٹ ویلیو لاتا ہے۔
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
