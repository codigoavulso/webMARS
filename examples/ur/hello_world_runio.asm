#ہیلو ورلڈ فار رن I/O
#ایک سادہ پیغام پرنٹ کرتا ہے اور باہر نکلتا ہے۔
# پیغام .data میں ہے؛ اس کو پرنٹ کرنے والی ہدایات .text میں ہیں۔

.data
#.asciiz حروف کو ذخیرہ کرتا ہے جس کے بعد syscall 4 کے لیے مطلوبہ صفر ٹرمینیٹر ہوتا ہے۔
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #پرنٹ سٹرنگ (4) کو $v0 میں منتخب کریں اور سٹرنگ ایڈریس کو $a0 میں پاس کریں۔
  li $v0, 4
  la $a0, msg
  syscall

  #ایگزٹ (10) مصنوعی پروگرام کو صاف طور پر روکتا ہے۔
  li $v0, 10
  syscall
