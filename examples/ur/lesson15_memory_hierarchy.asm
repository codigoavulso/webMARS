# 15 - آگے بڑھنے سے رفتار کیوں بدل جاتی ہے۔
#
# دونوں لوپس ایک ہی صف کا استعمال کرتے ہیں۔ پہلا تمام 256 الفاظ پڑھتا ہے۔ دوسرا ہر 16 ویں لفظ کو
# پڑھتا ہے، صرف 16 بوجھ بناتا ہے۔
#
# 16 الفاظ کے کیشے بلاکس کے ساتھ، ترتیب وار ریڈز ہر حاصل کردہ بلاک کو دوبارہ استعمال کر سکتی ہے۔
# دوسرا لوپ ہر بوجھ پر ایک نئے بلاک کی طرف بڑھتا ہے۔
#
# سیمولیٹر کو MIPS سے جوڑیں، «فعال» کو نشان زد کریں اور بلاک کا سائز 16 ورڈ مقرر کریں۔
# پہلے لوپ کا معائنہ کرنے کے لیے `far` پر بریک پوائنٹ کے ساتھ ڈیٹا کیش سمیلیٹر استعمال کریں۔
# دوسرا لوپ چلانے سے پہلے وہاں کیشے کے اعدادوشمار کو دوبارہ ترتیب دیں، اور ہٹ ریٹ کا موازنہ
# کریں۔

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# ترتیب وار پاس: تمام 256 الفاظ۔
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #ترتیب وار اشاریہ جات آگے بڑھنے سے پہلے ہر کیشے بلاک سے الفاظ کو دوبارہ استعمال کرتے ہیں۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# سٹرائیڈ پاس: ہر سولہ الفاظ پر ایک بوجھ۔
        li   $t1, 0
        li   $t3, 0
far:
        # اگلا پتہ 64 بائٹس کے فاصلے پر ہے: ہر ایک پر چار بائٹس پر سولہ الفاظ۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
