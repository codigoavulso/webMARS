#THE PROBLEM
#نیچے کے دو لوپس ایک ہی صف کو پڑھتے ہیں اور وہی انجام دیتے ہیں۔
#بوجھ کی تعداد. ایک حقیقی مشین پر ایک بہت سست ہے۔ دی
#ہدایات کی تعداد اس کی وضاحت نہیں کر سکتی۔
#
#WHAT THE HARDWARE DOES
#یادداشت ایک لفظ فراہم نہیں کرتی۔ ایک مس ایک پوری لاتی ہے۔
#بلاک، شرط لگاتے ہوئے کہ پڑوسی الفاظ جلد ہی مطلوب ہوں گے۔
#ایک قدم اس شرط کو جمع کرتا ہے؛ سولہ کا ایک قدم ادا کرتا ہے۔
#ایک بلاک کے لیے اور اس کا ایک لفظ پڑھتا ہے۔
#
#THE SOLUTION
#کوڈ میں کچھ بھی تبدیل نہیں ہوتا ہے۔ مقامیت کی ملکیت ہے۔
#رسائی پیٹرن، اور یہ وہ پیٹرن ہے جسے طے کرنا ضروری ہے۔
#
#WATCH FOR
#ٹولز > ڈیٹا کیش سمیلیٹر کھولیں، کنیکٹ ٹو MIPS کو دبائیں،
#پھر چلائیں. دو لوپس کی ہٹ ریٹ کا موازنہ کریں۔ دونوں رقوم
#پرنٹ 0 کیونکہ صف صفر ہے - نمبر نہیں ہے۔
#یہاں پوائنٹ، ہٹ کی شرح ہے.
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- ہر بلاک کا ہر لفظ ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #ترتیب وار اشاریہ جات آگے بڑھنے سے پہلے ہر کیشے بلاک سے الفاظ کو دوبارہ استعمال کرتے ہیں۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- فی بلاک ایک لفظ، سولہ الفاظ کے علاوہ ----
        li   $t1, 0
        li   $t3, 0
far:
        #16 سکپس 64 بائٹس فی تکرار شامل کرنا: عام طور پر ایک مکمل کیش بلاک۔
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
