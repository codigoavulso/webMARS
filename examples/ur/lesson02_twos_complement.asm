# 02 - دو کی تکمیل
#
# 32 بٹ ٹو کی تکمیل میں، 5 کے بٹس کو الٹنا اور 1 کو شامل کرنا -5 کی نمائندگی کرتا ہے۔
#
# پروگرام ایک ہی قدر کو دو طریقوں سے شمار کرتا ہے: صفر سے `sub`، پھر `nor` اور `addi`۔
#
# دونوں راستے پرنٹ -5۔ رجسٹر میں `0xFFFFFFFB` کا معائنہ کریں کہ وہی بٹس ہیکسا ڈیسیمل میں کیسے
# نظر آتے ہیں۔

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #صفر سے گھٹانے سے مائنس سائن بٹ کے بغیر اضافی معکوس بنتا ہے۔
        li   $t0, 5
        sub  $t1, $zero, $t0    #جوڑنے والا کام کرتا ہے۔
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #اور نہ ہی $zero کے ساتھ بٹ وائز ہے NOT; ایک کو شامل کرنے سے دو کی تکمیل ہوتی ہے۔
        nor  $t2, $t0, $zero    #تمام بٹس کو الٹ دیں۔
        addi $t2, $t2, 1        #ایک شامل کریں
        move $a0, $t2           #اوپر کے طور پر ایک ہی قیمت
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
