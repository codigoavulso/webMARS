#WHAT THE HARDWARE DOES
#یہ اوپری بٹ کو بطور نشانی پڑھتا ہے، لیکن الگ جھنڈے کے طور پر نہیں:
#-n کو بٹ پیٹرن کے طور پر محفوظ کیا جاتا ہے جو n میں شامل ہوتا ہے، لپیٹ دیتا ہے۔
#صفر ہر بٹ کو الٹ دیں اور ایک شامل کریں اور آپ کے پاس ہے۔
#
#THE SOLUTION
#گھٹاؤ کو دوسرے سرکٹ کی ضرورت نہیں ہے۔ a - b بن جاتا ہے۔
#a + (-b)، لہذا ایک ایڈر دونوں کاموں کو انجام دیتا ہے۔
#
#WATCH FOR
#دونوں نصف پرنٹ -5. دوسرا اس تک لمبا فاصلہ طے کرتا ہے،
#nor اور addi کے ساتھ، دکھا رہا ہے کہ ذیلی اندرونی طور پر کیا کرتا ہے۔
#0xFFFFFFFB دیکھنے کے لیے اقدار کو ہیکسا ڈیسیمل پر سیٹ کریں۔
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #صفر سے گھٹانے سے مائنس سائن بٹ کے بغیر اضافی معکوس بنتا ہے۔
        li   $t0, 5
        sub  $t1, $zero, $t0    #جوڑنے والا کام کرتا ہے۔
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #اور نہ ہی $zero کے ساتھ بٹ وائز ہے NOT; ایک کو شامل کرنے سے دو کی تکمیل ہوتی ہے۔
        nor  $t2, $t0, $zero    #تمام بٹس کو الٹ دیں۔
        addi $t2, $t2, 1        #ایک شامل کریں
        move $a0, $t2           #اوپر کے طور پر ایک ہی قیمت
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
