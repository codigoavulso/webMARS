#
#THE PROBLEM
#ہارڈویئر کاؤنٹر ایک رجسٹر، ایک انکریمنٹر اور ایک ہے۔
#موازنہ کرنے والا وہی مشین لکھی کیسی نظر آتی ہے۔
#ہدایات کے طور پر؟
#
#WHAT THE HARDWARE DOES
#بالکل وہی تین حصے، ایک فی ہدایت: رجسٹر
#شمار رکھتا ہے، addi اضافہ کرنے والا ہے، شاخ کے ساتھ slt
#موازنہ کرنے والا ہے جو دوسرے دور کا فیصلہ کرتا ہے۔
#
#THE SOLUTION
#لوپ کوئی نیا تصور نہیں ہے۔ یہ ترتیب وار منطق ہے
#باہر، گھڑی کے طور پر پی سی کے ساتھ.
#
#WATCH FOR
#$t0 گنتی کا رجسٹر اور $t1 حد ہے۔ کے ذریعے قدم
#ایک مکمل راؤنڈ اور نام کون سی لائن کون سا حصہ ہے۔
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #گنتی کا رجسٹر
        li   $t1, 11            #حد

loop:
        #لوپ انویریئنٹ: $t0 پرنٹ کرنے کے لیے اگلی قدر ہے اور $t1 سے نیچے رہتی ہے۔
        slt  $t2, $t0, $t1      #موازنہ کرنے والا
        beq  $t2, $zero, endl   #جب گنتی حد تک پہنچ جائے تو باہر نکلیں۔

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #کودنے سے پہلے کاؤنٹر کو اپ ڈیٹ کرنا ختم ہونے کی طرف پیشرفت کی ضمانت دیتا ہے۔
        addi $t0, $t0, 1        #جوڑنے والا
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
