# 06 - ایک کاؤنٹر کے طور پر لوپ
#
# `$t0` پرنٹ کرنے کے لیے اگلا نمبر ہے۔ `$t1` خصوصی بالائی حد ہے، لہذا 11 پرنٹس کی حد 1 سے 10 تک
# ہے۔
#
# موازنہ ہر تکرار سے پہلے چلتا ہے۔ اضافہ حد کی طرف پیشرفت کرتا ہے، اور چھلانگ چیک کو دہراتی ہے۔
#
# حد کو 1 میں تبدیل کریں اور چلائیں۔ ایگزٹ برانچ پہلے پرنٹ سے پہلے لی جاتی ہے۔

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #گنتی کا رجسٹر
        li   $t1, 11            #حد

loop:
        # لوپ ٹیسٹ میں، $t0 اگلا امیدوار ہے۔ اسے صرف اس صورت میں پرنٹ کریں جب یہ $t1 سے نیچے ہو۔
        slt  $t2, $t0, $t1      #موازنہ کرنے والا
        beq  $t2, $zero, endl   #جب گنتی حد تک پہنچ جائے تو باہر نکلیں۔

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #کودنے سے پہلے کاؤنٹر کو اپ ڈیٹ کرنا ختم ہونے کی طرف پیشرفت کی ضمانت دیتا ہے۔
        addi $t0, $t0, 1        #جوڑنے والا
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
