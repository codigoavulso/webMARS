#THE PROBLEM
#ایک لفظ چار پتے پر قبضہ کرتا ہے۔ کون سا بائٹ سب سے کم کام کرتا ہے۔
#ان پتوں کا نام؟
#
#WHAT THE HARDWARE DOES
#یہ انتخاب بائٹ آرڈر ہے، اور یہ وائرنگ کا فیصلہ ہے۔
#ایک بار پوری مشین کے لیے۔ MIPS یہاں لٹل اینڈین ہے: the
#کم از کم اہم بائٹ سب سے کم پتے پر رہتا ہے۔
#
#THE SOLUTION
#ایک لفظ ذخیرہ کریں، پھر اسے ایک وقت میں ایک بائٹ پڑھیں اور جانے دیں۔
#آرڈر آپ کے لیے سوال کا جواب دیتا ہے۔
#
#WATCH FOR
#0x04030201 1 2 3 4 کے طور پر واپس آتا ہے۔ بائٹ آخری میں لکھا گیا
#لغوی پہلے پڑھا جاتا ہے۔ lb کے بجائے lbu استعمال کیا جاتا ہے لہذا a
#127 سے اوپر کا بائٹ سائن توسیع شدہ نہیں ہے۔
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #بائٹ 01 کم از کم اہم ہے۔
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #بائٹ آفسیٹ
bloop:
        #لوپ ذخیرہ شدہ لفظ کے اندر 0، 1، 2 اور 3 کو آف سیٹ کرتا ہے۔
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #موثر ایڈریس = بیس ایڈریس + موجودہ بائٹ آفسیٹ۔
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #غیر دستخط شدہ بائٹ
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
