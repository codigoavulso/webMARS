# 08 - بائٹس اور بائٹ آرڈر
#
# اس سمیلیٹر کی لٹل اینڈین میموری میں، کسی لفظ کا سب سے کم اہم بائٹ سب سے کم پتے پر رہتا ہے۔
#
# `0x04030201` کو ایک لفظ کے طور پر اسٹور کریں اور آفسیٹس 0 سے 3 تک بائٹس کے طور پر پڑھیں۔ آؤٹ
# پٹ 1، 2، 3، 4 ہے۔
#
# `0xFF` کا کم بائٹ آزمائیں۔ `lbu` کے ساتھ ایک غیر دستخط شدہ بوجھ 255 دیتا ہے، جبکہ `lb` کے ساتھ
# دستخط شدہ لوڈ -1 دیتا ہے۔

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #بائٹ 01 کم از کم اہم ہے۔
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #بائٹ آفسیٹ
bloop:
        #لوپ ذخیرہ شدہ لفظ کے اندر 0، 1، 2 اور 3 کو آف سیٹ کرتا ہے۔
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #موثر ایڈریس = بیس ایڈریس + موجودہ بائٹ آفسیٹ۔
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #غیر دستخط شدہ بائٹ
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
