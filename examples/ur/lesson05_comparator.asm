# 05 - موازنہ کرنے والا اور برانچ
#
# `slt` دو دستخط شدہ عدد کا موازنہ کرتا ہے اور جب پہلا چھوٹا ہوتا ہے تو 1 لکھتا ہے، یا دوسری
# صورت میں 0۔
#
# 7 اور 12 کے لیے، `$t2` 1 ہے، اس لیے `beq` چھلانگ لگا کر `notless` پر نہیں آتا اور اگلی ہدایات
# پر عمل درآمد جاری رہتا ہے۔
#
# برانچنگ میں تاخیر کے ساتھ، `beq` سے آگے بڑھیں اور PC کا مشاہدہ کریں۔ دو ان پٹ اقدار کو تبدیل
# کریں اور نئی منزل کا موازنہ کریں۔

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #a
        li   $t1, 12            #ب
        #slt موازنہ کو ایک عام عدد کے طور پر پیش کرتا ہے، کبھی بھی پوشیدہ جھنڈوں کی طرح نہیں۔
        slt  $t2, $t0, $t1      #t2 = 1 اگر a < b
        #صرف اس وقت برانچ کریں جب وہ بولین نتیجہ صفر ہو۔
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
