#THE PROBLEM
#فیصلے کے لیے ایک بٹ کی ضرورت ہوتی ہے، لیکن دو 32 بٹ نمبروں کا موازنہ کرنا
#ایک گھٹاؤ ہے. گھٹاؤ انتخاب کیسے بنتا ہے؟
#
#WHAT THE HARDWARE DOES
#slt نشان کے علاوہ ہر چیز کو گھٹا کر پھینک دیتا ہے،
#0 یا 1 لکھنا۔ پھر برانچ اس بٹ کو پی سی کو فیڈ کرتی ہے۔
#منطق، جو یا تو آفسیٹ کا اضافہ کرتی ہے یا پی سی کو آگے بڑھنے دیتی ہے۔
#
#THE SOLUTION
#اس رجسٹر پر ایک رجسٹر، برانچ سے موازنہ کریں۔ کنٹرول
#فلو پی سی پر ریاضی کے علاوہ ایک ملٹی پلیکسر ہے۔
#
#WATCH FOR
#slt کے بعد، $t2 1 رکھتا ہے۔ beq سے آگے بڑھیں اور PC دیکھیں
#اسٹیٹس بار میں: یہ چار سے آگے بڑھنے کے بجائے چھلانگ لگاتا ہے۔
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #a
        li   $t1, 12            #ب
        #slt موازنہ کو ایک عام عدد کے طور پر پیش کرتا ہے، کبھی بھی پوشیدہ جھنڈوں کی طرح نہیں۔
        slt  $t2, $t0, $t1      #t2 = 1 اگر a < b
        #صرف اس وقت برانچ کریں جب وہ بولین نتیجہ صفر ہو۔
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
