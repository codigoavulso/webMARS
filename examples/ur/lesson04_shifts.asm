# 04 - دو کی تبدیلیاں اور اختیارات
#
# جب نتیجہ فٹ ہوجاتا ہے تو بائیں شفٹ کو 3 سے 8 سے ضرب دیتا ہے۔ کنارے سے گزرے ہوئے بٹس کو ضائع کر
# دیا جاتا ہے۔
#
# دائیں طرف، `srl` صفر سے بھرتا ہے اور `sra` سائن بٹ کو کاپی کرتا ہے۔ -16 کے لیے 2 سے شفٹ ہوئے،
# بالترتیب 1073741820 اور -4 کی توقع کریں۔
#
# `sra` کے ساتھ -15 آزمائیں۔ نتیجہ -4 ہے کیونکہ شفٹ نیچے آتی ہے۔ صفر کی طرف تقسیم کے راؤنڈ پر
# دستخط ہوئے۔

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #صرف 32 رزلٹ بٹس کو برقرار رکھتے ہوئے تین بائیں شفٹیں 2^3 سے ضرب کرتی ہیں۔
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #مختلف آنے والے بٹس کو دیکھنے کے لیے ہیکساڈیسیمل میں $t3 اور $t4 کا موازنہ کریں۔
        sra  $t3, $t2, 2        #نشان محفوظ: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #زیرو منتقل ہو گئے: بہت بڑا مثبت
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
