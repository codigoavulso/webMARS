#سبق 04 - تبدیلیاں، یا تاروں سے ضرب
#
#THE PROBLEM
#ایک جنرل ضرب سب سے مہنگے بلاکس میں سے ایک ہے۔
#ایک ڈیٹا پاتھ 8 سے ضرب کرنے پر اتنا خرچ نہیں ہونا چاہیے۔
#
#WHAT THE HARDWARE DOES
#ایک شفٹ بالکل بھی ریاضی نہیں ہے: یہ وہی بٹس ہے جسے پڑھا جاتا ہے۔
#مختلف تاروں سے n سے بائیں شفٹ کرنا 2^n سے ضرب کرتا ہے۔
#اور صرف روٹنگ کی لاگت آتی ہے۔
#
#THE SOLUTION
#دو کی طاقتیں بدل جاتی ہیں۔ دو دائیں شفٹوں کو نوٹ کریں: srl
#سب سے اوپر زیرو کو فیڈ کرتا ہے، sra سائن بٹ کو کاپی کرتا ہے، اس لیے صرف
#sra منفی نمبر کو صحیح طریقے سے تقسیم کرتا ہے۔
#
#WATCH FOR
#-16 >> 2 sra کے ساتھ -4 دیتا ہے لیکن srl کے ساتھ ایک بہت بڑا مثبت۔ دی
#بٹس یکساں طور پر منتقل ہو گئے؛ صرف وہی فرق ہے جو اوپر درج کیا گیا ہے۔
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #صرف 32 رزلٹ بٹس کو برقرار رکھتے ہوئے تین بائیں شفٹیں 2^3 سے ضرب کرتی ہیں۔
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #مختلف آنے والے بٹس کو دیکھنے کے لیے ہیکساڈیسیمل میں $t3 اور $t4 کا موازنہ کریں۔
        sra  $t3, $t2, 2        #نشان محفوظ: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #زیرو منتقل ہو گئے: بہت بڑا مثبت
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
