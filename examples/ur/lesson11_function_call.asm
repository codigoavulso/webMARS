#WHAT THE HARDWARE DOES
#jal ایک ہدایت میں دو کام کرتا ہے: یہ ذخیرہ کرتا ہے۔
#$ra میں درج ذیل ہدایات کا پتہ، پھر چھلانگ لگاتا ہے۔ جونیئر
#جو کچھ بھی رجسٹر میں ہے اس پر چھلانگ لگاتا ہے، تو jr $ra واپس آتا ہے۔
#
#THE SOLUTION
#باقی سب کچھ معاہدہ ہے، سرکٹری نہیں: دلائل میں
#$a0۔$a3، نتیجہ $v0 میں۔ کنونشن اور کوڈ کو توڑ دیں۔
#پھر بھی جمع ہوتا ہے - یہ آسانی سے آپس میں کام کرنا بند کر دیتا ہے۔
#
#WATCH FOR
#جل پر قدم رکھیں اور $ra پڑھیں۔ اس کا ایڈریس سے موازنہ کریں۔
#ٹیکسٹ سیگمنٹ میں کال کے بعد لائن کا۔
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #پہلی دلیل
        li   $a1, 42            #دوسری دلیل
        #jal ایک آرکیٹیکچرل آپریشن میں کنٹرول فلو اور $ra دونوں کو تبدیل کرتا ہے۔
        jal  maxof              #$ra = اگلی لائن کا پتہ

        move $a0, $v0           #نتیجہ $v0 میں واپس آیا
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof ایک لیف فنکشن ہے، لہذا یہ اسٹیک پر $ra کو محفوظ کیے بغیر واپس آ سکتا ہے۔
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
