# 11 - فنکشن کو کال کرنا
#
# تاخیر سے برانچنگ آف کے ساتھ چلائیں۔ `jal` فنکشن میں چھلانگ لگاتا ہے اور اگلی ہدایات کا پتہ
# `$ra` میں رکھتا ہے۔
#
# کالنگ کنونشن 17 اور 42 `$a0` اور `$a1` میں گزرتا ہے۔ فنکشن `$v0` میں بڑی قدر لوٹاتا ہے۔
#
# کال میں قدم رکھیں، `$ra` کا `jal` کے بعد کے پتے کے ساتھ موازنہ کریں، پھر کال کرنے والے کے پاس
# واپس `jr $ra` کی پیروی کریں۔

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #پہلی دلیل
        li   $a1, 42            #دوسری دلیل
        jal  maxof

        move $a0, $v0           #نتیجہ $v0 میں واپس آیا
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof ایک لیف فنکشن ہے، لہذا یہ اسٹیک پر $ra کو محفوظ کیے بغیر واپس آ سکتا ہے۔
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
