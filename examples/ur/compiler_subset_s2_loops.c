int main(void) {
  //ضرورت ہے C0-S2- یا اس سے زیادہ: لوپس، وقفے/جاری، اور ++/-- کے لیے۔
  int sum = 0;   //جمع کرنے والا ایک بار مرتب ہونے والے رجسٹر میں رہتا ہے۔

  for (int i = 0; i < 10; i++) {   //a for loop ایک موازنہ کے علاوہ ایک پسماندہ شاخ بن جاتا ہے۔
    if ((i % 2) == 0) continue;   //جسم کو چھوڑ کر انکریمنٹ کی طرف چھلانگیں جاری رکھیں
    if (i > 7) break;   //بریک چھلانگ لوپ کے اختتام سے گزرتا ہے۔
    sum += i;
  }

  int down = 3;
  down--;   //پوسٹ ڈیکریمنٹ اور پری انکریمنٹ کو ایک ہی ایڈ میں کمپائل کریں۔
  int up = 3;
  ++up;

  //متوقع آؤٹ پٹ: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
