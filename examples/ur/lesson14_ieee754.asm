#
# `lwc1` بٹ پیٹرن کو فلوٹنگ پوائنٹ رجسٹر میں کاپی کرتا ہے۔ پھر `add.s` 3.5 اور 1.25 جوڑ کر 4.75
# پیدا کرتا ہے۔
#
# فلوٹنگ پوائنٹ کی نمائندگی ٹول میں 4.75 اور 0.1 کی انکوڈنگز کا موازنہ کریں۔ 4.75 بالکل درست ہے۔
# 0.1 کو گول کرنے کی ضرورت ہے۔

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU رجسٹر فائل میں
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU ایڈر

        #Syscall 2 خاص طور پر $f12 میں اپنے فلوٹ دلیل کی توقع کرتا ہے۔
        mov.s $f12, $f4
        li   $v0, 2             #پرنٹ فلوٹ
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
