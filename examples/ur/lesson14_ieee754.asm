#THE PROBLEM
#انٹیجر رجسٹر میں 3.5 کی کوئی جگہ نہیں ہے۔ کہاں کرتا ہے
#جزوی حصہ جانا، اور ایک بہت بڑی تعداد کو کیسے ذخیرہ کیا جاتا ہے۔
#ایک ہی 32 بٹس میں ایک بہت چھوٹے کے طور پر؟
#
#WHAT THE HARDWARE DOES
#IEEE-754 لفظ کو تین شعبوں میں تقسیم کرتا ہے: ایک سائن بٹ،
#آٹھ ایکسپوننٹ بٹس اور تئیس فریکشن بٹس۔ دی
#exponent بائنری پوائنٹ کو سلائیڈ کرتا ہے، یہی وجہ ہے کہ فارمیٹ ہے۔
#فلوٹنگ پوائنٹ کہلاتا ہے۔
#
#THE SOLUTION
#ایک علیحدہ رجسٹر فائل ($f0..$f31) اور ایک الگ ایڈر
#ان اقدار کو ہینڈل کریں، یہی وجہ ہے کہ یادداشتیں مختلف ہیں:
#لوڈ کرنے کے لیے lwc1، ایڈ کرنے کے لیے add.s، پرنٹ کرنے کے لیے syscall 2۔
#
#WATCH FOR
#ٹولز > فلوٹنگ پوائنٹ ریپریزنٹیشن کھولیں اور 3.5 درج کریں۔
#تین فیلڈز دیکھیں، پھر چیک کریں کہ 4.75 بالکل درست ہے۔
#0.1 کے برعکس، جس کا کوئی محدود بائنری فریکشن نہیں ہے۔
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #عددی پتے اب بھی ڈیٹا کو تلاش کرتے ہیں۔ lwc1 اپنے بٹس کو COP1 میں منتقل کرتا ہے۔
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU رجسٹر فائل میں
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU ایڈر

        #Syscall 2 خاص طور پر $f12 میں اپنے فلوٹ دلیل کی توقع کرتا ہے۔
        mov.s $f12, $f4
        li   $v0, 2             #پرنٹ فلوٹ
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
