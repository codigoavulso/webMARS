#
#THE PROBLEM
#میموری کو ایک وقت میں ایک بائٹ ایڈریس کیا جاتا ہے، لیکن ایک رجسٹر ہوتا ہے۔
#چار بائٹس ایک واحد پتہ اصل میں کیا منتخب کرتا ہے؟
#
#WHAT THE HARDWARE DOES
#lw اور sw ایک رسائی میں چار بائٹس منتقل کرتے ہیں، تو لگاتار
#الفاظ چار پتے الگ کرتے ہیں۔ کے کم دو بٹس
#ایڈریس صفر ہونا چاہیے: وہ سیدھ وہی ہے جو اجازت دیتی ہے۔
#ہارڈ ویئر ایک چکر میں پورا لفظ لاتا ہے۔
#
#THE SOLUTION
#ایڈریس ریاضی بائٹس میں کیا جاتا ہے، لہذا الفاظ میں ایک اشاریہ
#ہمیشہ چار سے چھوٹا ہوتا ہے۔
#
#WATCH FOR
#جمع کریں، پھر ڈیٹا سیگمنٹ کو 0x10010000 پر کھولیں۔ دی
#تین قدریں ایک قطار کے ملحقہ کالموں میں ظاہر ہوتی ہیں۔
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #بنیادی پتہ

        #ذیل میں موجود ہر آفسیٹ $t0 سے متعلق ہے اور لفظ کے موافق رہتا ہے۔
        li   $t1, 111
        sw   $t1, 0($t0)        #پہلا لفظ
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بائٹس = اگلا لفظ
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بائٹس

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw انہی 32 بٹ اقدار کو دوبارہ تشکیل دیتا ہے جو پہلے sw کے ذریعہ لکھا گیا تھا۔
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
