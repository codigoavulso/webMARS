# 07 - یادداشت میں الفاظ
#
# میموری ایڈریس بائٹس شمار کرتے ہیں۔ ہر لفظ چار بائٹس پر قبضہ کرتا ہے، لہذا `lw` اور `sw` یہاں
# آفسیٹس 0، 4 اور 8 استعمال کریں۔
#
# ایک لفظ کا پتہ چار کا کثیر ہونا چاہیے۔ 4 کے بجائے آفسیٹ 1 کا استعمال اس پروگرام میں سیدھ میں
# رعایت کا سبب بنتا ہے۔
#
# اسٹورز کے بعد، ڈیٹا سیگمنٹ میں `cell` دیکھیں۔ تین ملحقہ الفاظ میں 111، 222 اور 333 ہونا چاہیے۔

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #بنیادی پتہ

        #ذیل میں موجود ہر آفسیٹ $t0 سے متعلق ہے اور لفظ کے موافق رہتا ہے۔
        li   $t1, 111
        sw   $t1, 0($t0)        #پہلا لفظ
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 بائٹس = اگلا لفظ
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 بائٹس

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw انہی 32 بٹ اقدار کو دوبارہ تشکیل دیتا ہے جو پہلے sw کے ذریعہ لکھا گیا تھا۔
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
