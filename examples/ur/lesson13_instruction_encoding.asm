#WHAT THE HARDWARE DOES
#کچھ بھی نہیں، جس سے آگے لفظ کو لوڈ کیا جاتا ہے۔ دی
#PC ایسے الفاظ کا انتخاب کرتا ہے جو ڈیکوڈر پر جاتے ہیں۔ lw الفاظ کا انتخاب کرتا ہے۔
#جو رجسٹر فائل میں جاتا ہے۔ بٹس ایک ہی قسم کے ہیں۔
#
#THE SOLUTION
#انکوڈنگ کو براہ راست پڑھیں۔ جمع کریں اور کھولیں۔
#Main > Execute: کوڈ کالم ہر ہدایت کو بطور دکھاتا ہے۔
#32 بٹ لفظ یہ واقعی ہے۔
#
#WATCH FOR
#یہ سبق مقصد کے مطابق کچھ نہیں پرنٹ کرتا ہے - آؤٹ پٹ ہے۔
#ٹیکسٹ سیگمنٹ خود۔ دو اضافہ کا موازنہ کریں: ایک ہی اوپکوڈ اور
#فنکشن فیلڈز، مختلف رجسٹر نمبر۔ پھر تلاش کریں۔
#اضافی لفظ کے اندر لفظی 100۔
# ==========================================================
        .text
        .globl main
main:
        #اسمبلی کے بعد کوڈ کالم کا معائنہ کریں: یہ یادداشتیں متن کے طور پر محفوظ نہیں ہیں۔
        add  $t0, $t1, $t2      #R-type: opcode, rs, rt, rd, funct
        add  $t3, $t4, $t5      #ایک ہی شکل، مختلف رجسٹر
        addi $t0, $t1, 100      #I-type: مستقل لفظ میں ہے۔
        sll  $t0, $t1, 4        #شفٹ کی رقم کی اپنی فیلڈ ہوتی ہے۔
        j    tail               #J-type: ایک پتہ، رجسٹر نہیں۔
tail:
        #پھانسی سے پہلے li خود کو بڑھایا جاتا ہے۔ پروسیسر صرف انکوڈ شدہ الفاظ دیکھتا ہے۔
        li   $v0, 10
        syscall
