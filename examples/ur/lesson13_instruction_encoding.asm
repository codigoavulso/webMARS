# 13 - ایک ہدایت ایک عدد ہے۔
#
# ٹیکسٹ سیگمنٹ میں کوڈ کالم کو جمع اور معائنہ کریں۔ ہر بنیادی ہدایت ایک 32 بٹ لفظ ہے جسے شعبوں
# میں تقسیم کیا گیا ہے۔
#
# دو `add` ہدایات کا موازنہ کریں۔ آپریشن فیلڈز مماثل ہیں، جبکہ رجسٹر فیلڈز مختلف آپرینڈز کو
# انکوڈ کرتے ہیں۔
#
# `addi` میں، کم 16 بٹس فوری 100 کو رکھتے ہیں، جو `0x0064` ہے۔ اسے 101 میں تبدیل کریں اور تبدیلی
# کو دیکھنے کے لیے دوبارہ جمع کریں۔

        .text
        .globl main
main:
        #اسمبلی کے بعد کوڈ کالم کا معائنہ کریں: یہ یادداشتیں متن کے طور پر محفوظ نہیں ہیں۔
        add  $t0, $t1, $t2      #R-type: opcode, rs, rt, rd, funct
        add  $t3, $t4, $t5      #ایک ہی شکل، مختلف رجسٹر
        addi $t0, $t1, 100      #I-type: مستقل لفظ میں ہے۔
        sll  $t0, $t1, 4        #شفٹ کی رقم کی اپنی فیلڈ ہوتی ہے۔
        j    tail               #J-type: ایک پتہ، رجسٹر نہیں۔
tail:
        #پھانسی سے پہلے li خود کو بڑھایا جاتا ہے۔ پروسیسر صرف انکوڈ شدہ الفاظ دیکھتا ہے۔
        li   $v0, 10
        syscall
