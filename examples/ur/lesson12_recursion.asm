#ایک بار بار آنے والی کال $ra اور دلیل رجسٹر کو اوور رائٹ کر دیتی ہے۔
#بیرونی کال کے پاس پھر واپسی کا کوئی راستہ نہیں ہے اور اس کا کوئی اندازہ نہیں ہے۔
#اپنا ن تھا.
#
#WHAT THE HARDWARE DOES
#یہ ایک $ra فراہم کرتا ہے، نہ کہ ان کا ڈھیر۔ کچھ بھی نہیں بچا
#خود کار طریقے سے؛ اگر کوڈ اسے محفوظ نہیں کرتا ہے، تو یہ چلا گیا ہے۔
#
#THE SOLUTION
#ہر ایکٹیویشن اسٹیک پر ایک فریم کھولتا ہے، اسے رکھتا ہے۔
#کال کے بعد بھی ضرورت ہوگی، اور راستے میں اسے بحال کردے گا۔
#باہر اسٹیک کی گہرائی تکرار کی گہرائی ہے۔
#
#WATCH FOR
#mul پر ایک بریک پوائنٹ سیٹ کریں اور $sp کو 8 فی پر اترتے دیکھیں
#سطح n کی پانچ محفوظ شدہ کاپیاں وہی ہیں جو بناتی ہیں۔
#ممکنہ واپسی کے راستے پر ضرب۔
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #ہر درخواست ایک الگ آٹھ بائٹ فریم کا مالک ہے۔
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #اس کال کی واپسی کا پتہ
        sw   $a0, 4($sp)        #اس کال کی این

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #بیس کیس: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #ہمارے ن دوبارہ
        mul  $v0, $v0, $a0

factend:
        #کالی حالت کو بحال کریں اور اندراج پر مختص کردہ فریم کو بالکل ضائع کریں۔
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
