# 12 - تکرار اور فریم
#
# ایک بار بار آنے والی کال `$ra` کو اوور رائٹ کرتی ہے اور اپنی دلیل کے لیے `$a0` استعمال کرتی
# ہے۔ کال کرنے سے پہلے دونوں اقدار کو محفوظ کریں۔
#
# 5 سے 1 تک ہر قدر کے لیے `fact` میں قدم رکھیں۔ ہر کال آٹھ بائٹس محفوظ رکھتی ہے، بشمول وہ کال جو
# 1 واپس کرتی ہے۔
#
# واپسی کا راستہ دیکھنے کے لیے `mul` پر بریک پوائنٹ سیٹ کریں۔ ہر کال اپنی دلیل کو دوبارہ لوڈ
# کرتی ہے، اپنے فریم کو ضرب اور جاری کرتی ہے۔

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fact(int n) ----
fact:
        #ہر درخواست ایک الگ آٹھ بائٹ فریم کا مالک ہے۔
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #اس کال کی واپسی کا پتہ
        sw   $a0, 4($sp)        #اس کال کی این

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #بیس کیس: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #ہمارے ن دوبارہ
        mul  $v0, $v0, $a0

factend:
        # اس کال کے فریم کو جاری کرنے سے پہلے محفوظ کردہ واپسی کا پتہ بحال کریں۔
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
