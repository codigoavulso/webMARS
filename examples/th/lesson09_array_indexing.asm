# 09 - การทำดัชนีอาร์เรย์
#
# แต่ละองค์ประกอบอาร์เรย์มีขนาดสี่ไบต์ เลื่อนดัชนีไปทางซ้ายสองเพื่อคำนวณออฟเซ็ตไบต์
#
# ทำตามลำดับ `sll`, `add`, `lw`: ปรับขนาดดัชนี เพิ่มที่อยู่ฐาน และโหลดองค์ประกอบ
#
# ที่ดัชนี 2 `$t5` คือ 8 และ `$t6` ชี้ไปที่ค่า 30 องค์ประกอบทั้งห้ารวมกันได้ 150

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #ฐาน
        li   $t1, 0             #ฉัน
        li   $t2, 5             #ความยาว
        li   $t3, 0             #สะสม

sum:
        #ค่าคงที่ของลูป: $t3 คือผลรวมของ arr[0] ถึง arr[i-1]
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #ฉัน * 4 ไบต์
        add  $t6, $t0, $t5      #ฐาน + ดัชนีที่ปรับขนาด
        #$t6 ตอนนี้ตั้งชื่อองค์ประกอบเดียวเท่านั้น lw ดึงค่า 32 บิต
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
