#THE PROBLEM
#คำสั่งโหลดมีรีจิสเตอร์พื้นฐานและค่าคงที่
#ชดเชย ไม่มีอะไรอื่น แล้ว [i] จะไปถึงได้อย่างไร ในเมื่อฉันเท่านั้น
#รู้จักกันตอนรันไทม์ กำลังนั่งอยู่ในรีจิสเตอร์ใช่ไหม?
#
#WHAT THE HARDWARE DOES
#มันเพิ่มฐานให้กับสิ่งที่ลงทะเบียนเก็บไว้ ดัชนี
#จึงต้องอยู่ในหน่วยไบต์อยู่แล้ว ไม่ใช่ในองค์ประกอบ
#
#THE SOLUTION
#ปรับขนาดดัชนีตามขนาดองค์ประกอบ จากนั้นจึงบวก สำหรับสี่ไบต์
#คำที่ปรับขนาดเป็นกะซ้ายสองซึ่งมีค่าใช้จ่าย
#ไม่มีอะไร
#
#WATCH FOR
#สามบรรทัด sll, add, lw คือสิ่งที่ a[i] คอมไพล์
#ทำตามขั้นตอนซ้ำหนึ่งครั้งแล้วอ่าน $t5 และ $t6
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #ฐาน
        li   $t1, 0             #ฉัน
        li   $t2, 5             #ความยาว
        li   $t3, 0             #สะสม

sum:
        #ค่าคงที่ของลูป: $t3 คือผลรวมของ arr[0] ถึง arr[i-1]
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #ฉัน * 4 ไบต์
        add  $t6, $t0, $t5      #ฐาน + ดัชนีที่ปรับขนาด
        #$t6 ตอนนี้ตั้งชื่อองค์ประกอบเดียวเท่านั้น lw ดึงค่า 32 บิต
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
