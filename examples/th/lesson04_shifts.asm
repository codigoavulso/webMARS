# ==========================================================
#บทที่ 04 - เลื่อนหรือคูณด้วยสายไฟ
#
#THE PROBLEM
#ตัวคูณทั่วไปเป็นหนึ่งในบล็อกที่แพงที่สุด
#พาธข้อมูล การคูณด้วย 8 ไม่น่าจะแพงขนาดนั้น
#
#WHAT THE HARDWARE DOES
#การเปลี่ยนแปลงไม่ใช่เลขคณิต แต่เป็นบิตเดียวกันที่อ่าน
#จากสายไฟที่แตกต่างกัน การเลื่อนไปทางซ้ายด้วย n คูณด้วย 2^n
#และมีค่าใช้จ่ายเพียงการกำหนดเส้นทางเท่านั้น
#
#THE SOLUTION
#พลังของทั้งสองกลายเป็นกะ สังเกตกะด้านขวาสองอัน: srl
#ป้อนค่าศูนย์ที่ด้านบน sra จะคัดลอกบิตเครื่องหมาย ดังนั้นเท่านั้น
#sra หารจำนวนลบได้อย่างถูกต้อง
#
#WATCH FOR
#-16 >> 2 ให้ -4 กับ sra แต่เป็นบวกอย่างมากกับ srl ที่
#บิตถูกย้ายเหมือนกัน เฉพาะสิ่งที่ป้อนที่ด้านบนเท่านั้นที่แตกต่างกัน
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #การเลื่อนไปทางซ้ายสามครั้งคูณด้วย 2^3 โดยคงไว้เพียง 32 บิตผลลัพธ์
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #เปรียบเทียบ $t3 และ $t4 เป็นเลขฐานสิบหกเพื่อดูบิตขาเข้าที่แตกต่างกัน
        sra  $t3, $t2, 2        #เครื่องหมายที่เก็บรักษาไว้: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #ศูนย์เลื่อนเข้ามา: เป็นบวกอย่างมาก
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
