# 04 - การเปลี่ยนแปลงและพลังของทั้งสอง
#
# การเลื่อนไปทางซ้ายด้วย 3 คูณด้วย 8 เมื่อผลลัพธ์ออกมาพอดี บิตที่เลื่อนผ่านขอบจะถูกละทิ้ง
#
# ทางด้านขวา `srl` เติมศูนย์และ `sra` คัดลอกบิตเครื่องหมาย สำหรับ -16 เลื่อนด้วย 2 คาดว่าจะเป็น
# 1073741820 และ -4 ตามลำดับ
#
# ลอง -15 ด้วย `sra` ผลลัพธ์คือ -4 เนื่องจากกะปัดลง ลงนามการแบ่งรอบไปสู่ศูนย์

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #การเลื่อนไปทางซ้ายสามครั้งคูณด้วย 2^3 โดยคงไว้เพียง 32 บิตผลลัพธ์
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #เปรียบเทียบ $t3 และ $t4 เป็นเลขฐานสิบหกเพื่อดูบิตขาเข้าที่แตกต่างกัน
        sra  $t3, $t2, 2        #เครื่องหมายที่เก็บรักษาไว้: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #ศูนย์เลื่อนเข้ามา: เป็นบวกอย่างมาก
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
