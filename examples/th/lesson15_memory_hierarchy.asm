# 15 - เหตุใดการก้าวย่างจึงเปลี่ยนความเร็ว
#
# ทั้งสองลูปใช้อาเรย์เดียวกัน คนแรกอ่านทั้งหมด 256 คำ ส่วนที่สองอ่านทุกๆ คำที่ 16
# โดยโหลดได้เพียง 16 ครั้ง
#
# ด้วยบล็อกแคชที่มี 16 คำ การอ่านตามลำดับสามารถนำแต่ละบล็อกที่ดึงมามาใช้ซ้ำได้
# วงที่สองจะเลื่อนไปยังบล็อกใหม่ในแต่ละโหลด
#
# เชื่อมต่อเครื่องจำลองกับ MIPS เลือก «เปิดใช้งานแล้ว» และตั้งขนาดบล็อกเป็น 16 คำ
# ใช้ เครื่องจำลองแคชข้อมูล โดยมีเบรกพอยต์ที่ `far` เพื่อตรวจสอบลูปแรก
# รีเซ็ตสถิติแคชที่นั่นก่อนที่จะรันลูปที่สอง และเปรียบเทียบอัตราการเข้าชม

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# การผ่านตามลำดับ: ทั้งหมด 256 คำ
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #ดัชนีตามลำดับจะใช้คำจากแต่ละบล็อกแคชซ้ำก่อนที่จะดำเนินการต่อ
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# Strided pass: โหลดหนึ่งครั้งทุกๆ สิบหกคำ
        li   $t1, 0
        li   $t3, 0
far:
        # ที่อยู่ถัดไปอยู่ห่างออกไป 64 ไบต์: สิบหกคำ แต่ละคำมีขนาดสี่ไบต์
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
