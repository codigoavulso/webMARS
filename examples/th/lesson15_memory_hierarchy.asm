#บทที่ 15 - เหตุใดการก้าวจึงเปลี่ยนความเร็ว
#
#THE PROBLEM
#สองลูปด้านล่างอ่านอาร์เรย์เดียวกันและดำเนินการเหมือนกัน
#จำนวนโหลด บนเครื่องจริงจะช้ากว่ามาก ที่
#จำนวนคำสั่งไม่สามารถอธิบายได้
#
#WHAT THE HARDWARE DOES
#หน่วยความจำไม่ได้ส่งคำเดียว พลาดดึงทั้งหมด
#บล็อกเดิมพันว่าคำข้างเคียงจะต้องการในไม่ช้า
#ก้าวหนึ่งรวบรวมเดิมพันนั้น ก้าวสิบหกจ่าย
#สำหรับบล็อกและอ่านหนึ่งคำ
#
#THE SOLUTION
#ไม่มีอะไรในการเปลี่ยนแปลงรหัส ท้องถิ่นเป็นทรัพย์สินของ
#รูปแบบการเข้าถึงและเป็นรูปแบบที่ต้องแก้ไข
#
#WATCH FOR
#เปิดเครื่องมือ > Data Cache Simulator กดเชื่อมต่อไปที่ MIPS
#แล้ววิ่ง เปรียบเทียบอัตราการตีของทั้งสองลูป จำนวนเงินทั้งสอง
#พิมพ์ 0 เนื่องจากอาร์เรย์เป็นศูนย์ - ตัวเลขไม่ใช่
#จุดนี้ อัตราการเข้าชมคือ
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- ทุกคำของแต่ละบล็อก ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #ดัชนีตามลำดับจะใช้คำจากแต่ละบล็อกแคชซ้ำก่อนที่จะดำเนินการต่อ
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- หนึ่งคำต่อบล็อก ห่างกันสิบหกคำ ----
        li   $t1, 0
        li   $t3, 0
far:
        #การเพิ่ม 16 ข้าม 64 ไบต์ต่อการวนซ้ำ: โดยทั่วไปจะเป็นหนึ่งบล็อกแคชทั้งหมด
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
