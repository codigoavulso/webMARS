#THE PROBLEM
#การกระโดดเข้าสู่กิจวัตรประจำวันเป็นเรื่องง่าย กลับไม่ได้เพราะว่า
#กิจวัตรเดียวกันอาจเรียกได้จากหลายที่และ
#ที่อยู่ผู้ส่งจะแตกต่างกันทุกครั้ง
#
#WHAT THE HARDWARE DOES
#jal ทำสองสิ่งในคำสั่งเดียว: มันเก็บ
#ที่อยู่ของคำสั่งต่อไปนี้ใน $ra จากนั้นจึงข้ามไป จูเนียร์
#ข้ามไปยังสิ่งที่รีจิสเตอร์เก็บไว้ ดังนั้น jr $ra จึงกลับมา
#
#THE SOLUTION
#ทุกสิ่งทุกอย่างเป็นไปตามข้อตกลง ไม่ใช่วงจรไฟฟ้า: อาร์กิวเมนต์ใน
#$a0..$a3 ผลลัพธ์จะเป็น $v0 ทำลายแบบแผนและรหัส
#ยังคงประกอบอยู่ - มันก็หยุดการทำงานร่วมกัน
#
#WATCH FOR
#ก้าวเข้าสู่ jal แล้วอ่าน $ra เปรียบเทียบกับที่อยู่
#ของบรรทัดหลังการโทรในส่วนข้อความ
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #อาร์กิวเมนต์แรก
        li   $a1, 42            #อาร์กิวเมนต์ที่สอง
        #jal เปลี่ยนทั้งโฟลว์การควบคุมและ $ra ในการดำเนินการทางสถาปัตยกรรมเดียว
        jal  maxof              #$ra = ที่อยู่ของบรรทัดถัดไป

        move $a0, $v0           #ผลลัพธ์กลับมาใน $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof (int a, int b) ----
maxof:
        #maxof เป็นฟังก์ชัน leaf จึงสามารถส่งคืนได้โดยไม่ต้องบันทึก $ra ลงในสแต็ก
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
