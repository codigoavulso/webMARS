# 11 - การเรียกใช้ฟังก์ชัน
#
# วิ่งโดยมีการแตกแขนงออกไปล่าช้า `jal` ข้ามไปที่ฟังก์ชันและใส่ที่อยู่ของคำสั่งถัดไปใน `$ra`
#
# แบบแผนการเรียกผ่าน 17 และ 42 ใน `$a0` และ `$a1` ฟังก์ชันส่งคืนค่าที่มากกว่าใน `$v0`
#
# ก้าวเข้าสู่การโทร เปรียบเทียบ `$ra` กับที่อยู่หลัง `jal` จากนั้นตาม `jr $ra` กลับไปที่ผู้โทร

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #อาร์กิวเมนต์แรก
        li   $a1, 42            #อาร์กิวเมนต์ที่สอง
        jal  maxof

        move $a0, $v0           #ผลลัพธ์กลับมาใน $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof (int a, int b) ----
maxof:
        #maxof เป็นฟังก์ชัน leaf จึงสามารถส่งคืนได้โดยไม่ต้องบันทึก $ra ลงในสแต็ก
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
