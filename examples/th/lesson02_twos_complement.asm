# 02 - ส่วนเติมเต็มของสอง
#
# ในส่วนเสริมของ two แบบ 32 บิต การกลับบิตของ 5 และการเพิ่ม 1 จะสร้างการแสดงค่าของ -5
#
# โปรแกรมคำนวณค่าเดียวกันสองวิธี: `sub` จากศูนย์ จากนั้น `nor` และ `addi`
#
# ทั้งสองเส้นทางพิมพ์ -5 ตรวจสอบ `0xFFFFFFFB`
# ในรีจิสเตอร์เพื่อดูว่าบิตเดียวกันมีลักษณะเป็นเลขฐานสิบหกอย่างไร

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #การลบออกจากศูนย์จะทำให้เกิดค่าผกผันการบวกโดยไม่มีเครื่องหมายลบ
        li   $t0, 5
        sub  $t1, $zero, $t0    #ตัวบวกจะทำงาน
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #หรือด้วย $zero จะเป็นระดับบิต NOT; การเพิ่มหนึ่งเติมเต็มส่วนเสริมของสอง
        nor  $t2, $t0, $zero    #กลับบิตทั้งหมด
        addi $t2, $t2, 1        #เพิ่มอันหนึ่ง
        move $a0, $t2           #ค่าเดียวกันกับด้านบน
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
