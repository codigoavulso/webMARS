#
#THE PROBLEM
#รีจิสเตอร์มีสายไฟ 32 เส้น แต่ละเส้นสูงหรือต่ำ ไม่มีลวด
#สำหรับเครื่องหมายลบ แต่จำนวนลบจะต้องใช้ได้
#
#WHAT THE HARDWARE DOES
#มันอ่านบิตบนสุดเป็นเครื่องหมาย แต่ไม่ใช่เป็นแฟล็กแยกต่างหาก:
#-n ถูกจัดเก็บเป็นรูปแบบบิตที่เพิ่มเข้าไปใน n แล้วตัดคำ
#ศูนย์ กลับด้านทุก ๆ บิตแล้วเพิ่มหนึ่งอันแล้วคุณก็จะได้มัน
#
#THE SOLUTION
#การลบไม่จำเป็นต้องมีวงจรที่สอง a - b กลายเป็น
#a + (-b) ดังนั้น adder หนึ่งตัวจึงทำหน้าที่ทั้งสองการดำเนินการ
#
#WATCH FOR
#พิมพ์ทั้งสองครึ่ง -5 ครั้งที่สองไปถึงมันเป็นระยะทางไกล
#ด้วย nor และ addi แสดงว่าส่วนย่อยทำอะไรภายใน
#ตั้งค่าเป็นเลขฐานสิบหกเพื่อดู 0xFFFFFFFB
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #การลบออกจากศูนย์จะทำให้เกิดค่าผกผันการบวกโดยไม่มีเครื่องหมายลบ
        li   $t0, 5
        sub  $t1, $zero, $t0    #ตัวบวกจะทำงาน
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #หรือด้วย $zero จะเป็นระดับบิต NOT; การเพิ่มหนึ่งเติมเต็มส่วนเสริมของสอง
        nor  $t2, $t0, $zero    #กลับบิตทั้งหมด
        addi $t2, $t2, 1        #เพิ่มอันหนึ่ง
        move $a0, $t2           #ค่าเดียวกันกับด้านบน
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
