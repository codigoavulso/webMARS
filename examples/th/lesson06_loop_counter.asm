#บทที่ 06 - ตัวนับ ในซอฟต์แวร์และฮาร์ดแวร์
#
#THE PROBLEM
#ตัวนับฮาร์ดแวร์คือรีจิสเตอร์ ตัวเพิ่ม และก
#ตัวเปรียบเทียบ เครื่องเดียวกันมีลักษณะเขียนว่าอย่างไร
#เป็นคำแนะนำเหรอ?
#
#WHAT THE HARDWARE DOES
#สามส่วนนั้น หนึ่งส่วนต่อคำสั่ง: รีจิสเตอร์
#ถือการนับ addi เป็นตัวเพิ่ม slt ด้วยสาขา
#เป็นผู้เปรียบเทียบตัดสินในรอบต่อไป
#
#THE SOLUTION
#การวนซ้ำไม่ใช่แนวคิดใหม่ มันเป็นตรรกะที่สะกดตามลำดับ
#ออกไป โดยมีพีซีเป็นนาฬิกา
#
#WATCH FOR
#$t0 คือรีจิสเตอร์การนับและ $t1 เป็นขีดจำกัด ก้าวผ่าน
#เต็มรอบแล้วบอกชื่อเส้นไหนส่วนไหน
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #การลงทะเบียนการนับ
        li   $t1, 11            #ขีด จำกัด

loop:
        #ค่าคงที่ของลูป: $t0 เป็นค่าถัดไปที่จะพิมพ์และยังคงอยู่ต่ำกว่า $t1
        slt  $t2, $t0, $t1      #ตัวเปรียบเทียบ
        beq  $t2, $zero, endl   #ออกเมื่อนับถึงขีดจำกัด

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #การอัปเดตตัวนับก่อนกระโดดรับประกันความคืบหน้าไปสู่การยกเลิก
        addi $t0, $t0, 1        #งูพิษ
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
