# 06 - วนซ้ำเป็นตัวนับ
#
# `$t0` คือหมายเลขถัดไปที่จะพิมพ์ `$t1` เป็นขีดจำกัดบนพิเศษ ดังนั้นขีดจำกัด 11 พิมพ์ 1 ถึง 10
#
# การเปรียบเทียบจะดำเนินการก่อนการวนซ้ำแต่ละครั้ง การเพิ่มขึ้นจะทำให้คืบหน้าไปสู่ขีดจำกัด
# และการกระโดดจะทำซ้ำการตรวจสอบ
#
# เปลี่ยนขีดจำกัดเป็น 1 แล้วรัน สาขาทางออกจะถูกถ่ายก่อนการพิมพ์ครั้งแรก

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #การลงทะเบียนการนับ
        li   $t1, 11            #ขีด จำกัด

loop:
        # ในการทดสอบลูป $t0 คือตัวเลือกถัดไป พิมพ์เฉพาะในกรณีที่ต่ำกว่า $t1
        slt  $t2, $t0, $t1      #ตัวเปรียบเทียบ
        beq  $t2, $zero, endl   #ออกเมื่อนับถึงขีดจำกัด

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #การอัปเดตตัวนับก่อนกระโดดรับประกันความคืบหน้าไปสู่การยกเลิก
        addi $t0, $t0, 1        #งูพิษ
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
