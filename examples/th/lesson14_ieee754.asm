# ==========================================================
#บทที่ 14 - จำนวนจริงใน 32 บิต
#
#THE PROBLEM
#3.5 ไม่มีตำแหน่งในการลงทะเบียนจำนวนเต็ม ที่ไหน
#เศษส่วนไปและเก็บไว้เป็นจำนวนมากได้อย่างไร
#ใน 32 บิตเดียวกับอันที่เล็กมากเหรอ?
#
#WHAT THE HARDWARE DOES
#IEEE-754 แยกคำออกเป็นสามฟิลด์: หนึ่งเครื่องหมายบิต
#เลขชี้กำลังแปดบิตและเศษส่วนยี่สิบสามบิต ที่
#เลขชี้กำลังเลื่อนจุดไบนารี่ ซึ่งเป็นสาเหตุที่ทำให้เกิดรูปแบบ
#เรียกว่าจุดลอยตัว
#
#THE SOLUTION
#ไฟล์รีจิสเตอร์แยกต่างหาก ($f0..$f31) และตัวเสริมแยกต่างหาก
#จัดการกับค่าเหล่านี้ ซึ่งเป็นเหตุผลว่าทำไมการช่วยจำจึงแตกต่างกัน:
#lwc1 เพื่อโหลด, add.s เพื่อเพิ่ม, syscall 2 เพื่อพิมพ์
#
#WATCH FOR
#เปิดเครื่องมือ > การแสดงจุดลอยตัว และป้อน 3.5
#ดูทั้งสามช่องแล้วตรวจสอบว่า 4.75 ตรงหรือไม่ -
#ต่างจาก 0.1 ซึ่งไม่มีเศษส่วนไบนารี่จำกัด
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #ที่อยู่จำนวนเต็มยังคงค้นหาข้อมูล lwc1 ย้ายบิตไปที่ COP1
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #ลงในไฟล์รีจิสเตอร์ FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #ตัวเสริม FPU

        #Syscall 2 คาดว่าอาร์กิวเมนต์ float โดยเฉพาะใน $f12
        mov.s $f12, $f4
        li   $v0, 2             #พิมพ์ลอย
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
