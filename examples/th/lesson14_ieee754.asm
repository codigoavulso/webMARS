# 14 - จำนวนจริงใน 32 บิต
#
# ทศนิยมที่มีความแม่นยำเดี่ยวมีบิตเครื่องหมายหนึ่งบิต บิตเลขชี้กำลังแปดบิต และบิตเศษส่วน 23 บิต
#
# `lwc1` คัดลอกรูปแบบบิตลงในรีจิสเตอร์ทศนิยม จากนั้น `add.s` บวก 3.5 และ 1.25 เพื่อสร้าง 4.75
#
# เปรียบเทียบการเข้ารหัสของ 4.75 และ 0.1 ในเครื่องมือ การแสดงจุดลอยตัว 4.75 คือค่าที่แน่นอน; 0.1
# ต้องการการปัดเศษ

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #ลงในไฟล์รีจิสเตอร์ FPU
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #ตัวเสริม FPU

        #Syscall 2 คาดว่าอาร์กิวเมนต์ float โดยเฉพาะใน $f12
        mov.s $f12, $f4
        li   $v0, 2             #พิมพ์ลอย
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
