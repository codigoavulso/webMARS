int main(void) {
  //ต้องใช้ C0-S2- หรือสูงกว่า: สำหรับลูป แบ่ง/ดำเนินการต่อ และ ++/--
  int sum = 0;   //ตัวสะสมอาศัยอยู่ในรีจิสเตอร์เมื่อรวบรวมแล้ว

  for (int i = 0; i < 10; i++) {   //a for loop กลายเป็นการเปรียบเทียบบวกกับสาขาย้อนหลัง
    if ((i % 2) == 0) continue;   //กระโดดต่อไปเรื่อย ๆ โดยข้ามร่างกาย
    if (i > 7) break;   //เบรกกระโดดเลยจุดสิ้นสุดของวง
    sum += i;
  }

  int down = 3;
  down--;   //การคอมไพล์หลังการลดและการเพิ่มล่วงหน้าเป็นการเพิ่มเดียวกัน
  int up = 3;
  ++up;

  //ผลลัพธ์ที่คาดหวัง: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
