#สวัสดีชาวโลกสำหรับ Run I/O
#พิมพ์ข้อความธรรมดาและออก
#นี่คือตัวอย่างที่เล็กที่สุดของการแยกข้อมูล/ข้อความและแบบแผน syscall

.data
#.asciiz เก็บอักขระที่ตามด้วยจุดสิ้นสุดที่เป็นศูนย์ซึ่งจำเป็นสำหรับ syscall 4
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #เลือกสตริงการพิมพ์ (4) ใน $v0 และส่งที่อยู่สตริงใน $a0
  li $v0, 4
  la $a0, msg
  syscall

  #ทางออก (10) หยุดโปรแกรมจำลองอย่างสมบูรณ์
  li $v0, 10
  syscall
