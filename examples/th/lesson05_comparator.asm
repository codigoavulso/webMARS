# 05 - ตัวเปรียบเทียบและสาขา
#
# `slt` เปรียบเทียบจำนวนเต็มที่มีเครื่องหมายสองตัว และเขียน 1 เมื่อจำนวนเต็มแรกน้อยกว่า
# หรือมิฉะนั้น 0
#
# สำหรับ 7 และ 12 `$t2` คือ 1 ดังนั้น `beq` จะไม่ข้ามไปที่ `notless`
# และการดำเนินการจะดำเนินต่อไปยังคำสั่งถัดไป
#
# เมื่อเกิดการแตกแขนงล่าช้า ให้ก้าวผ่าน `beq` แล้วสังเกตพีซี
# สลับค่าอินพุตทั้งสองและเปรียบเทียบปลายทางใหม่

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ก
        li   $t1, 12            #ข
        #slt ทำให้การเปรียบเทียบเป็นจริงเป็นจำนวนเต็มธรรมดา ไม่เคยเป็นแฟล็กที่ซ่อนอยู่
        slt  $t2, $t0, $t1      #t2 = 1 ถ้า a < b
        #แยกสาขาไปไม่เฉพาะเมื่อผลลัพธ์บูลีนนั้นเป็นศูนย์
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
