#THE PROBLEM
#การตัดสินใจต้องใช้หนึ่งบิต แต่เปรียบเทียบตัวเลข 32 บิตสองตัว
#คือการลบ การลบกลายเป็นทางเลือกได้อย่างไร?
#
#WHAT THE HARDWARE DOES
#slt ลบและทิ้งทุกอย่างยกเว้นเครื่องหมาย
#กำลังเขียน 0 หรือ 1 จากนั้นสาขาจะฟีดบิตนั้นไปยังพีซี
#ลอจิกซึ่งจะเพิ่มออฟเซ็ตหรือปล่อยให้พีซีก้าวไปข้างหน้า
#
#THE SOLUTION
#เปรียบเทียบกับรีจิสเตอร์ สาขาในรีจิสเตอร์นั้น การควบคุม
#โฟลว์เป็นเลขคณิตบวกหนึ่งมัลติเพล็กเซอร์บนพีซี
#
#WATCH FOR
#หลังจาก slt แล้ว $t2 ถือ 1 ก้าวผ่าน beq และดูพีซี
#ในแถบสถานะ: จะกระโดดแทนที่จะก้าวหน้าไปสี่
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ก
        li   $t1, 12            #ข
        #slt ทำให้การเปรียบเทียบเป็นจริงเป็นจำนวนเต็มธรรมดา ไม่เคยเป็นแฟล็กที่ซ่อนอยู่
        slt  $t2, $t0, $t1      #t2 = 1 ถ้า a < b
        #แยกสาขาไปไม่เฉพาะเมื่อผลลัพธ์บูลีนนั้นเป็นศูนย์
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
