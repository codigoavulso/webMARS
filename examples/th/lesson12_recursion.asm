# 12 - การเรียกซ้ำและเฟรม
#
# การเรียกซ้ำจะเขียนทับ `$ra` และใช้ `$a0` สำหรับอาร์กิวเมนต์ของตัวเอง
# บันทึกทั้งสองค่าก่อนโทรออก
#
# ก้าวเข้าสู่ `fact` สำหรับแต่ละค่าตั้งแต่ 5 ถึง 1 ทุกการโทรสงวนไว้แปดไบต์
# รวมถึงการเรียกที่ส่งคืน 1
#
# ตั้งเบรกพอยต์บน `mul` เพื่อดูเส้นทางกลับ การเรียกแต่ละครั้งจะรีโหลดอาร์กิวเมนต์ของตัวเอง
# คูณและปล่อยเฟรมของมัน

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- ข้อเท็จจริงที่แท้จริง (int n) ----
fact:
        #การร้องขอแต่ละครั้งมีเฟรมแปดไบต์ที่แตกต่างกัน
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #ที่อยู่ผู้ส่งสายนี้
        sw   $a0, 4($sp)        #สายนี้โทรมา

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #กรณีฐาน: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #n ของเราอีกครั้ง
        mul  $v0, $v0, $a0

factend:
        # กู้คืนที่อยู่ผู้ส่งที่บันทึกไว้ก่อนที่จะปล่อยเฟรมการโทรนี้
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
