#THE PROBLEM
#การเรียกซ้ำจะเขียนทับ $ra และการลงทะเบียนอาร์กิวเมนต์
#การโทรภายนอกไม่มีทางย้อนกลับและไม่รู้ว่ามันคืออะไร
#ของตัวเองคือ
#
#WHAT THE HARDWARE DOES
#โดยจะมี $ra หนึ่งรายการ ไม่ใช่สแต็ก ไม่มีอะไรถูกบันทึกไว้
#โดยอัตโนมัติ; หากโค้ดไม่บันทึกแสดงว่าโค้ดนั้นหายไป
#
#THE SOLUTION
#การเปิดใช้งานแต่ละครั้งจะเปิดเฟรมบนสแต็ก และเก็บสิ่งที่มันอยู่
#จะยังคงต้องการหลังจากการโทรและเรียกคืนระหว่างทาง
#ออก ความลึกของสแต็กคือความลึกของการเรียกซ้ำ
#
#WATCH FOR
#ตั้งจุดพักบน mul และดู $sp ลดลง 8 ต่อ
#ระดับ สำเนาที่บันทึกไว้ทั้งห้าของ n คือสิ่งที่ทำให้
#การคูณระหว่างทางกลับเป็นไปได้
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- ข้อเท็จจริงที่แท้จริง (int n) ----
fact:
        #การร้องขอแต่ละครั้งมีเฟรมแปดไบต์ที่แตกต่างกัน
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #ที่อยู่ผู้ส่งสายนี้
        sw   $a0, 4($sp)        #สายนี้โทรมา

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #กรณีฐาน: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #n ของเราอีกครั้ง
        mul  $v0, $v0, $a0

factend:
        #กู้คืนสถานะผู้ถูกเรียกและละทิ้งเฟรมที่จัดสรรเมื่อเข้า
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
