# 08 - ไบต์และลำดับไบต์
#
# ในหน่วยความจำ little-endian ของโปรแกรมจำลองนี้
# ไบต์ที่มีนัยสำคัญน้อยที่สุดของคำจะอยู่ที่ที่อยู่ต่ำสุด
#
# เก็บ `0x04030201` เป็นคำและอ่านออฟเซ็ต 0 ถึง 3 เป็นไบต์ เอาต์พุตคือ 1, 2, 3, 4
#
# ลองไบต์ต่ำของ `0xFF` โหลดที่ไม่ได้ลงนามด้วย `lbu` ให้ 255 ในขณะที่โหลดที่ลงนามด้วย `lb` ให้ -1

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #ไบต์ 01 มีนัยสำคัญน้อยที่สุด
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #ไบต์ชดเชย
bloop:
        #การเข้าชมแบบวนซ้ำจะชดเชย 0, 1, 2 และ 3 ภายในคำที่เก็บไว้
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #ที่อยู่ที่มีประสิทธิภาพ = ที่อยู่ฐาน + ออฟเซ็ตไบต์ปัจจุบัน
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #ไบต์ที่ไม่ได้ลงนาม
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
