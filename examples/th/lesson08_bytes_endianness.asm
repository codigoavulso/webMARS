#
#THE PROBLEM
#คำหนึ่งตรงบริเวณที่อยู่สี่แห่ง ไบต์ใดทำได้น้อยที่สุด
#ของชื่อที่อยู่เหล่านั้นเหรอ?
#
#WHAT THE HARDWARE DOES
#ตัวเลือกนั้นคือลำดับไบต์และเป็นการตัดสินใจในการเดินสาย
#ครั้งเดียวทั้งเครื่อง MIPS นี่คือ little-endian: the
#ไบต์ที่มีนัยสำคัญน้อยที่สุดอาศัยอยู่ที่ที่อยู่ต่ำสุด
#
#THE SOLUTION
#เก็บหนึ่งคำ จากนั้นอ่านกลับทีละไบต์แล้วปล่อยไป
#คำสั่งซื้อตอบคำถามสำหรับคุณ
#
#WATCH FOR
#0x04030201 กลับมาเป็น 1 2 3 4. ไบต์ที่เขียนสุดท้ายใน
#อ่านตัวอักษรก่อน lbu ถูกใช้มากกว่า lb ดังนั้น a
#ไบต์ที่สูงกว่า 127 ไม่ได้ขยายสัญญาณ
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #ไบต์ 01 มีนัยสำคัญน้อยที่สุด
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #ไบต์ชดเชย
bloop:
        #การเข้าชมแบบวนซ้ำจะชดเชย 0, 1, 2 และ 3 ภายในคำที่เก็บไว้
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #ที่อยู่ที่มีประสิทธิภาพ = ที่อยู่ฐาน + ออฟเซ็ตไบต์ปัจจุบัน
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #ไบต์ที่ไม่ได้ลงนาม
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
