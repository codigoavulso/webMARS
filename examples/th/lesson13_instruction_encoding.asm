#THE PROBLEM
#โปรเซสเซอร์ดึงคำจากหน่วยความจำ รหัสอาศัยอยู่ใน
#หน่วยความจำด้วย ดังนั้นสิ่งที่ทำให้คำสั่งแตกต่างจากก
#ชิ้นส่วนของข้อมูลเหรอ?
#
#WHAT THE HARDWARE DOES
#ไม่มีอะไรที่เกินกว่าการลงทะเบียนคำนั้นจะถูกโหลดเข้าไป ที่
#พีซีเลือกคำที่ไปที่ตัวถอดรหัส ฉันจะเลือกคำ
#ที่ไปที่ไฟล์รีจิสเตอร์ บิตเป็นชนิดเดียวกัน
#
#THE SOLUTION
#อ่านการเข้ารหัสโดยตรง ประกอบและเปิด
#Main > Execute: คอลัมน์ Code จะแสดงแต่ละคำสั่งเป็น
#มันเป็นคำแบบ 32 บิตจริงๆ
#
#WATCH FOR
#บทเรียนนี้ไม่ได้พิมพ์ออกมาโดยไม่ได้ตั้งใจ - ผลลัพธ์คือ
#ส่วนข้อความนั้นเอง เปรียบเทียบทั้งสองการเพิ่ม: opcode เดียวกันและ
#ฟิลด์ฟังก์ชัน หมายเลขรีจิสเตอร์ที่แตกต่างกัน แล้วหา
#ตัวอักษร 100 ภายในคำ addi
# ==========================================================
        .text
        .globl main
main:
        #ตรวจสอบคอลัมน์รหัสหลังการประกอบ: ตัวช่วยจำเหล่านี้จะไม่ถูกจัดเก็บเป็นข้อความ
        add  $t0, $t1, $t2      #ประเภท R: opcode, rs, rt, rd, ฟังก์ชัน
        add  $t3, $t4, $t5      #รูปร่างเดียวกัน รีจิสเตอร์ต่างกัน
        addi $t0, $t1, 100      #I-type: ค่าคงที่อยู่ในคำ
        sll  $t0, $t1, 4        #จำนวนกะมีฟิลด์ของตัวเอง
        j    tail               #J-type: ที่อยู่ ไม่ใช่การลงทะเบียน
tail:
        #li ถูกขยายก่อนดำเนินการ โปรเซสเซอร์จะเห็นเฉพาะคำที่เข้ารหัสเท่านั้น
        li   $v0, 10
        syscall
