# 13 - คำสั่งคือตัวเลข
#
# ประกอบและตรวจสอบคอลัมน์รหัสในส่วนข้อความ คำสั่งพื้นฐานแต่ละคำสั่งเป็นคำขนาด 32
# บิตที่แบ่งออกเป็นช่องต่างๆ
#
# เปรียบเทียบคำสั่ง `add` สองคำสั่ง ฟิลด์การดำเนินการตรงกัน
# ในขณะที่ฟิลด์รีจิสเตอร์เข้ารหัสตัวถูกดำเนินการที่แตกต่างกัน
#
# ใน `addi` บิตที่ต่ำ 16 บิตจะเก็บ 100 ทันที ซึ่งก็คือ `0x0064` เปลี่ยนเป็น 101
# แล้วประกอบใหม่เพื่อดูการเปลี่ยนแปลง

        .text
        .globl main
main:
        #ตรวจสอบคอลัมน์รหัสหลังการประกอบ: ตัวช่วยจำเหล่านี้จะไม่ถูกจัดเก็บเป็นข้อความ
        add  $t0, $t1, $t2      #ประเภท R: opcode, rs, rt, rd, ฟังก์ชัน
        add  $t3, $t4, $t5      #รูปร่างเดียวกัน รีจิสเตอร์ต่างกัน
        addi $t0, $t1, 100      #I-type: ค่าคงที่อยู่ในคำ
        sll  $t0, $t1, 4        #จำนวนกะมีฟิลด์ของตัวเอง
        j    tail               #J-type: ที่อยู่ ไม่ใช่การลงทะเบียน
tail:
        #li ถูกขยายก่อนดำเนินการ โปรเซสเซอร์จะเห็นเฉพาะคำที่เข้ารหัสเท่านั้น
        li   $v0, 10
        syscall
