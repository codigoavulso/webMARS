# 10 - สแต็ค
#
# ตามธรรมเนียมแล้ว สแต็กจะขยายไปสู่ที่อยู่ที่ต่ำกว่า ลบ 8 จาก `$sp`
# เพื่อสงวนที่ว่างไว้สำหรับสองคำ
#
# โปรแกรมจะบันทึกรีจิสเตอร์สองตัวด้วย `sw` ล้างข้อมูลเหล่านั้น จากนั้นกู้คืนค่าด้วย `lw`
#
# รับชม `$sp` ก่อนจอง ระหว่างสองร้าน และหลังวางจำหน่าย ค่าสุดท้ายควรตรงกับค่าเริ่มต้น

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #สแต็กขยายลดลง ดังนั้นการจัดสรรจึงลบออกจาก $sp
        addi $sp, $sp, -8       #จองสองคำ.
        sw   $t0, 0($sp)        #ผลักดัน
        sw   $t1, 4($sp)

        li   $t0, 0             #ขัดขวางการลงทะเบียน
        li   $t1, 0

        lw   $t0, 0($sp)        #ป๊อป
        lw   $t1, 4($sp)
        #การจัดสรรทุกครั้งจะต้องมีความสมดุลเพื่อให้ผู้เรียกเห็นต้นฉบับ $sp
        addi $sp, $sp, 8        #ปล่อย

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
