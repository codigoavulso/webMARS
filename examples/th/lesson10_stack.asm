#
#THE PROBLEM
#มีการลงทะเบียน 32 รายการและแบ่งปันโดยทุกชิ้น
#รหัส คุณค่าจะไปไหนในเมื่อมันต้องรอดจากการทำงานนั้น
#จะนำทะเบียนเหล่านั้นกลับมาใช้ใหม่หรือไม่
#
#WHAT THE HARDWARE DOES
#ไม่มีอะไรพิเศษเลย $sp เป็นการลงทะเบียนธรรมดาที่
#เกิดขึ้นเพื่อชี้ไปที่หน่วยความจำ และสแต็กก็ขยายไปทางนั้น
#ที่อยู่ต่ำกว่าตามแบบแผนล้วนๆ
#
#THE SOLUTION
#การจองพื้นที่จะเป็นการลบออกจาก $sp โดยปล่อยไว้
#นอกจากนี้ Push และ Pop เป็นเพียง sw และ lw
#
#WATCH FOR
#การลงทะเบียนถูกจงใจเคลียร์ระหว่างร้านค้า
#และจำนวนโหลด ดังนั้นค่าที่พิมพ์ออกมาจึงสามารถมาได้เท่านั้น
#กลับจากความทรงจำ ดู $sp ขยับไป 8 และถอยหลัง
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #สแต็กขยายลดลง ดังนั้นการจัดสรรจึงลบออกจาก $sp
        addi $sp, $sp, -8       #จองสองคำ.
        sw   $t0, 0($sp)        #ผลักดัน
        sw   $t1, 4($sp)

        li   $t0, 0             #ขัดขวางการลงทะเบียน
        li   $t1, 0

        lw   $t0, 0($sp)        #ป๊อป
        lw   $t1, 4($sp)
        #การจัดสรรทุกครั้งจะต้องมีความสมดุลเพื่อให้ผู้เรียกเห็นต้นฉบับ $sp
        addi $sp, $sp, 8        #ปล่อย

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
