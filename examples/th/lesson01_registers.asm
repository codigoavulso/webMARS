# 01 - ลงทะเบียนและทันที
#
# ทันทีถูกเข้ารหัสในคำสั่ง ประกอบและตรวจสอบว่าคำสั่งพื้นฐานใดที่แต่ละ `li` กลายเป็น
#
# ก้าวผ่านสองโหลดและการบวก ในรีจิสเตอร์ ให้ติดตาม `$t0 = 12`, `$t1 = 30` และ `$t2 = 42`
#
# ลองแทนที่ 30 ด้วย `0x12345678` แล้วประกอบใหม่
# ค่าคงที่ที่ใหญ่กว่าต้องการคำสั่งพื้นฐานมากกว่าหนึ่งคำสั่ง

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls ใช้ $v0 เป็นตัวเลือกบริการและ $a0 เป็นอาร์กิวเมนต์แรก
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li เป็นคำสั่งหลอก รวบรวมแสดงให้เห็นว่าคำสั่งที่แท้จริงนั้นจะกลายเป็นคำสั่งใด
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # ผลรวมจะถูกเขียนไปยังทะเบียนอื่น

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
