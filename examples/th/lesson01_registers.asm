#บทที่ 01 - การลงทะเบียนและค่าทันที
#
#THE PROBLEM
#ALU มีพอร์ตอินพุตสองพอร์ต และทั้งสองพอร์ตต่อสายเข้ากับ
#ไฟล์ลงทะเบียน ตัวเลขที่เขียนในแหล่งที่มาไม่อยู่ใน a
#register จึงไม่สามารถเข้าถึงพอร์ตเหล่านั้นได้โดยตรง
#
#WHAT THE HARDWARE DOES
#การเดินทางภายในคำคำสั่งนั้นทันที
#addi มีฟิลด์ 16 บิต; li คือความสะดวกสบาย
#แอสเซมเบลอร์ขยายเป็นคำสั่งจริงหนึ่งหรือสองคำสั่ง
#
#THE SOLUTION
#ลงค่าคงที่ในรีจิสเตอร์ก่อน จากนั้นให้ ALU
#อ่านสองรีจิสเตอร์และเขียนหนึ่งในสาม
#
#WATCH FOR
#ขั้นตอนละครั้งต่อบรรทัดและปฏิบัติตาม $t0, $t1 และ $t2 ใน
#แผงการลงทะเบียน เฉพาะบรรทัดที่สามเท่านั้นที่แตะ ALU
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls ใช้ $v0 เป็นตัวเลือกบริการและ $a0 เป็นอาร์กิวเมนต์แรก
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li เป็นคำสั่งหลอก รวบรวมแสดงให้เห็นว่าคำสั่งที่แท้จริงนั้นจะกลายเป็นคำสั่งใด
        li   $t0, 12            #ทันที -> ลงทะเบียน
        li   $t1, 30            #ทันที -> ลงทะเบียน
        add  $t2, $t0, $t1      #ALU อ่านสองรีจิสเตอร์

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
