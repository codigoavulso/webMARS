# 07 - คำพูดในความทรงจำ
#
# ที่อยู่หน่วยความจำนับไบต์ แต่ละคำกินพื้นที่สี่ไบต์ ดังนั้น `lw` และ `sw` ใช้ออฟเซ็ต 0, 4 และ 8
# ที่นี่
#
# ที่อยู่คำต้องเป็นทวีคูณของสี่ การใช้ออฟเซ็ต 1 แทน 4
# ทำให้เกิดข้อยกเว้นการจัดตำแหน่งในโปรแกรมนี้
#
# หลังจากร้านค้า ให้ดูที่ `cell` ในส่วนข้อมูล คำสามคำที่อยู่ติดกันควรมี 111, 222 และ 333

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #ที่อยู่ฐาน

        #ทุกออฟเซ็ตด้านล่างนี้สัมพันธ์กับ $t0 และยังคงการจัดแนวคำ
        li   $t1, 111
        sw   $t1, 0($t0)        #คำแรก
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 ไบต์ = คำถัดไป
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 ไบต์

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw สร้างค่า 32 บิตเดียวกันกับที่เขียนก่อนหน้านี้โดย sw
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
