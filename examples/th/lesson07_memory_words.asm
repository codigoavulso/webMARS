#
#THE PROBLEM
#หน่วยความจำได้รับการแก้ไขทีละไบต์ แต่การลงทะเบียนยังคงอยู่
#สี่ไบต์ ที่อยู่เดียวเลือกอะไรจริงๆ
#
#WHAT THE HARDWARE DOES
#lw และ sw ย้ายสี่ไบต์ในการเข้าถึงครั้งเดียว ดังนั้นต่อเนื่องกัน
#คำที่อยู่แยกจากกันสี่คำ สองบิตต่ำของ
#ที่อยู่ต้องเป็นศูนย์: การจัดตำแหน่งนั้นเป็นสิ่งที่ช่วยให้
#ฮาร์ดแวร์ดึงข้อมูลทั้งคำในรอบเดียว
#
#THE SOLUTION
#เลขคณิตของที่อยู่เสร็จสิ้นในหน่วยไบต์ ดังนั้นดัชนีเป็นคำ
#จะถูกปรับขนาดเป็นสี่เสมอ
#
#WATCH FOR
#ประกอบ จากนั้นเปิด Data Segment ที่ 0x10010000 ที่
#ค่าสามค่าปรากฏในคอลัมน์ที่อยู่ติดกันของหนึ่งแถว
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #ที่อยู่ฐาน

        #ทุกออฟเซ็ตด้านล่างนี้สัมพันธ์กับ $t0 และยังคงการจัดแนวคำ
        li   $t1, 111
        sw   $t1, 0($t0)        #คำแรก
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 ไบต์ = คำถัดไป
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 ไบต์

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw สร้างค่า 32 บิตเดียวกันกับที่เขียนก่อนหน้านี้โดย sw
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
