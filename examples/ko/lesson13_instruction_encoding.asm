# 13 - 명령어는 숫자이다
#
# 텍스트 세그먼트의 코드 열을 조합하고 검사합니다. 각 기본 명령어는 필드로 구분된 32비트 워드입니다.
#
# 두 가지 `add` 명령어를 비교해 보세요. 연산 필드는 일치하지만 레지스터 필드는 다른 피연산자를 인코딩합니다.
#
# `addi`에서 하위 16비트는 즉시 100, 즉 `0x0064`을 보유합니다. 101로 바꾸고 재조립해서 변화를 확인해 보세요.

        .text
        .globl main
main:
        #조립 후 코드 열을 검사하십시오. 이러한 니모닉은 텍스트로 저장되지 않습니다.
        add  $t0, $t1, $t2      #R 유형: opcode, rs, rt, rd, funct
        add  $t3, $t4, $t5      #같은 모양, 다른 레지스터
        addi $t0, $t1, 100      #I형: 상수가 단어에 있음
        sll  $t0, $t1, 4        #이동량에는 자체 필드가 있습니다.
        j    tail               #J-type: 레지스터가 아닌 주소
tail:
        #li 자체는 실행 전에 확장됩니다. 프로세서는 인코딩된 단어만 볼 수 있습니다.
        li   $v0, 10
        syscall
