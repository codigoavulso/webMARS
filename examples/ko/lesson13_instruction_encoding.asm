#데이터 조각?
#
#WHAT THE HARDWARE DOES
#그 이상에는 단어가 로드되는 레지스터가 없습니다. 는
#PC는 디코더로 이동하는 단어를 선택합니다. lw는 단어를 선택합니다
#레지스터 파일로 이동합니다. 비트도 같은 종류입니다.
#
#THE SOLUTION
#인코딩을 직접 읽으십시오. 조립 및 개봉
#Main > Execute: 코드 열에는 각 명령어가 다음과 같이 표시됩니다.
#32비트 단어는 정말 그렇습니다.
#
#WATCH FOR
#이 단원에서는 의도적으로 아무 것도 인쇄하지 않습니다. 출력은 다음과 같습니다.
#텍스트 세그먼트 자체. 두 가지 추가 사항을 비교하십시오. 동일한 opcode와
#기능 필드, 다른 레지스터 번호. 그런 다음
#addi 단어 안에 리터럴 100이 있습니다.
# ==========================================================
        .text
        .globl main
main:
        #조립 후 코드 열을 검사하십시오. 이러한 니모닉은 텍스트로 저장되지 않습니다.
        add  $t0, $t1, $t2      #R 유형: opcode, rs, rt, rd, funct
        add  $t3, $t4, $t5      #같은 모양, 다른 레지스터
        addi $t0, $t1, 100      #I형: 상수가 단어에 있음
        sll  $t0, $t1, 4        #이동량에는 자체 필드가 있습니다.
        j    tail               #J-type: 레지스터가 아닌 주소
tail:
        #li 자체는 실행 전에 확장됩니다. 프로세서는 인코딩된 단어만 볼 수 있습니다.
        li   $v0, 10
        syscall
