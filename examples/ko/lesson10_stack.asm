# ==========================================================
#레슨 10 - 스택은 레지스터이자 오프셋입니다
#
#THE PROBLEM
#32개의 레지스터가 있으며 모든 장치에서 공유됩니다.
#코드. 가치는 그 일에서 살아남아야 할 때 어디로 가나요?
#그 레지스터를 재사용할 것인가?
#
#WHAT THE HARDWARE DOES
#전혀 특별한 것이 없습니다. $sp는 다음과 같은 일반 레지스터입니다.
#우연히 메모리를 가리키고 스택은 다음 방향으로 커집니다.
#순전히 관례에 따라 주소를 낮추십시오.
#
#THE SOLUTION
#공간 예약은 $sp에서 빼는 것입니다.
#추가. 푸시와 팝은 sw와 lw에 불과합니다.
#
#WATCH FOR
#매장 간 등록부를 고의로 삭제합니다.
#그리고 하중이 있으므로 인쇄된 값만 올 수 있습니다.
#기억에서 돌아왔습니다. $sp가 8만큼 뒤로 움직이는 것을 지켜보세요.
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #스택이 아래쪽으로 커지므로 $sp에서 할당이 뺍니다.
        addi $sp, $sp, -8       #두 단어 예약
        sw   $t0, 0($sp)        #푸시
        sw   $t1, 4($sp)

        li   $t0, 0             #레지스터를 두들겨 패다
        li   $t1, 0

        lw   $t0, 0($sp)        #팝
        lw   $t1, 4($sp)
        #호출자가 원본 $sp을 볼 수 있도록 모든 할당은 균형을 이루어야 합니다.
        addi $sp, $sp, 8        #릴리스

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
