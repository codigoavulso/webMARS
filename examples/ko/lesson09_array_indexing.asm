#THE PROBLEM
#로드 명령어는 기본 레지스터와 상수를 제공합니다.
#오프셋. 다른 것은 없습니다. 그러면 i만 있을 때 a[i]에 어떻게 도달하나요?
#런타임에 알려지고 레지스터에 앉아 있습니까?
#
#WHAT THE HARDWARE DOES
#레지스터가 보유하는 모든 것에 기본을 추가합니다. 인덱스
#따라서 이미 요소가 아닌 바이트 단위여야 합니다.
#
#THE SOLUTION
#요소 크기에 따라 인덱스의 크기를 조정한 다음 추가합니다. 4바이트의 경우
#스케일링은 왼쪽으로 2만큼 이동하는 것이며 비용이 많이 듭니다.
#아무것도.
#
#WATCH FOR
#sll, add, lw 세 줄은 a[i]가 컴파일하는 내용입니다.
#한 번의 반복을 진행하고 $t5 및 $t6를 읽습니다.
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #베이스
        li   $t1, 0             #나
        li   $t2, 5             #길이
        li   $t3, 0             #누산기

sum:
        #루프 불변: $t3는 arr[0]부터 arr[i-1]까지의 합계입니다.
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #나는 * 4바이트
        add  $t6, $t0, $t5      #기본 + 스케일 인덱스
        #$t6 이제 정확히 하나의 요소 이름이 지정됩니다. lw는 32비트 값을 가져옵니다.
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
