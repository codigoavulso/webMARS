#
#THE PROBLEM
#하드웨어 카운터는 레지스터, 증분기 및
#비교기. 같은 기계가 쓰여진 것처럼 보이나요?
#지시대로?
#
#WHAT THE HARDWARE DOES
#정확히 세 부분(명령당 하나씩): 레지스터
#카운트를 보유하고 addi는 증분자이며 slt는 분기입니다.
#다른 라운드를 결정하는 비교기입니다.
#
#THE SOLUTION
#루프는 새로운 개념이 아닙니다. 순차 논리로 표기됩니다.
#밖으로, PC를 시계로 사용합니다.
#
#WATCH FOR
#$t0는 카운트 레지스터이고 $t1는 한계입니다. 단계별로
#하나의 완전한 라운드와 어느 라인이 어느 부분인지 이름을 지정합니다.
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #카운트 레지스터
        li   $t1, 11            #한계

loop:
        #루프 불변: $t0는 인쇄할 다음 값이며 $t1 아래에 유지됩니다.
        slt  $t2, $t0, $t1      #비교기
        beq  $t2, $zero, endl   #개수가 한계에 도달하면 종료

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #점프하기 전에 카운터를 업데이트하면 종료를 향한 진행이 보장됩니다.
        addi $t0, $t0, 1        #가산기
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
