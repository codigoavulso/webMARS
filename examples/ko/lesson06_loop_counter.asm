# 06 - 카운터로서의 루프
#
# `$t0`는 인쇄할 다음 숫자입니다. `$t1`은 배타적 상한이므로 11개로 제한되면 1부터 10까지 인쇄됩니다.
#
# 비교는 각 반복 전에 실행됩니다. 증분은 한계를 향해 진행되고 점프는 확인을 반복합니다.
#
# 제한을 1로 변경하고 실행하십시오. 종료 분기는 첫 번째 인쇄 전에 수행됩니다.

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #카운트 레지스터
        li   $t1, 11            #한계

loop:
        # 루프 테스트에서는 $t0가 다음 후보입니다. $t1 이하인 경우에만 인쇄하세요.
        slt  $t2, $t0, $t1      #비교기
        beq  $t2, $zero, endl   #개수가 한계에 도달하면 종료

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #점프하기 전에 카운터를 업데이트하면 종료를 향한 진행이 보장됩니다.
        addi $t0, $t0, 1        #가산기
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
