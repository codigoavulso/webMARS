# ==========================================================
#Lesson 07 - 기억에 남는 단어와 주소가 4씩 점프하는 이유
#
#THE PROBLEM
#메모리는 한 번에 한 바이트씩 주소가 지정되지만 레지스터는
#4바이트. 단일 주소는 실제로 무엇을 선택합니까?
#
#WHAT THE HARDWARE DOES
#lw 및 sw는 한 번의 액세스로 4바이트를 이동하므로 연속적입니다.
#단어는 네 개의 주소로 떨어져 있습니다. 하위 2비트는
#주소는 0이어야 합니다. 해당 정렬을 통해
#하드웨어는 한 주기에 전체 단어를 가져옵니다.
#
#THE SOLUTION
#주소 산술은 바이트 단위로 수행되므로 단어 인덱스
#항상 4씩 크기가 조정됩니다.
#
#WATCH FOR
#조립한 다음 0x10010000에서 데이터 세그먼트를 엽니다. 는
#한 행의 인접한 열에 세 개의 값이 나타납니다.
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #기본 주소

        #아래의 모든 오프셋은 $t0를 기준으로 하며 단어 정렬 상태를 유지합니다.
        li   $t1, 111
        sw   $t1, 0($t0)        #첫 번째 단어
        li   $t1, 222
        sw   $t1, 4($t0)        #+4바이트 = 다음 단어
        li   $t1, 333
        sw   $t1, 8($t0)        #+8바이트

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw는 이전에 sw가 작성한 동일한 32비트 값을 재구성합니다.
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
