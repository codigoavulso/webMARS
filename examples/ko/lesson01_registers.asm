# 01 - 레지스터 및 즉시 항목
#
# 즉시 항목은 명령어에 인코딩됩니다. 각각의 `li`이 어떤 기본 명령어가 되는지 조립하고 확인합니다.
#
# 두 개의 로드와 추가를 단계별로 진행합니다. 레지스터에서 `$t0 = 12`, `$t1 = 30` 및 `$t2 = 42`를 따릅니다.
#
# 30을 `0x12345678`로 바꾸고 다시 조립해 보세요. 더 큰 상수에는 하나 이상의 기본 명령어가 필요합니다.

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscall은 $v0를 서비스 선택기로 사용하고 $a0를 첫 번째 인수로 사용합니다.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li는 의사 명령어입니다. Assemble은 그것이 어떤 실제 명령이 되는지 보여줍니다.
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # 합계는 다른 레지스터에 기록됩니다.

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
