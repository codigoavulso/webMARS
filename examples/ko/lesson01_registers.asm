#Lesson 01 - 레지스터와 즉치값
#
#THE PROBLEM
#ALU에는 두 개의 입력 포트가 있으며 둘 다
#등록 파일. 소스에 적힌 숫자가
#등록해야 해당 포트에 직접 연결할 수 없습니다.
#
#WHAT THE HARDWARE DOES
#Immediate는 명령어 자체 내부로 이동합니다.
#addi는 16비트 필드를 전달합니다. li는 편의상
#어셈블러는 하나 또는 두 개의 실제 명령어로 확장됩니다.
#
#THE SOLUTION
#먼저 레지스터에 상수를 넣은 다음 ALU
#두 개의 레지스터를 읽고 세 번째 레지스터를 씁니다.
#
#WATCH FOR
#   한 줄에 한 번씩 스텝을 밟고 따라가세요 $t0, $t1 그리고 $t2 에서
#레지스터 패널. 세 번째 줄만 ALU에 닿습니다.
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscall은 $v0를 서비스 선택기로 사용하고 $a0를 첫 번째 인수로 사용합니다.
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li는 의사 명령어입니다. Assemble은 그것이 어떤 실제 명령이 되는지 보여줍니다.
        li   $t0, 12            #즉시 -> 등록
        li   $t1, 30            #즉시 -> 등록
        add  $t2, $t0, $t1      #ALU 두 개의 레지스터를 읽습니다.

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
