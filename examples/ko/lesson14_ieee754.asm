# ==========================================================
#레슨 14 - 32비트의 실수
#
#THE PROBLEM
#3.5는 정수 레지스터에 위치하지 않습니다. 어디에서
#분수 부분은 이동하고 매우 큰 숫자는 어떻게 저장됩니까?
#아주 작은 것과 동일한 32비트에?
#
#WHAT THE HARDWARE DOES
#IEEE-754는 단어를 세 개의 필드, 즉 하나의 부호 비트,
#8개의 지수 비트와 23개의 분수 비트입니다. 는
#지수는 이진수를 슬라이드하므로 형식이 다음과 같습니다.
#부동소수점이라고 합니다.
#
#THE SOLUTION
#별도의 레지스터 파일($f0..$f31) 및 별도의 가산기
#이러한 값을 처리하므로 니모닉이 다릅니다.
#로드하려면 lwc1, 추가하려면 add.s, 인쇄하려면 syscall 2를 사용하세요.
#
#WATCH FOR
#도구 > 부동 소수점 표현을 열고 3.5를 입력합니다.
#세 필드를 관찰한 다음 4.75가 정확한지 확인하세요.
#유한한 이진 분수가 없는 0.1과 다릅니다.
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #정수 주소는 여전히 데이터를 찾습니다. lwc1은 해당 비트를 COP1로 이동합니다.
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU 레지스터 파일에
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU 가산기

        #Syscall 2는 특히 $f12에서 float 인수를 기대합니다.
        mov.s $f12, $f4
        li   $v0, 2             #플로트 인쇄
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
