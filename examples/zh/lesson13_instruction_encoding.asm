# 13 - 指令是一个数字
#
# 组装并检查文本段中的代码列。每个基本指令都是一个分为多个字段的 32 位字。
#
# 比较两条`add`指令。操作字段匹配，而寄存器字段对不同的操作数进行编码。
#
# 在`addi`中，低16位保存的是立即数100，即`0x0064`。将其更改为 101 并重新组装以查看更改。

        .text
        .globl main
main:
        #组装后检查代码栏：这些助记符不是以文本形式存储的。
        add  $t0, $t1, $t2      #R 类型：操作码、rs、rt、rd、funct
        add  $t3, $t4, $t5      #相同的形状，不同的寄存器
        addi $t0, $t1, 100      #I型：常数在字中
        sll  $t0, $t1, 4        #移位量有自己的字段
        j    tail               #J型：地址，不是寄存器
tail:
        #li 本身在执行前展开；处理器只能看到编码的字。
        li   $v0, 10
        syscall
