# ==========================================================
#第 13 课 - 指令是一个数字
#
#THE PROBLEM
#处理器从内存中获取单词。代码位于
#记忆也。那么指令和指令的区别是什么
#一条数据？
#
#WHAT THE HARDWARE DOES
#没有任何内容，超出该单词将被加载到的寄存器中。的
#PC选择进入解码器的单词； lw选择单词
#进入寄存器文件。这些位是同一类型的。
#
#THE SOLUTION
#直接读取编码。组装并打开
#Main > Execute：代码列将每条指令显示为
#真正的 32 位字。
#
#WATCH FOR
#本课故意不打印任何内容 - 输出是
#文本段本身。比较两个添加：相同的操作码和
#功能字段，不同的寄存器号。然后找到
#addi 单词内的字面值 100。
# ==========================================================
        .text
        .globl main
main:
        #组装后检查代码栏：这些助记符不是以文本形式存储的。
        add  $t0, $t1, $t2      #R 类型：操作码、rs、rt、rd、funct
        add  $t3, $t4, $t5      #相同的形状，不同的寄存器
        addi $t0, $t1, 100      #I型：常数在字中
        sll  $t0, $t1, 4        #移位量有自己的字段
        j    tail               #J型：地址，不是寄存器
tail:
        #li 本身在执行前展开；处理器只能看到编码的字。
        li   $v0, 10
        syscall
