#
#THE PROBLEM
#硬件计数器由寄存器、增量器和
#比较器。同样的机器写起来是什么样的
#作为说明？
#
#WHAT THE HARDWARE DOES
#正是这三个部分，每条指令一个：寄存器
#保存计数，addi 是增量器，slt 带分支
#是决定另一轮的比较器。
#
#THE SOLUTION
#循环并不是一个新概念。它是顺序逻辑的拼写
#出，以PC作为时钟。
#
#WATCH FOR
#$t0 是计数寄存器，$t1 是限制。单步执行
#一整轮并说出哪一行是哪一部分。
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #计数寄存器
        li   $t1, 11            #极限

loop:
        #循环不变式：$t0 是下一个要打印的值，并保持在 $t1 以下。
        slt  $t2, $t0, $t1      #比较器
        beq  $t2, $zero, endl   #当计数达到限制时退出

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #在跳转之前更新计数器可以保证终止的进展。
        addi $t0, $t0, 1        #加法器
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
