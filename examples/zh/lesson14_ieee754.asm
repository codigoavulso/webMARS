# ==========================================================
#第 14 课 - 32 位实数
#
#THE PROBLEM
#3.5 在整数寄存器中没有位置。哪里有
#小数部分以及如何存储非常大的数字
#与非常小的 32 位相同？
#
#WHAT THE HARDWARE DOES
#IEEE-754 将字分为三个字段：一个符号位，
#八个指数位和二十三个小数位。的
#指数滑动二进制小数点，这就是格式为
#称为浮点数。
#
#THE SOLUTION
#一个单独的寄存器文件 ($f0..$f31) 和一个单独的加法器
#处理这些值，这就是助记符不同的原因：
#lwc1 用于加载，add.s 用于添加，syscall 2 用于打印。
#
#WATCH FOR
#打开工具 > 浮点表示法并输入 3.5。
#观察三个字段，然后检查 4.75 是否准确 -
#与 0.1 不同，0.1 没有有限的二进制分数。
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #整数地址仍然可以定位数据； lwc1 将其位移入 COP1。
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #进入 FPU 寄存器文件
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU 加法器

        #系统调用 2 期望其 float 参数特别位于 $f12 中。
        mov.s $f12, $f4
        li   $v0, 2             #打印浮动
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
