# ==========================================================
#第 01 课 - 寄存器和立即值
#
#THE PROBLEM
#ALU 有两个输入端口，并且都连接到
#注册文件。源中写入的数字不在
#注册，因此它无法直接到达这些端口。
#
#WHAT THE HARDWARE DOES
#立即数在指令字本身内部传播。
#addi携带16位字段； li是一个方便
#汇编程序扩展为一两个实际指令。
#
#THE SOLUTION
#首先将常量放入寄存器，然后让 ALU
#读取两个寄存器并写入第三个。
#
#WATCH FOR
#每行执行一次，并按照 $t0、$t1 和 $t2 进行操作
#寄存器面板。只有第三行触及 ALU。
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #系统调用使用 $v0 作为服务选择器，并使用 $a0 作为第一个参数。
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li 是伪指令；汇编显示了它变成了哪条真正的指令。
        li   $t0, 12            #立即 -> 注册
        li   $t1, 30            #立即 -> 注册
        add  $t2, $t0, $t1      #ALU 读取两个寄存器

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
