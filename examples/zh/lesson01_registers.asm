# 01 - 寄存器和立即数
#
# 立即数被编码在指令中。组装并检查每个 `li` 成为哪条基本指令。
#
# 单步执行两个负载和相加。在寄存器中，遵循`$t0 = 12`、`$t1 = 30`和`$t2 = 42`。
#
# 尝试用 `0x12345678` 替换 30 并重新组装。较大的常数需要多个基本指令。

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #系统调用使用 $v0 作为服务选择器，并使用 $a0 作为第一个参数。
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li 是伪指令；汇编显示了它变成了哪条真正的指令。
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # 总和被写入不同的寄存器。

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
