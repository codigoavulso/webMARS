# ==========================================================
#レッスン 01 - レジスタと即値
#
#THE PROBLEM
#ALU には 2 つの入力ポートがあり、両方とも
#レジスタファイル。ソースに書かれている数字は、
#登録されているため、これらのポートに直接到達することはできません。
#
#WHAT THE HARDWARE DOES
#イミディエートは命令語自体の内部を移動します。
#addi は 16 ビットのフィールドを運びます。 liは便利です
#アセンブラは 1 つまたは 2 つの実際の命令に展開されます。
#
#THE SOLUTION
#まず定数をレジスタに配置し、次に ALU を実行させます。
#2 つのレジスタを読み取り、3 番目のレジスタに書き込みます。
#
#WATCH FOR
#1 行に 1 回ステップを実行し、$t0、$t1、および $t2 に従います。
#レジスタパネル。 3 行目のみが ALU に触れています。
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #システムコールは、サービス セレクターとして $v0 を使用し、最初の引数として $a0 を使用します。
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li は疑似命令です。アセンブルは、どの実際の命令になるかを示します。
        li   $t0, 12            #即時→登録
        li   $t1, 30            #即時→登録
        add  $t2, $t0, $t1      #ALU は 2 つのレジスタを読み取ります

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
