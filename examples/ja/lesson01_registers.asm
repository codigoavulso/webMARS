# 01 - レジスタとイミディエイト
#
# イミディエイトは命令内でエンコードされます。それぞれの`li`がどの基本命令になるかをアセンブルして確認します。
#
# 2 つのロードと加算をステップ実行します。 [レジスタ] では、`$t0 = 12`、`$t1 = 30`、`$t2 = 42` に従います。
#
# 30を`0x12345678`に置き換えて再組み立てしてみてください。より大きな定数には複数の基本命令が必要です。

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #システムコールは、サービス セレクターとして $v0 を使用し、最初の引数として $a0 を使用します。
        la   $a0, lbl
        li   $v0, 4
        syscall

        #li は疑似命令です。アセンブルは、どの実際の命令になるかを示します。
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # 合計は別のレジスタに書き込まれます。

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
