# ==========================================================
#レッスン 11 - 関数の呼び出し
#
#THE PROBLEM
#ルーチンに飛び込むのは簡単です。戻ることはそうではありません、なぜなら
#同じルーチンが多くの場所から呼び出される可能性があり、
#返送先住所は毎回異なります。
#
#WHAT THE HARDWARE DOES
#jal は 1 つの命令で 2 つのことを行います。
#$ra 内の次の命令のアドレスを指定してジャンプします。ジュニア
#レジスタが保持しているものにジャンプするため、 jr $ra が返されます。
#
#THE SOLUTION
#それ以外はすべて合意であり、回路ではありません: の引数
#$a0..$a3、結果は $v0 となります。慣例や規範を打ち破る
#アセンブリはまだ行われますが、相互運用が停止するだけです。
#
#WATCH FOR
#jal に乗り込んで $ra を読んでください。住所と照らし合わせてみる
#テキストセグメントの呼び出し後の行の。
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #最初の引数
        li   $a1, 42            #2 番目の引数
        #jal は、1 つのアーキテクチャ操作で制御フローと $ra の両方を変更します。
        jal  maxof              #$ra = 次の行のアドレス

        move $a0, $v0           #結果が $v0 で返されました
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #maxof はリーフ関数であるため、$ra をスタックに保存せずに返すことができます。
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
