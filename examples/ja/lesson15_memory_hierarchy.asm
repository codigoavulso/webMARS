# ==========================================================
#レッスン 15 – ストライドによって速度が変わる理由
#
#THE PROBLEM
#以下の 2 つのループは同じ配列を読み取り、同じことを実行します。
#ロード数。実際のマシンでははるかに遅くなります。の
#命令数では説明できません。
#
#WHAT THE HARDWARE DOES
#記憶は単一の単語を伝えることはできません。ミスすると丸ごとフェッチされる
#隣接する単語がすぐに求められることに賭けてブロックします。
#1 の歩幅でその賭け金が回収されます。 16 歩の歩幅で支払う
#ブロックを対象として、そのブロックの 1 ワードを読み取ります。
#
#THE SOLUTION
#コードは何も変更されません。地域性は、
#アクセス パターンであり、修正する必要があるのはこのパターンです。
#
#WATCH FOR
#[ツール] > [データ キャッシュ シミュレーター] を開き、MIPS に接続を押します。
#それから走ります。 2 つのループのヒット率を比較します。両方の合計
#配列がゼロ化されているため、0 を出力します。数値は実際の数値ではありません。
#ここでの命中率がポイントです。
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- 各ブロックのすべての単語 ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #シーケンシャル インデックスは、次に進む前に各キャッシュ ブロックのワードを再利用します。
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- ブロックごとに 1 ワード、16 ワード間隔 ----
        li   $t1, 0
        li   $t3, 0
far:
        #16 を追加すると、反復ごとに 64 バイトがスキップされます。通常は 1 つのキャッシュ ブロック全体です。
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
