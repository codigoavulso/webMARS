# ==========================================================
#レッスン 04 - シフト、またはワイヤーによる乗算
#
#THE PROBLEM
#一般的な乗算器は、最も高価なブロックの 1 つです。
#データパス。 8倍してもそれほどコストはかかりません。
#
#WHAT THE HARDWARE DOES
#シフトはまったく算術的ではありません。読み取られるビットは同じです。
#異なるワイヤーから。 n だけ左にシフトすると 2^n 倍になります
#費用はルーティングのみです。
#
#THE SOLUTION
#2 の累乗がシフトになります。 2 つの右シフトに注意してください: srl
#先頭にゼロを入力し、sra は符号ビットをコピーするため、
#sra は負の数を正しく除算します。
#
#WATCH FOR
#-16 >> 2 は sra では -4 ですが、srl では大きなプラスになります。の
#ビットは同じように移動しました。一番上に入力されたものだけが異なります。
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #3 回の左シフトは 2^3 を乗算し、結果の 32 ビットのみを保持します。
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #$t3 と $t4 を 16 進数で比較して、異なる受信ビットを確認します。
        sra  $t3, $t2, 2        #符号の保持: -4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #ゼロがシフトイン: 大きなプラス
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
