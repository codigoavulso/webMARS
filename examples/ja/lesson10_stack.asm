# ==========================================================
#レッスン 10 - スタックはレジスタとオフセットです
#
#THE PROBLEM
#レジスタは 32 個あり、すべての部分で共有されます。
#コード。価値が仕事を生き延びなければならないとき、価値はどこに行くのでしょうか？
#それらのレジスタを再利用しますか?
#
#WHAT THE HARDWARE DOES
#特別なことは何もありません。 $sp は通常のレジスタです。
#たまたまメモリを指しており、スタックは次の方向に成長します。
#純粋に慣例により、下位アドレス。
#
#THE SOLUTION
#スペースの予約は $sp から減算され、解放されます。
#追加。 Pushとpopはswとlwだけです。
#
#WATCH FOR
#レジは店舗間で意図的にクリアされます
#と負荷なので、印刷された値は単に来ている可能性があります
#記憶から戻ってきました。 $sp が 8 ずつ移動して戻るのを見てください。
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #スタックは下方向に成長するため、割り当ては $sp から減算されます。
        addi $sp, $sp, -8       #2つの単語を保留します
        sw   $t0, 0($sp)        #押す
        sw   $t1, 4($sp)

        li   $t0, 0             #レジスターを破壊する
        li   $t1, 0

        lw   $t0, 0($sp)        #ポップ
        lw   $t1, 4($sp)
        #呼び出し元が元の $sp を参照できるように、すべての割り当てのバランスを取る必要があります。
        addi $sp, $sp, 8        #リリース

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
