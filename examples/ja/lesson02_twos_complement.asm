# ==========================================================
#レッスン 02 - 2 の補数
#
#THE PROBLEM
#レジスタは 32 本のワイヤで構成され、それぞれが High または Low です。ワイヤーがありません
#マイナス記号の場合は、負の数値も機能する必要があります。
#
#WHAT THE HARDWARE DOES
#最上位ビットを符号として読み取りますが、別個のフラグとしては読み取りません。
#-n は、n に加算されてラップされるビット パターンとして保存されます。
#ゼロ。すべてのビットを反転して 1 つ追加すると、それが完成します。
#
#THE SOLUTION
#減算には 2 番目の回路は必要ありません。 a - b になります
#a + (-b) なので、1 つの加算器が両方の演算を実行します。
#
#WATCH FOR
#両方の半分に -5 が出力されます。 2番目は遠くまで到達し、
#Nor と addi を使用して、sub が内部で何を行うかを示します。
#0xFFFFFFFB を表示するには、値を 16 進数に設定します。
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #ゼロから減算すると、マイナス符号ビットなしの加算逆元が形成されます。
        li   $t0, 5
        sub  $t1, $zero, $t0    #加算器が仕事をする
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #また、 $zero はビット単位の NOT です。 1 を追加すると 2 の補数が完成します。
        nor  $t2, $t0, $zero    #すべてのビットを反転する
        addi $t2, $t2, 1        #1つ追加します
        move $a0, $t2           #上記と同じ値
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
