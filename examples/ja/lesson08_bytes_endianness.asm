# ==========================================================
#レッスン 08 - ワード内のバイトとバイトオーダー
#
#THE PROBLEM
#1 つのワードは 4 つのアドレスを占有します。どのバイトが最も低いのか
#それらのアドレスの名前は何ですか？
#
#WHAT THE HARDWARE DOES
#その選択はバイトオーダーであり、配線の決定です。
#マシン全体に対して 1 回。 MIPS ここにリトルエンディアンがあります:
#最下位バイトは最下位アドレスに存在します。
#
#THE SOLUTION
#1 つの単語を保存し、一度に 1 バイトずつ読み戻して、
#注文はあなたの質問に答えます。
#
#WATCH FOR
#0x04030201 は 1 2 3 4 として返されます。最後に書き込まれたバイト
#リテラルが最初に読み取られます。 lb ではなく lbu が使用されるため、
#127 より上のバイトは符号拡張されません。
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #バイト 01 が最下位です
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #バイトオフセット
bloop:
        #ループは、保存されたワード内のオフセット 0、1、2、および 3 を訪問します。
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #実効アドレス = ベース アドレス + 現在のバイト オフセット。
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #符号なしバイト
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
