# ==========================================================
#レッスン 14 - 32 ビットの実数
#
#THE PROBLEM
#3.5 は整数レジスタには入りません。どこにありますか
#小数部分は処理されますが、非常に大きな数値はどのように保存されるのでしょうか。
#非常に小さいビットと同じ 32 ビットでしょうか?
#
#WHAT THE HARDWARE DOES
#IEEE-754 はワードを 3 つのフィールドに分割します: 1 つの符号ビット、
#8 つの指数ビットと 23 の小数ビット。の
#指数は 2 進小数点をスライドさせます。そのため、形式は次のようになります。
#浮動小数点と呼ばれます。
#
#THE SOLUTION
#別個のレジスタ ファイル ($f0..$f31) および別個の加算器
#これらの値を処理するため、ニーモニックが異なります。
#lwc1 でロード、add.s で追加、syscall 2 で出力します。
#
#WATCH FOR
#[ツール] > [浮動小数点表現] を開き、「3.5」と入力します。
#3 つのフィールドを観察し、4.75 が正確であることを確認します -
#有限の 2 進小数を持たない 0.1 とは異なります。
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #整数アドレスは引き続きデータを見つけます。 lwc1 はそのビットを COP1 に移動します。
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU レジスタ ファイルに書き込む
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU 加算器

        #Syscall 2 は、特に $f12 にある float 引数を期待します。
        mov.s $f12, $f4
        li   $v0, 2             #プリントフロート
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
