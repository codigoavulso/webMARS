# 13 - 命令は数字です
#
# テキストセグメントのコード列を組み立てて検査します。各基本命令は、フィールドに分割された 32 ビット ワードです。
#
# 2 つの `add` 命令を比較してください。演算フィールドは一致しますが、レジスタ フィールドは異なるオペランドをエンコードします。
#
# `addi` では、下位 16 ビットは即値 100、つまり `0x0064` を保持します。これを 101 に変更し、再組み立てして変更を確認します。

        .text
        .globl main
main:
        #アセンブリ後にコード列を調べます。これらのニーモニックはテキストとして保存されません。
        add  $t0, $t1, $t2      #R タイプ: オペコード、rs、rt、rd、funct
        add  $t3, $t4, $t5      #同じ形状、異なる音域
        addi $t0, $t1, 100      #I タイプ: 定数が単語内にあります
        sll  $t0, $t1, 4        #シフト量には独自のフィールドがあります
        j    tail               #J タイプ: レジスタではなくアドレス
tail:
        #li 自体は実行前に展開されます。プロセッサはエンコードされた単語のみを認識します。
        li   $v0, 10
        syscall
