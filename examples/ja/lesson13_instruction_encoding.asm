# ==========================================================
#レッスン 13 - 命令は数字です
#
#THE PROBLEM
#プロセッサはメモリから単語をフェッチします。コードが存在する
#思い出も。では、命令と命令の違いは何でしょうか。
#データの一部？
#
#WHAT THE HARDWARE DOES
#何もありません。レジスタを超えてワードがロードされます。の
#PC はデコーダに送られる単語を選択します。 lwは単語を選択します
#それはレジスタファイルに移動します。ビットも同じ種類です。
#
#THE SOLUTION
#エンコーディングを直接読み取ります。組み立てて開ける
#Main > Execute: コード列には各命令が次のように表示されます。
#それは実際の 32 ビット ワードです。
#
#WATCH FOR
#このレッスンでは意図的に何も出力しません。出力は
#テキストセグメント自体。 2 つの追加を比較します: 同じオペコードと
#機能フィールド、異なるレジスタ番号。次に、
#addi ワード内のリテラル 100。
# ==========================================================
        .text
        .globl main
main:
        #アセンブリ後にコード列を調べます。これらのニーモニックはテキストとして保存されません。
        add  $t0, $t1, $t2      #R タイプ: オペコード、rs、rt、rd、funct
        add  $t3, $t4, $t5      #同じ形状、異なる音域
        addi $t0, $t1, 100      #I タイプ: 定数が単語内にあります
        sll  $t0, $t1, 4        #シフト量には独自のフィールドがあります
        j    tail               #J タイプ: レジスタではなくアドレス
tail:
        #li 自体は実行前に展開されます。プロセッサはエンコードされた単語のみを認識します。
        li   $v0, 10
        syscall
