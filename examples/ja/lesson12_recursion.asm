# ==========================================================
#レッスン 12 - 再帰には呼び出しごとにフレームが必要です
#
#THE PROBLEM
#再帰呼び出しにより、$ra と引数レジスタが上書きされます。
#外側の呼び出しには戻る方法がなく、その呼び出しが何であるかわかりません。
#自分自身のnでした。
#
#WHAT THE HARDWARE DOES
#スタックではなく、1 つの $ra を提供します。何も保存されない
#自動的に;コードがそれを保存しない場合、それは失われます。
#
#THE SOLUTION
#アクティベーションごとにスタック上のフレームが開き、そのフレームが保持されます。
#通話後も必要になり、途中で復元されます
#アウト。スタックの深さは再帰の深さです。
#
#WATCH FOR
#mul にブレークポイントを設定し、$sp が 8 ずつ下降するのを監視します。
#レベル。 n の保存された 5 つのコピーにより、
#帰りの乗算も可能。
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int fat(int n) ----
fact:
        #各呼び出しは、個別の 8 バイトのフレームを所有します。
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #この通話の返信先アドレス
        sw   $a0, 4($sp)        #この電話はnです

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #基本ケース: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (n-1)!
        lw   $a0, 4($sp)        #私たちのもう一度
        mul  $v0, $v0, $a0

factend:
        #呼び出し先の状態を復元し、開始時に割り当てられたフレームを正確に破棄します。
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
