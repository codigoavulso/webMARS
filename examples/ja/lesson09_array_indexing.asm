# ==========================================================
#レッスン 09 - 配列のインデックス付け
#
#THE PROBLEM
#ロード命令はベースレジスタと定数を提供します。
#オフセット。他には何もありません。それでは、i が だけの場合、どのようにして a[i] に到達するのでしょうか?
#実行時に認識され、レジスターに座っていますか?
#
#WHAT THE HARDWARE DOES
#レジスタが保持するものに基数を追加します。インデックス
#したがって、要素ではなく、すでにバイト単位になっている必要があります。
#
#THE SOLUTION
#要素のサイズに応じてインデックスをスケールし、追加します。 4バイトの場合
#スケーリングは 2 だけ左にシフトするものであり、コストがかかるという言葉
#何もない。
#
#WATCH FOR
#3 行 sll、add、lw は、a[i] のコンパイル結果です。
#1 回の反復を実行して、$t5 と $t6 を読み取ります。
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #ベース
        li   $t1, 0             #私は
        li   $t2, 5             #長さ
        li   $t3, 0             #アキュムレータ

sum:
        #ループ不変式: $t3 は arr[0] から arr[i-1] までの合計です。
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #i * 4バイト
        add  $t6, $t0, $t5      #ベース + スケーリングされたインデックス
        #$t6 は 1 つの要素にのみ名前を付けるようになりました。 lw は 32 ビット値を取得します。
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
