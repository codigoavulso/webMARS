# 06 - カウンターとしてループする
#
# `$t0` は次に印刷する数字です。 `$t1` は排他的な上限であるため、11 個の制限は 1 から 10 までを印刷します。
#
# 比較は各反復の前に実行されます。インクリメントは限界に向かって進み、ジャンプはチェックを繰り返します。
#
# 制限を 1 に変更して実行します。最初の出力の前に終了分岐が行われます。

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #カウントレジスタ
        li   $t1, 11            #限界

loop:
        # ループテストでは$t0が次の候補です。 $t1 以下の場合のみ印刷します。
        slt  $t2, $t0, $t1      #コンパレータ
        beq  $t2, $zero, endl   #カウントが制限に達すると終了します

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #ジャンプする前にカウンターを更新すると、終了に向けた進行が保証されます。
        addi $t0, $t0, 1        #加算器
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
