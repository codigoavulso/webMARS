# ==========================================================
#レッスン 06 - ソフトウェアとハードウェアのカウンター
#
#THE PROBLEM
#ハードウェア カウンタは、レジスタ、インクリメンタ、および
#コンパレータ。同じマシンがどのように書かれているか
#指示として?
#
#WHAT THE HARDWARE DOES
#まさにこれら 3 つの部分 (命令ごとに 1 つ): レジスタ
#カウントを保持します、addi はインクリメンタ、slt は分岐を持ちます
#別のラウンドを決定するコンパレータです。
#
#THE SOLUTION
#ループは新しい概念ではありません。シーケンシャルロジックを綴ったものです
#PC を時計として使用します。
#
#WATCH FOR
#$t0 はカウント レジスタ、$t1 は制限値です。ステップスルー
#1 つのラウンドと、どの行がどの部分であるかを指定します。
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #カウントレジスタ
        li   $t1, 11            #限界

loop:
        #ループ不変条件: $t0 は次に出力する値であり、$t1 より下に残ります。
        slt  $t2, $t0, $t1      #コンパレータ
        beq  $t2, $zero, endl   #カウントが制限に達すると終了します

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #ジャンプする前にカウンターを更新すると、終了に向けた進行が保証されます。
        addi $t0, $t0, 1        #加算器
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
