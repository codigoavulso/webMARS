# ==========================================================
#レッスン 07 - メモリ内の単語と、アドレスが 4 つずつ変化する理由
#
#THE PROBLEM
#メモリは一度に 1 バイトずつアドレス指定されますが、レジスタは
#4バイト。単一のアドレスは実際に何を選択するのでしょうか?
#
#WHAT THE HARDWARE DOES
#lw と sw は 1 回のアクセスで 4 バイト移動するため、連続して
#単語は 4 つのアドレス離れて配置されます。の下位 2 ビット
#アドレスはゼロである必要があります。その位置合わせにより、
#ハードウェアは 1 サイクルでワード全体をフェッチします。
#
#THE SOLUTION
#アドレス演算はバイト単位で行われるため、単語へのインデックスが作成されます。
#常に 4 倍にスケールされます。
#
#WATCH FOR
#アセンブルしてから、0x10010000 でデータ セグメントを開きます。の
#1 つの行の隣接する列に 3 つの値が表示されます。
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #ベースアドレス

        #以下のすべてのオフセットは $t0 に相対しており、ワード位置に揃えられています。
        li   $t1, 111
        sw   $t1, 0($t0)        #最初の言葉
        li   $t1, 222
        sw   $t1, 4($t0)        #+4バイト = 次のワード
        li   $t1, 333
        sw   $t1, 8($t0)        #+8バイト

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw は、sw によって以前に書き込まれた同じ 32 ビット値を再構築します。
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
