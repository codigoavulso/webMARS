# 06 - काउंटर के रूप में लूप करें
#
# `$t0` प्रिंट करने वाला अगला नंबर है। `$t1` विशिष्ट ऊपरी सीमा है, इसलिए 11 की सीमा 1 से 10 तक
# प्रिंट करती है।
#
# तुलना प्रत्येक पुनरावृत्ति से पहले चलती है। वृद्धि सीमा की ओर प्रगति करती है, और छलांग जाँच को
# दोहराती है।
#
# सीमा को 1 में बदलें और चलाएँ। निकास शाखा को पहले प्रिंट से पहले लिया जाता है।

        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #गिनती रजिस्टर
        li   $t1, 11            #सीमा

loop:
        # लूप टेस्ट में, $t0 अगला उम्मीदवार है। इसे तभी प्रिंट करें जब यह $t1 से नीचे हो।
        slt  $t2, $t0, $t1      #तुलनित्र
        beq  $t2, $zero, endl   #गिनती सीमा तक पहुंचने पर बाहर निकलें

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #कूदने से पहले काउंटर को अपडेट करना समाप्ति की दिशा में प्रगति की गारंटी देता है।
        addi $t0, $t0, 1        #योजक
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
