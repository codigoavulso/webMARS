#पाठ 06 - एक काउंटर, सॉफ्टवेयर और हार्डवेयर में
#
#THE PROBLEM
#एक हार्डवेयर काउंटर एक रजिस्टर, एक इंक्रीमेंटर और एक है
#तुलनित्र. वही मशीन लिखी हुई कैसी दिखती है
#निर्देश के रूप में?
#
#WHAT THE HARDWARE DOES
#बिल्कुल वे तीन भाग, निर्देश के अनुसार एक: रजिस्टर
#गिनती रखता है, addi वृद्धिकर्ता है, एक शाखा के साथ slt
#वह तुलनित्र है जो दूसरे दौर पर निर्णय लेता है।
#
#THE SOLUTION
#लूप कोई नई अवधारणा नहीं है. यह अनुक्रमिक तर्क वर्तनी है
#बाहर, घड़ी के रूप में पीसी के साथ।
#
#WATCH FOR
#$t0 गिनती रजिस्टर और $t1 सीमा है। आगे बढ़ें
#एक पूर्ण दौर और नाम बताएं कि कौन सी रेखा कौन सा भाग है।
# ==========================================================
        .data
sp:     .asciiz " "
        .text
        .globl main
main:
        li   $t0, 1             #गिनती रजिस्टर
        li   $t1, 11            #सीमा

loop:
        #लूप इनवेरिएंट: $t0 प्रिंट करने के लिए अगला मान है और $t1 से नीचे रहता है।
        slt  $t2, $t0, $t1      #तुलनित्र
        beq  $t2, $zero, endl   #गिनती सीमा तक पहुंचने पर बाहर निकलें

        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        #कूदने से पहले काउंटर को अपडेट करना समाप्ति की दिशा में प्रगति की गारंटी देता है।
        addi $t0, $t0, 1        #योजक
        j    loop

endl:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
