# 10 - ढेर
#
# परंपरा के अनुसार स्टैक निचले पतों की ओर बढ़ता है। दो शब्दों के लिए स्थान आरक्षित करने के लिए
# `$sp` में से 8 घटाएँ।
#
# प्रोग्राम `sw` के साथ दो रजिस्टरों को सहेजता है, उन्हें साफ़ करता है, फिर `lw` के साथ उनके
# मूल्यों को पुनर्स्थापित करता है।
#
# आरक्षण से पहले, दो दुकानों के दौरान और रिलीज के बाद `$sp` देखें। इसका अंतिम मूल्य इसके
# प्रारंभिक मूल्य से मेल खाना चाहिए।

        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #स्टैक नीचे की ओर बढ़ता है, इसलिए आवंटन $sp से घट जाता है।
        addi $sp, $sp, -8       #दो शब्द सुरक्षित रखें
        sw   $t0, 0($sp)        #धक्का
        sw   $t1, 4($sp)

        li   $t0, 0             #रजिस्टरों को बंद करो
        li   $t1, 0

        lw   $t0, 0($sp)        #पॉप
        lw   $t1, 4($sp)
        #प्रत्येक आवंटन संतुलित होना चाहिए ताकि कॉल करने वाले को उसका मूल $sp दिखाई दे।
        addi $sp, $sp, 8        #रिहाई

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
