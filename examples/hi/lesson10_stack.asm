#पाठ 10 - स्टैक एक रजिस्टर और एक ऑफसेट है
#
#THE PROBLEM
#32 रजिस्टर हैं और इन्हें प्रत्येक भाग द्वारा साझा किया जाता है
#कोड. कोई मूल्य तब कहां जाता है जब उसे जीवित रहना चाहिए
#क्या उन रजिस्टरों का पुन: उपयोग किया जाएगा?
#
#WHAT THE HARDWARE DOES
#बिल्कुल भी कुछ खास नहीं. $sp एक साधारण रजिस्टर है
#स्मृति में इंगित करने के लिए होता है, और स्टैक की ओर बढ़ता है
#निम्न पते विशुद्ध रूप से सम्मेलन द्वारा।
#
#THE SOLUTION
#स्थान आरक्षित करना $sp से घटाना है, इसे जारी करना और
#जोड़. पुश और पॉप सिर्फ sw और lw हैं।
#
#WATCH FOR
#दुकानों के बीच रजिस्टरों को जानबूझकर साफ किया जाता है
#और भार, इसलिए मुद्रित मूल्य ही आ सकते हैं
#स्मृति से वापस. $sp को 8 और पीछे जाते हुए देखें।
# ==========================================================
        .data
m1:     .asciiz "restored: "
sp2:    .asciiz " "
        .text
        .globl main
main:
        li   $t0, 7
        li   $t1, 9

        #स्टैक नीचे की ओर बढ़ता है, इसलिए आवंटन $sp से घट जाता है।
        addi $sp, $sp, -8       #दो शब्द सुरक्षित रखें
        sw   $t0, 0($sp)        #धक्का
        sw   $t1, 4($sp)

        li   $t0, 0             #रजिस्टरों को बंद करो
        li   $t1, 0

        lw   $t0, 0($sp)        #पॉप
        lw   $t1, 4($sp)
        #प्रत्येक आवंटन संतुलित होना चाहिए ताकि कॉल करने वाले को उसका मूल $sp दिखाई दे।
        addi $sp, $sp, 8        #रिहाई

        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t0
        li   $v0, 1
        syscall
        la   $a0, sp2
        li   $v0, 4
        syscall
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
