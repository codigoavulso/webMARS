#THE PROBLEM
#किसी निर्णय के लिए एक बिट की आवश्यकता होती है, लेकिन दो 32-बिट संख्याओं की तुलना करना
#एक घटाव है. घटाव विकल्प कैसे बन जाता है?
#
#WHAT THE HARDWARE DOES
#एसएलटी चिन्ह को छोड़कर सब कुछ घटा देता है और फेंक देता है,
#0 या 1 लिखना। फिर शाखा उस बिट को पीसी पर फीड करती है
#तर्क, जो या तो एक ऑफसेट जोड़ता है या पीसी को आगे बढ़ने देता है।
#
#THE SOLUTION
#एक रजिस्टर में तुलना करें, उस रजिस्टर पर शाखा लगाएं। नियंत्रण
#प्रवाह अंकगणित प्लस पीसी पर एक मल्टीप्लेक्सर है।
#
#WATCH FOR
#Slt के बाद, $t2 1 को होल्ड करता है। beq से आगे बढ़ें और PC देखें
#स्टेटस बार में: यह चार से आगे बढ़ने के बजाय छलांग लगाता है।
# ==========================================================
        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ए
        li   $t1, 12            #बी
        #एसएलटी तुलना को एक सामान्य पूर्णांक के रूप में साकार करता है, कभी भी छिपे हुए झंडे के रूप में नहीं।
        slt  $t2, $t0, $t1      #t2 = 1 यदि a < b
        #नोटलेस पर शाखा तभी लगाएं जब वह बूलियन परिणाम शून्य हो।
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
