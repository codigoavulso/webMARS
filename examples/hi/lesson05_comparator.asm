# 05 - तुलनित्र और शाखा
#
# `slt` दो हस्ताक्षरित पूर्णांकों की तुलना करता है और पहला छोटा होने पर 1 लिखता है, या अन्यथा 0
# लिखता है।
#
# 7 और 12 के लिए, `$t2` 1 है, इसलिए `beq` `notless` पर नहीं जाता है और निष्पादन अगले निर्देश तक
# जारी रहता है।
#
# देरी से शाखाएं बंद होने पर, `beq` से आगे बढ़ें और पीसी का निरीक्षण करें। दो इनपुट मानों को
# स्वैप करें और नए गंतव्य की तुलना करें।

        .data
lo:     .asciiz "a is smaller"
hi:     .asciiz "a is not smaller"
        .text
        .globl main
main:
        li   $t0, 7             #ए
        li   $t1, 12            #बी
        #एसएलटी तुलना को एक सामान्य पूर्णांक के रूप में साकार करता है, कभी भी छिपे हुए झंडे के रूप में नहीं।
        slt  $t2, $t0, $t1      #t2 = 1 यदि a < b
        #नोटलेस पर शाखा तभी लगाएं जब वह बूलियन परिणाम शून्य हो।
        beq  $t2, $zero, notless

        la   $a0, lo
        li   $v0, 4
        syscall
        j    done

notless:
        la   $a0, hi
        li   $v0, 4
        syscall

done:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
