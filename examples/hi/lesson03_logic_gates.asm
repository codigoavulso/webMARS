# ==========================================================
#पाठ 03 - 32 बिट्स में लॉजिक गेट
#
#THE PROBLEM
#AND, या और XOR एक-बिट गेट हैं। एक रजिस्टर में 32 बिट होते हैं।
#इतनी चौड़ाई पर गेट का क्या मतलब है?
#
#WHAT THE HARDWARE DOES
#इसमें गेट की 32 प्रतियां एक साथ रखी गई हैं। का बिट 0
#परिणाम प्रत्येक ऑपरेंड के केवल बिट 0 पर निर्भर करता है, बिट 1 पर
#बिट 1, इत्यादि। उनके बीच कोई कैरी यात्रा नहीं करता।
#
#THE SOLUTION
#वह स्वतंत्रता ही मुखौटा को कारगर बनाती है: किसे चुनें
#AND के साथ रखने के लिए बिट्स, OR के साथ एक करने के लिए बाध्य करें, XOR के साथ फ़्लिप करें।
#
#WATCH FOR
#0xCC 11001100 है और मास्क 0x0F 00001111 है। AND रखता है
#निम्न चार बिट्स, या उन्हें सेट करता है, XOR उन्हें फ़्लिप करता है। केवल
#कम निबल कभी भी बदलता है।
# ==========================================================
        .data
ma:     .asciiz "AND keeps the low nibble: "
mo:     .asciiz "OR sets the low nibble:   "
mx:     .asciiz "XOR flips the low nibble: "
        .text
        .globl main
main:
        li   $t0, 204           #0xCC
        li   $t1, 15            #0x0F मुखौटा

        la   $a0, ma
        li   $v0, 4
        syscall
        #AND हर उस स्थिति को साफ़ करता है जहां मास्क में शून्य होता है।
        and  $t2, $t0, $t1
        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mo
        li   $v0, 4
        syscall
        or   $t3, $t0, $t1
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, mx
        li   $v0, 4
        syscall
        #XOR केवल मास्क में लोगों द्वारा चुनी गई स्थिति को टॉगल करता है।
        xor  $t4, $t0, $t1
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
