#THE PROBLEM
#एक रजिस्टर में 32 तार होते हैं, प्रत्येक उच्च या निम्न। कोई तार नहीं है
#ऋण चिह्न के लिए, फिर भी ऋणात्मक संख्याएँ काम करनी चाहिए।
#
#WHAT THE HARDWARE DOES
#यह शीर्ष बिट को एक संकेत के रूप में पढ़ता है, लेकिन एक अलग ध्वज के रूप में नहीं:
#-n को बिट पैटर्न के रूप में संग्रहीत किया जाता है, जो n में जोड़ा जाता है, लपेटता है
#शून्य. प्रत्येक बिट को उलटा करें और एक जोड़ें और यह आपके पास है।
#
#THE SOLUTION
#घटाव के लिए दूसरे सर्किट की आवश्यकता नहीं होती। ए - बी हो जाता है
#ए + (-बी), इसलिए एक योजक दोनों परिचालनों को पूरा करता है।
#
#WATCH FOR
#दोनों हिस्से -5 प्रिंट करते हैं। दूसरा उस तक लंबा रास्ता तय करता है,
#न ही और एडी के साथ, यह दर्शाता है कि उप आंतरिक रूप से क्या करता है।
#0xFFFFFFFB देखने के लिए मानों को हेक्साडेसिमल पर सेट करें।
# ==========================================================
        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #शून्य से घटाने पर ऋण-चिह्न बिट के बिना योगात्मक व्युत्क्रम बनता है।
        li   $t0, 5
        sub  $t1, $zero, $t0    #योजक कार्य करता है
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #न ही $zero के साथ बिटवाइज़ है NOT; एक जोड़ने से दो का पूरक पूरा होता है।
        nor  $t2, $t0, $zero    #सभी बिट्स को उलटा करें
        addi $t2, $t2, 1        #एक जोड़ें
        move $a0, $t2           #ऊपर जैसा ही मान
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
