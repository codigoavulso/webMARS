# 02-दो का पूरक
#
# 32-बिट दो के पूरक में, 5 के बिट्स को उल्टा करने और 1 जोड़ने से -5 का प्रतिनिधित्व उत्पन्न होता
# है।
#
# प्रोग्राम समान मान की गणना दो तरीकों से करता है: शून्य से `sub`, फिर `nor` और `addi`।
#
# दोनों पथ -5 प्रिंट करते हैं। हेक्साडेसिमल में समान बिट्स कैसे दिखते हैं यह देखने के लिए
# रजिस्टरों में `0xFFFFFFFB` का निरीक्षण करें।

        .data
m1:     .asciiz "zero minus 5 = "
m2:     .asciiz "invert bits of 5, add 1 = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        #शून्य से घटाने पर ऋण-चिह्न बिट के बिना योगात्मक व्युत्क्रम बनता है।
        li   $t0, 5
        sub  $t1, $zero, $t0    #योजक कार्य करता है
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m2
        li   $v0, 4
        syscall
        #न ही $zero के साथ बिटवाइज़ है NOT; एक जोड़ने से दो का पूरक पूरा होता है।
        nor  $t2, $t0, $zero    #सभी बिट्स को उलटा करें
        addi $t2, $t2, 1        #एक जोड़ें
        move $a0, $t2           #ऊपर जैसा ही मान
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
