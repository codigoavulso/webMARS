#पाठ 08 - एक शब्द के अंदर बाइट्स, और बाइट क्रम
#
#THE PROBLEM
#एक शब्द चार पते रखता है। कौन सा बाइट सबसे कम काम करता है
#उन पतों का नाम?
#
#WHAT THE HARDWARE DOES
#वह विकल्प बाइट ऑर्डर है, और यह एक वायरिंग निर्णय है
#पूरी मशीन के लिए एक बार। MIPS यहां लिटिल-एंडियन है: द
#सबसे कम महत्वपूर्ण बाइट सबसे निचले पते पर रहता है।
#
#THE SOLUTION
#एक शब्द संग्रहीत करें, फिर उसे एक बार में एक बाइट पढ़ें और छोड़ें
#आदेश आपके लिए प्रश्न का उत्तर देता है।
#
#WATCH FOR
#0x04030201 1 2 3 4 के रूप में वापस आता है। अंत में लिखी गई बाइट
#शाब्दिक पहले पढ़ा जाता है. एलबीयू का प्रयोग एलबी सो ए के बजाय किया जाता है
#127 से ऊपर की बाइट साइन-विस्तारित नहीं है।
# ==========================================================
        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #बाइट 01 सबसे कम महत्वपूर्ण है
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #बाइट ऑफसेट
bloop:
        #लूप संग्रहित शब्द के अंदर ऑफसेट 0, 1, 2 और 3 पर जाता है।
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #प्रभावी पता = आधार पता + वर्तमान बाइट ऑफसेट।
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #अहस्ताक्षरित बाइट
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
