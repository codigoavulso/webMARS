# 08 - बाइट्स और बाइट क्रम
#
# इस सिम्युलेटर की छोटी-छोटी मेमोरी में, किसी शब्द का सबसे कम महत्वपूर्ण बाइट सबसे कम पते पर
# रहता है।
#
# `0x04030201` को एक शब्द के रूप में संग्रहीत करें और 0 से 3 तक के ऑफसेट को बाइट्स के रूप में
# पढ़ें। आउटपुट 1, 2, 3, 4 है।
#
# `0xFF` की कम बाइट आज़माएँ। `lbu` के साथ एक अहस्ताक्षरित लोड 255 देता है, जबकि `lb` के साथ एक
# हस्ताक्षरित लोड -1 देता है।

        .data
cell:   .word 0
m1:     .asciiz "bytes from low address: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell
        li   $t1, 0x04030201    #बाइट 01 सबसे कम महत्वपूर्ण है
        sw   $t1, 0($t0)

        la   $a0, m1
        li   $v0, 4
        syscall

        li   $t2, 0             #बाइट ऑफसेट
bloop:
        #लूप संग्रहित शब्द के अंदर ऑफसेट 0, 1, 2 और 3 पर जाता है।
        slti $t3, $t2, 4
        beq  $t3, $zero, endb

        #प्रभावी पता = आधार पता + वर्तमान बाइट ऑफसेट।
        add  $t4, $t0, $t2
        lbu  $a0, 0($t4)        #अहस्ताक्षरित बाइट
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        addi $t2, $t2, 1
        j    bloop

endb:
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
