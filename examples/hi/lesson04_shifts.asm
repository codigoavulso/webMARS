# 04 - दो की शिफ्ट और शक्तियां
#
# परिणाम फिट होने पर 3 से बायां बदलाव 8 से गुणा हो जाता है। किनारे से हटे हुए बिट्स को हटा दिया
# जाता है।
#
# दाईं ओर, `srl` शून्य से भरता है और `sra` साइन बिट की प्रतिलिपि बनाता है। -16 को 2 से
# स्थानांतरित करने के लिए, क्रमशः 1073741820 और -4 की अपेक्षा करें।
#
# `sra` के साथ -15 आज़माएं। परिणाम -4 है क्योंकि शिफ्ट नीचे की ओर घूमती है; शून्य की ओर
# हस्ताक्षरित डिवीजन राउंड।

        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #केवल 32 परिणाम बिट्स को बरकरार रखते हुए तीन बाईं शिफ्ट को 2^3 से गुणा किया जाता है।
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #विभिन्न आने वाले बिट्स देखने के लिए हेक्साडेसिमल में $t3 और $t4 की तुलना करें।
        sra  $t3, $t2, 2        #चिह्न संरक्षित:-4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #शून्य स्थानांतरित हो गया: बहुत बड़ा सकारात्मक
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
