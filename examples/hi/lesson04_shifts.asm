# ==========================================================
#पाठ 04 - तारों को बदलना, या गुणा करना
#
#THE PROBLEM
#एक सामान्य गुणक सबसे महंगे ब्लॉकों में से एक है
#एक डाटापथ. 8 से गुणा करने पर इतना खर्च नहीं होना चाहिए.
#
#WHAT THE HARDWARE DOES
#एक बदलाव बिल्कुल भी अंकगणित नहीं है: यह वही बिट्स पढ़ा जाता है
#विभिन्न तारों से. n द्वारा बायीं ओर खिसकने पर 2^n का गुणन होता है
#और लागत केवल रूटिंग की है।
#
#THE SOLUTION
#दो की शक्तियाँ शिफ्ट हो जाती हैं। दो दाएँ बदलावों पर ध्यान दें: srl
#शीर्ष पर शून्य फ़ीड करता है, एसआरए साइन बिट की प्रतिलिपि बनाता है, इसलिए केवल
#एसआरए एक ऋणात्मक संख्या को सही ढंग से विभाजित करता है।
#
#WATCH FOR
#-16 >> 2 एसआरए के साथ -4 देता है लेकिन एसआरएल के साथ एक बड़ा सकारात्मक परिणाम देता है। द
#बिट्स समान रूप से चले गए; केवल शीर्ष पर जो दर्ज किया गया है वह भिन्न है।
# ==========================================================
        .data
m1:     .asciiz "5 << 3 = "
m2:     .asciiz "-16 >> 2 arithmetic = "
m3:     .asciiz "-16 >> 2 logical    = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall
        li   $t0, 5
        #केवल 32 परिणाम बिट्स को बरकरार रखते हुए तीन बाईं शिफ्ट को 2^3 से गुणा किया जाता है।
        sll  $t1, $t0, 3        # 5 * 8
        move $a0, $t1
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $t2, -16

        la   $a0, m2
        li   $v0, 4
        syscall
        #विभिन्न आने वाले बिट्स देखने के लिए हेक्साडेसिमल में $t3 और $t4 की तुलना करें।
        sra  $t3, $t2, 2        #चिह्न संरक्षित:-4
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        la   $a0, m3
        li   $v0, 4
        syscall
        srl  $t4, $t2, 2        #शून्य स्थानांतरित हो गया: बहुत बड़ा सकारात्मक
        move $a0, $t4
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
