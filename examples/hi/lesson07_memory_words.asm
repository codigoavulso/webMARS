# 07 - स्मृति में शब्द
#
# मेमोरी पते बाइट्स की गिनती करते हैं। प्रत्येक शब्द चार बाइट्स घेरता है, इसलिए `lw` और `sw`
# यहां ऑफसेट 0, 4 और 8 का उपयोग करते हैं।
#
# एक शब्द पता चार का गुणज होना चाहिए. 4 के बजाय ऑफसेट 1 का उपयोग करने से इस प्रोग्राम में संरेखण
# अपवाद उत्पन्न होता है।
#
# स्टोर्स के बाद, डेटा सेगमेंट में `cell` देखें। तीन आसन्न शब्दों में 111, 222 और 333 होना
# चाहिए।

        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #आधार पता

        #नीचे दिया गया प्रत्येक ऑफसेट $t0 से संबंधित है और शब्द-संरेखित रहता है।
        li   $t1, 111
        sw   $t1, 0($t0)        #पहला शब्द
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 बाइट्स = अगला शब्द
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 बाइट्स

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw उन्हीं 32-बिट मानों का पुनर्निर्माण करता है जो पहले sw द्वारा लिखे गए थे।
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
