#पाठ 07 - स्मृति में शब्द, और पते चार से क्यों बढ़ जाते हैं
#
#THE PROBLEM
#मेमोरी को एक समय में एक बाइट संबोधित किया जाता है, लेकिन एक रजिस्टर रखता है
#चार बाइट्स. एक एकल पता वास्तव में क्या चुनता है?
#
#WHAT THE HARDWARE DOES
#lw और sw एक ही एक्सेस में लगातार चार बाइट्स ले जाते हैं
#शब्द चार पते के अंतर पर बैठते हैं। के निम्न दो बिट्स
#पता शून्य होना चाहिए: वह संरेखण ही देता है
#हार्डवेयर एक चक्र में पूरा शब्द लाता है।
#
#THE SOLUTION
#पते का अंकगणित बाइट्स में किया जाता है, इसलिए अनुक्रमणिका शब्दों में
#हमेशा चार से मापा जाता है।
#
#WATCH FOR
#असेंबल करें, फिर डेटा सेगमेंट को 0x10010000 पर खोलें। द
#एक पंक्ति के आसन्न कॉलम में तीन मान दिखाई देते हैं।
# ==========================================================
        .data
cell:   .word 0, 0, 0
m1:     .asciiz "read back: "
sp:     .asciiz " "
        .text
        .globl main
main:
        la   $t0, cell          #आधार पता

        #नीचे दिया गया प्रत्येक ऑफसेट $t0 से संबंधित है और शब्द-संरेखित रहता है।
        li   $t1, 111
        sw   $t1, 0($t0)        #पहला शब्द
        li   $t1, 222
        sw   $t1, 4($t0)        #+4 बाइट्स = अगला शब्द
        li   $t1, 333
        sw   $t1, 8($t0)        #+8 बाइट्स

        la   $a0, m1
        li   $v0, 4
        syscall

        #lw उन्हीं 32-बिट मानों का पुनर्निर्माण करता है जो पहले sw द्वारा लिखे गए थे।
        lw   $a0, 0($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 4($t0)
        li   $v0, 1
        syscall
        la   $a0, sp
        li   $v0, 4
        syscall

        lw   $a0, 8($t0)
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
