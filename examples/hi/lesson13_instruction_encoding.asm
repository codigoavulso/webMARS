# 13 - एक निर्देश एक संख्या है
#
# टेक्स्ट सेगमेंट में कोड कॉलम को इकट्ठा करें और उसका निरीक्षण करें। प्रत्येक मूल निर्देश एक
# 32-बिट शब्द है जो फ़ील्ड में विभाजित है।
#
# दो `add` निर्देशों की तुलना करें। ऑपरेशन फ़ील्ड मेल खाते हैं, जबकि रजिस्टर फ़ील्ड विभिन्न
# ऑपरेंड को एन्कोड करते हैं।
#
# `addi` में, निम्न 16 बिट तत्काल 100 रखते हैं, जो `0x0064` है। इसे 101 में बदलें और परिवर्तन
# देखने के लिए पुनः संयोजन करें।

        .text
        .globl main
main:
        #असेंबली के बाद कोड कॉलम का निरीक्षण करें: ये निमोनिक्स टेक्स्ट के रूप में संग्रहीत नहीं हैं।
        add  $t0, $t1, $t2      #आर-प्रकार: ऑपकोड, आरएस, आरटी, आरडी, फ़ंक्शन
        add  $t3, $t4, $t5      #एक ही आकार, अलग-अलग रजिस्टर
        addi $t0, $t1, 100      #I-टाइप: स्थिरांक शब्द में है
        sll  $t0, $t1, 4        #शिफ्ट राशि का अपना क्षेत्र होता है
        j    tail               #जे-प्रकार: एक पता, रजिस्टर नहीं
tail:
        #निष्पादन से पहले ली का विस्तार स्वयं किया जाता है; प्रोसेसर केवल एन्कोडेड शब्द देखता है।
        li   $v0, 10
        syscall
