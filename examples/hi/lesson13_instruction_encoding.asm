#पाठ 13 - एक निर्देश एक संख्या है
#
#THE PROBLEM
#प्रोसेसर मेमोरी से शब्द लाता है। कोड में रहता है
#स्मृति भी. तो क्या एक निर्देश को ए से अलग करता है?
#डेटा का टुकड़ा?
#
#WHAT THE HARDWARE DOES
#कुछ भी नहीं, जिसके परे शब्द को रजिस्टर में लोड किया गया है। द
#पीसी उन शब्दों का चयन करता है जो डिकोडर पर जाते हैं; lw शब्दों का चयन करता है
#वह रजिस्टर फ़ाइल पर जाएँ। बिट्स एक ही तरह के हैं.
#
#THE SOLUTION
#एन्कोडिंग को सीधे पढ़ें. इकट्ठा करो और खोलो
#मुख्य > निष्पादित करें: कोड कॉलम प्रत्येक निर्देश को इस प्रकार दिखाता है
#यह वास्तव में 32-बिट शब्द है।
#
#WATCH FOR
#यह पाठ जानबूझकर कुछ भी प्रिंट नहीं करता - आउटपुट है
#पाठ खंड स्वयं. दो ऐड की तुलना करें: समान ऑपकोड और
#फ़ंक्शन फ़ील्ड, विभिन्न रजिस्टर नंबर। फिर खोजें
#Addi शब्द के अंदर शाब्दिक 100।
# ==========================================================
        .text
        .globl main
main:
        #असेंबली के बाद कोड कॉलम का निरीक्षण करें: ये निमोनिक्स टेक्स्ट के रूप में संग्रहीत नहीं हैं।
        add  $t0, $t1, $t2      #आर-प्रकार: ऑपकोड, आरएस, आरटी, आरडी, फ़ंक्शन
        add  $t3, $t4, $t5      #एक ही आकार, अलग-अलग रजिस्टर
        addi $t0, $t1, 100      #I-टाइप: स्थिरांक शब्द में है
        sll  $t0, $t1, 4        #शिफ्ट राशि का अपना क्षेत्र होता है
        j    tail               #जे-प्रकार: एक पता, रजिस्टर नहीं
tail:
        #निष्पादन से पहले ली का विस्तार स्वयं किया जाता है; प्रोसेसर केवल एन्कोडेड शब्द देखता है।
        li   $v0, 10
        syscall
