#पाठ 01 - रजिस्टर और तत्काल मूल्य
#
#THE PROBLEM
#ALU में दो इनपुट पोर्ट हैं और दोनों इससे जुड़े हैं
#फ़ाइल पंजीकृत करें. स्रोत में लिखी गई संख्या a में नहीं है
#रजिस्टर करें, इसलिए यह सीधे उन बंदरगाहों तक नहीं पहुंच सकता।
#
#WHAT THE HARDWARE DOES
#अनुदेश शब्द के अंदर ही तत्काल यात्रा होती है।
#Addi में 16-बिट फ़ील्ड है; ली एक सुविधा है
#असेंबलर एक या दो वास्तविक निर्देशों में विस्तारित होता है।
#
#THE SOLUTION
#पहले स्थिरांक को एक रजिस्टर में दर्ज करें, फिर ALU दें
#दो रजिस्टर पढ़ें और तीसरा लिखें।
#
#WATCH FOR
#प्रति पंक्ति एक बार कदम रखें और $t0, $t1 और $t2 का अनुसरण करें
#रजिस्टर पैनल. केवल तीसरी पंक्ति ALU को छूती है।
# ==========================================================
        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls सेवा चयनकर्ता के रूप में $v0 और पहले तर्क के रूप में $a0 का उपयोग करते हैं।
        la   $a0, lbl
        li   $v0, 4
        syscall

        #ली एक छद्म निर्देश है; असेंबल से पता चलता है कि यह कौन सा वास्तविक निर्देश बन जाता है।
        li   $t0, 12            #तत्काल -> रजिस्टर करें
        li   $t1, 30            #तत्काल -> रजिस्टर करें
        add  $t2, $t0, $t1      #ALU दो रजिस्टर पढ़ता है

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
