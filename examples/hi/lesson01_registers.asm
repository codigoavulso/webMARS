# 01 - रजिस्टर एवं तत्काल
#
# तत्काल निर्देश में एन्कोड किया गया है। इकट्ठा करें और जांचें कि प्रत्येक `li` कौन सा बुनियादी
# निर्देश बनता है।
#
# दो भार और जोड़ के माध्यम से कदम रखें। रजिस्टरों में, `$t0 = 12`, `$t1 = 30` और `$t2 = 42` का
# पालन करें।
#
# 30 को `0x12345678` से बदलने का प्रयास करें और पुनः संयोजन करें। बड़े स्थिरांक को एक से अधिक
# बुनियादी निर्देशों की आवश्यकता होती है।

        .data
lbl:    .asciiz "12 + 30 = "
        .text
        .globl main
main:
        #Syscalls सेवा चयनकर्ता के रूप में $v0 और पहले तर्क के रूप में $a0 का उपयोग करते हैं।
        la   $a0, lbl
        li   $v0, 4
        syscall

        #ली एक छद्म निर्देश है; असेंबल से पता चलता है कि यह कौन सा वास्तविक निर्देश बन जाता है।
        li   $t0, 12
        li   $t1, 30
        add  $t2, $t0, $t1      # राशि को एक अलग रजिस्टर में लिखा जाता है।

        move $a0, $t2
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
