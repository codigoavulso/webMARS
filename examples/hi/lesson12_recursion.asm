# 12 - रिकर्सन और फ्रेम
#
# एक पुनरावर्ती कॉल `$ra` को अधिलेखित कर देती है और अपने तर्क के लिए `$a0` का उपयोग करती है। कॉल
# करने से पहले दोनों मान सहेजें।
#
# 5 से 1 तक प्रत्येक मान के लिए `fact` में कदम रखें। प्रत्येक कॉल आठ बाइट्स आरक्षित करती है,
# जिसमें 1 लौटाने वाली कॉल भी शामिल है।
#
# वापसी पथ देखने के लिए `mul` पर एक ब्रेकप्वाइंट सेट करें। प्रत्येक कॉल अपने स्वयं के तर्क को
# पुनः लोड करती है, गुणा करती है और अपना फ्रेम जारी करती है।

        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- पूर्णांक तथ्य(पूर्णांक n) ----
fact:
        #प्रत्येक आमंत्रण में एक अलग आठ-बाइट फ्रेम होता है।
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #इस कॉल का वापसी पता
        sw   $a0, 4($sp)        #यह कॉल एन

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #आधार मामला: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (एन-1)!
        lw   $a0, 4($sp)        #हमारा फिर से
        mul  $v0, $v0, $a0

factend:
        # इस कॉल के फ़्रेम को जारी करने से पहले सहेजे गए रिटर्न पते को पुनर्स्थापित करें।
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
