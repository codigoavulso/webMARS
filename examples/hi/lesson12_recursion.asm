#पाठ 12 - रिकर्सन को प्रति कॉल एक फ्रेम की आवश्यकता होती है
#
#THE PROBLEM
#एक पुनरावर्ती कॉल $ra और तर्क रजिस्टर को अधिलेखित कर देती है।
#तब बाहरी कॉल के पास वापस लौटने का कोई रास्ता नहीं होता और न ही पता चलता कि यह क्या है
#अपना एन था.
#
#WHAT THE HARDWARE DOES
#यह एक $ra प्रदान करता है, उनका ढेर नहीं। कुछ भी नहीं बचा
#स्वचालित रूप से; यदि कोड इसे सहेजता नहीं है, तो यह चला जाता है।
#
#THE SOLUTION
#प्रत्येक सक्रियण स्टैक पर एक फ़्रेम खोलता है, उसे रखता है
#कॉल के बाद भी इसकी आवश्यकता होगी, और रास्ते में इसे पुनर्स्थापित कर देगा
#बाहर. स्टैक की गहराई रिकर्सन गहराई है।
#
#WATCH FOR
#मल पर एक ब्रेकप्वाइंट सेट करें और $sp को 8 प्रति से नीचे आते हुए देखें
#स्तर. n की पाँच सहेजी गई प्रतियाँ ही इसे बनाती हैं
#रास्ते में गुणन संभव।
# ==========================================================
        .data
m1:     .asciiz "5! = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 5
        jal  fact

        move $a0, $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- पूर्णांक तथ्य(पूर्णांक n) ----
fact:
        #प्रत्येक आमंत्रण में एक अलग आठ-बाइट फ्रेम होता है।
        addi $sp, $sp, -8
        sw   $ra, 0($sp)        #इस कॉल का वापसी पता
        sw   $a0, 4($sp)        #यह कॉल एन

        li   $t0, 2
        slt  $t1, $a0, $t0
        beq  $t1, $zero, recurse
        li   $v0, 1             #आधार मामला: 0! = 1! = 1
        j    factend

recurse:
        addi $a0, $a0, -1
        jal  fact               #$v0 = (एन-1)!
        lw   $a0, 4($sp)        #हमारा फिर से
        mul  $v0, $v0, $a0

factend:
        #कैली स्थिति को पुनर्स्थापित करें और प्रविष्टि पर आवंटित फ़्रेम को बिल्कुल हटा दें।
        lw   $ra, 0($sp)
        addi $sp, $sp, 8
        jr   $ra
