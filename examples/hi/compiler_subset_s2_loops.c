int main(void) {
  //C0-S2- या उच्चतर की आवश्यकता है: लूप के लिए, ब्रेक/जारी रखें, और ++/--।
  int sum = 0;   //एक बार संकलित होने के बाद संचायक एक रजिस्टर में रहता है

  for (int i = 0; i < 10; i++) {   //लूप के लिए तुलना प्लस बैकवर्ड शाखा बन जाती है
    if ((i % 2) == 0) continue;   //शरीर को छोड़ते हुए, वृद्धि के लिए कूदना जारी रखें
    if (i > 7) break;   //लूप के अंत से पहले ब्रेक जंप करता है
    sum += i;
  }

  int down = 3;
  down--;   //पोस्ट-डिक्रीमेंट और प्री-इंक्रीमेंट एक ही ऐड में संकलित होते हैं
  int up = 3;
  ++up;

  //अपेक्षित आउटपुट: 16 2 4
  print_int(sum);
  print_char(32);
  print_int(down);
  print_char(32);
  print_int(up);
  print_char(10);
  return 0;
}
