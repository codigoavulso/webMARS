# 09 - किसी सारणी को अनुक्रमित करना
#
# प्रत्येक सरणी तत्व चार बाइट्स रखता है। इसके बाइट ऑफसेट की गणना करने के लिए सूचकांक को दो से
# बाईं ओर खिसकाएँ।
#
# अनुक्रम `sll`, `add`, `lw` का पालन करें: सूचकांक को स्केल करें, आधार पता जोड़ें और तत्व लोड
# करें।
#
# सूचकांक 2 पर, `$t5` 8 है और `$t6` मान 30 को इंगित करता है। पाँच तत्वों का योग 150 होता है।

        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #आधार
        li   $t1, 0             #मैं
        li   $t2, 5             #लंबाई
        li   $t3, 0             #संचायक

sum:
        #लूप अपरिवर्तनीय: $t3 गिरफ्तारी [0] से गिरफ्तारी [i-1] का योग है।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #मैं * 4 बाइट्स
        add  $t6, $t0, $t5      #आधार + स्केल्ड इंडेक्स
        #$t6 अब बिल्कुल एक तत्व का नाम बताता है; lw अपना 32-बिट मान प्राप्त करता है।
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
