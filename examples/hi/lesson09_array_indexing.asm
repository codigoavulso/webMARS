#THE PROBLEM
#एक लोड निर्देश एक आधार रजिस्टर और एक स्थिरांक प्रदान करता है
#ऑफसेट और कुछ नहीं। तो जब केवल मैं ही हूं तो a[i] तक कैसे पहुंचा जा सकता है
#रन टाइम पर जाना जाता है, एक रजिस्टर में बैठे?
#
#WHAT THE HARDWARE DOES
#यह रजिस्टर में जो कुछ भी है, उसमें आधार जोड़ता है। सूचकांक
#इसलिए यह पहले से ही बाइट्स में होना चाहिए, तत्वों में नहीं।
#
#THE SOLUTION
#तत्व आकार के आधार पर सूचकांक को स्केल करें, फिर जोड़ें। चार-बाइट के लिए
#शब्द जो स्केलिंग दो द्वारा छोड़ी गई एक शिफ्ट है, जिसकी लागत होती है
#कुछ नहीं.
#
#WATCH FOR
#तीन पंक्तियाँ sll, add, lw हैं जिन्हें a[i] संकलित करता है।
#एक पुनरावृत्ति से गुजरें और $t5 और $t6 पढ़ें।
# ==========================================================
        .data
arr:    .word 10, 20, 30, 40, 50
m1:     .asciiz "sum = "
        .text
        .globl main
main:
        la   $t0, arr           #आधार
        li   $t1, 0             #मैं
        li   $t2, 5             #लंबाई
        li   $t3, 0             #संचायक

sum:
        #लूप अपरिवर्तनीय: $t3 गिरफ्तारी [0] से गिरफ्तारी [i-1] का योग है।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, ends

        sll  $t5, $t1, 2        #मैं * 4 बाइट्स
        add  $t6, $t0, $t5      #आधार + स्केल्ड इंडेक्स
        #$t6 अब बिल्कुल एक तत्व का नाम बताता है; lw अपना 32-बिट मान प्राप्त करता है।
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7

        addi $t1, $t1, 1
        j    sum

ends:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
