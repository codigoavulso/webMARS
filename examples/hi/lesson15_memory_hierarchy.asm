# 15 - कदम बढ़ने से गति क्यों बदल जाती है?
#
# दोनों लूप एक ही सरणी का उपयोग करते हैं। पहला सभी 256 शब्दों को पढ़ता है; दूसरा प्रत्येक 16वाँ
# शब्द पढ़ता है, जिससे केवल 16 भार बनते हैं।
#
# 16 शब्दों के कैश ब्लॉक के साथ, अनुक्रमिक रीड्स प्रत्येक प्राप्त ब्लॉक का पुन: उपयोग कर सकते
# हैं। दूसरा लूप प्रत्येक लोड पर एक नए ब्लॉक की ओर बढ़ता है।
#
# सिम्युलेटर को MIPS से जोड़ें, «सक्षम» चुनें और ब्लॉक का आकार 16 वर्ड रखें।
# पहले लूप का निरीक्षण करने के लिए `far` पर ब्रेकपॉइंट के साथ डेटा कैश सिम्युलेटर का उपयोग करें।
# दूसरा लूप चलाने से पहले वहां कैश आँकड़े रीसेट करें, और हिट दरों की तुलना करें।

        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
# अनुक्रमिक पास: सभी 256 शब्द।
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #अनुक्रमिक अनुक्रमणिका आगे बढ़ने से पहले प्रत्येक कैश ब्लॉक से शब्दों का पुन: उपयोग करती हैं।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

# स्ट्राइड पास: हर सोलह शब्दों में एक लोड।
        li   $t1, 0
        li   $t3, 0
far:
        # अगला पता 64 बाइट्स दूर है: प्रत्येक चार बाइट्स पर सोलह शब्द।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
