# ==========================================================
#पाठ 15 - कदम बढ़ने से गति क्यों बदल जाती है?
#
#THE PROBLEM
#नीचे दिए गए दो लूप एक ही सरणी को पढ़ते हैं और वही कार्य करते हैं
#भार की संख्या. वास्तविक मशीन पर कोई बहुत धीमी होती है। द
#निर्देश संख्या इसकी व्याख्या नहीं कर सकती।
#
#WHAT THE HARDWARE DOES
#स्मृति एक भी शब्द नहीं बोलती। एक चूक से संपूर्ण मिलता है
#ब्लॉक करें, यह शर्त लगाते हुए कि पड़ोसी शब्द जल्द ही वांछित होंगे।
#किसी का एक कदम उस शर्त को एकत्र करता है; सोलह भुगतान का एक कदम
#एक ब्लॉक के लिए और उसका एक शब्द पढ़ता है।
#
#THE SOLUTION
#कोड में कुछ भी नहीं बदलता. स्थानीयता की संपत्ति है
#एक्सेस पैटर्न, और यह वह पैटर्न है जिसे निश्चित किया जाना चाहिए।
#
#WATCH FOR
#टूल्स > डेटा कैश सिम्युलेटर खोलें, MIPS से कनेक्ट दबाएँ,
#फिर चलाओ. दो लूपों की हिट दर की तुलना करें। दोनों योग
#0 प्रिंट करें क्योंकि सरणी शून्य है - संख्या नहीं है
#यहाँ बिंदु, हिट दर है।
# ==========================================================
        .data
buf:    .word 0:256
m1:     .asciiz "stride 1 sum = "
m2:     .asciiz "stride 16 sum = "
        .text
        .globl main
main:
#---- प्रत्येक ब्लॉक का प्रत्येक शब्द ----
        la   $t0, buf
        li   $t1, 0
        li   $t2, 256
        li   $t3, 0
near:
        #अनुक्रमिक अनुक्रमणिका आगे बढ़ने से पहले प्रत्येक कैश ब्लॉक से शब्दों का पुन: उपयोग करती हैं।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endnear
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 1
        j    near
endnear:
        la   $a0, m1
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall

#---- प्रति ब्लॉक एक शब्द, सोलह शब्द अलग ----
        li   $t1, 0
        li   $t3, 0
far:
        #प्रति पुनरावृत्ति में 16 स्किप्स 64 बाइट्स जोड़ना: आमतौर पर एक संपूर्ण कैश ब्लॉक।
        slt  $t4, $t1, $t2
        beq  $t4, $zero, endfar
        sll  $t5, $t1, 2
        add  $t6, $t0, $t5
        lw   $t7, 0($t6)
        add  $t3, $t3, $t7
        addi $t1, $t1, 16
        j    far
endfar:
        la   $a0, m2
        li   $v0, 4
        syscall
        move $a0, $t3
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
