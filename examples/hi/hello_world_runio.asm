#रन I/O के लिए हेलो वर्ल्ड
#एक साधारण संदेश प्रिंट करता है और बाहर निकल जाता है।
#यह डेटा/टेक्स्ट स्प्लिट और सिस्कल कन्वेंशन का सबसे छोटा उदाहरण है।

.data
#.asciiz syscall 4 के लिए आवश्यक शून्य टर्मिनेटर के बाद वर्णों को संग्रहीत करता है।
msg: .asciiz "Hello, webMARS! Run I/O is working.\n"

.text
main:
  #$v0 में प्रिंट-स्ट्रिंग (4) का चयन करें और $a0 में स्ट्रिंग एड्रेस पास करें।
  li $v0, 4
  la $a0, msg
  syscall

  #बाहर निकलें (10) सिम्युलेटेड प्रोग्राम को सफाई से रोक देता है।
  li $v0, 10
  syscall
