# ==========================================================
#पाठ 11 - किसी फ़ंक्शन को कॉल करना
#
#THE PROBLEM
#दिनचर्या में शामिल होना आसान है। वापस पाना नहीं है, क्योंकि
#एक ही दिनचर्या को कई स्थानों से बुलाया जा सकता है और
#हर बार वापसी का पता अलग-अलग होता है।
#
#WHAT THE HARDWARE DOES
#जल एक निर्देश में दो काम करता है: यह संग्रहीत करता है
#$ra में निम्नलिखित निर्देश का पता, फिर कूदता है। जूनियर
#रजिस्टर में जो कुछ भी है उस पर कूद जाता है, इसलिए जूनियर $ra वापस आ जाता है।
#
#THE SOLUTION
#बाकी सब कुछ सहमति है, सर्किटरी नहीं: तर्क
#$a0..$a3, परिणाम $v0 होता है। परंपरा और संहिता को तोड़ें
#अभी भी असेंबल होता है - यह बस इंटरऑपरेट करना बंद कर देता है।
#
#WATCH FOR
#जल पर कदम रखें और $ra पढ़ें। इसकी तुलना पते से करें
#टेक्स्ट सेगमेंट में कॉल के बाद लाइन का।
# ==========================================================
        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #पहला तर्क
        li   $a1, 42            #दूसरा तर्क
        #जल एक आर्किटेक्चरल ऑपरेशन में नियंत्रण प्रवाह और $ra दोनों को बदलता है।
        jal  maxof              #$ra = अगली पंक्ति का पता

        move $a0, $v0           #परिणाम वापस आया $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #मैक्सऑफ़ एक लीफ फ़ंक्शन है, इसलिए यह स्टैक पर $ra को सहेजे बिना वापस आ सकता है।
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
