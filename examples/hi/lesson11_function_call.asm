# 11 - किसी फ़ंक्शन को कॉल करना
#
# विलंबित शाखाओं को बंद करके दौड़ें। `jal` फ़ंक्शन पर जाता है और अगले निर्देश का पता `$ra` में
# डालता है।
#
# कॉलिंग कन्वेंशन `$a0` और `$a1` में 17 और 42 पास करता है। फ़ंक्शन `$v0` में बड़ा मान लौटाता है।
#
# कॉल में कदम रखें, `jal` के बाद के पते के साथ `$ra` की तुलना करें, फिर कॉल करने वाले के पास
# `jr $ra` का अनुसरण करें।

        .data
m1:     .asciiz "max(17, 42) = "
        .text
        .globl main
main:
        la   $a0, m1
        li   $v0, 4
        syscall

        li   $a0, 17            #पहला तर्क
        li   $a1, 42            #दूसरा तर्क
        jal  maxof

        move $a0, $v0           #परिणाम वापस आया $v0
        li   $v0, 1
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall

#---- int maxof(int a, int b) ----
maxof:
        #मैक्सऑफ़ एक लीफ फ़ंक्शन है, इसलिए यह स्टैक पर $ra को सहेजे बिना वापस आ सकता है।
        slt  $t0, $a0, $a1
        beq  $t0, $zero, keepa
        move $v0, $a1
        jr   $ra
keepa:
        move $v0, $a0
        jr   $ra
