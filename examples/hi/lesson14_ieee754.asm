# ==========================================================
#पाठ 14 - 32 बिट्स में वास्तविक संख्याएँ
#
#THE PROBLEM
#3.5 का पूर्णांक रजिस्टर में कोई स्थान नहीं है। कहाँ होता है
#भिन्नात्मक भाग जाओ, और एक बहुत बड़ी संख्या कैसे संग्रहित की जाती है
#बहुत छोटे समान 32 बिट्स में?
#
#WHAT THE HARDWARE DOES
#IEEE-754 शब्द को तीन क्षेत्रों में विभाजित करता है: एक साइन बिट,
#आठ घातांक बिट्स और तेईस अंश बिट्स। द
#घातांक बाइनरी बिंदु को स्लाइड करता है, यही कारण है कि प्रारूप है
#फ़्लोटिंग पॉइंट कहा जाता है।
#
#THE SOLUTION
#एक अलग रजिस्टर फ़ाइल ($f0..$f31) और एक अलग योजक
#इन मूल्यों को संभालें, यही कारण है कि निमोनिक्स भिन्न हैं:
#लोड करने के लिए lwc1, जोड़ने के लिए add.s, प्रिंट करने के लिए syscall 2।
#
#WATCH FOR
#टूल्स > फ़्लोटिंग पॉइंट रिप्रेजेंटेशन खोलें और 3.5 दर्ज करें।
#तीन फ़ील्ड देखें, फिर जांचें कि 4.75 सटीक है -
#0.1 के विपरीत, जिसका कोई परिमित बाइनरी अंश नहीं है।
# ==========================================================
        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:
        #पूर्णांक पते अभी भी डेटा का पता लगाते हैं; lwc1 अपने बिट्स को COP1 में ले जाता है।
        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU रजिस्टर फ़ाइल में
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU योजक

        #Syscall 2 विशेष रूप से $f12 में अपने फ्लोट तर्क की अपेक्षा करता है।
        mov.s $f12, $f4
        li   $v0, 2             #प्रिंट फ्लोट
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
