# 14 - 32 बिट्स में वास्तविक संख्याएँ
#
# एकल-परिशुद्धता फ्लोट में एक साइन बिट, आठ एक्सपोनेंट बिट्स और 23 अंश बिट्स होते हैं।
#
# `lwc1` बिट पैटर्न को फ़्लोटिंग-पॉइंट रजिस्टर में कॉपी करता है। फिर `add.s` 3.5 और 1.25 जोड़कर
# 4.75 प्राप्त करता है।
#
# फ़्लोटिंग पॉइंट प्रतिनिधित्व टूल में 4.75 और 0.1 के एन्कोडिंग की तुलना करें। 4.75 सटीक है; 0.1
# को पूर्णांकित करने की आवश्यकता है।

        .data
a:      .float 3.5
b:      .float 1.25
m1:     .asciiz "3.5 + 1.25 = "
        .text
        .globl main
main:

        la   $a0, m1
        li   $v0, 4
        syscall

        la   $t0, a
        lwc1 $f0, 0($t0)        #FPU रजिस्टर फ़ाइल में
        la   $t0, b
        lwc1 $f2, 0($t0)
        add.s $f4, $f0, $f2     #FPU योजक

        #Syscall 2 विशेष रूप से $f12 में अपने फ्लोट तर्क की अपेक्षा करता है।
        mov.s $f12, $f4
        li   $v0, 2             #प्रिंट फ्लोट
        syscall
        li   $v0, 11
        li   $a0, 10
        syscall
        li   $v0, 10
        syscall
